#!/usr/bin/env python3
"""Generate the Buff HUD debuff badge overlays and embed them in the DLL source (stdlib only, deterministic).

Several hostile spells share one vanilla icon (a launcher grenade and its hand grenade, tier 1-4 of a droid device). The Buff HUD
draws the vanilla icon and then one of these transparent 64x64 overlays on top, so each variant reads as its own icon while the
only art we ship is our own (no modified game textures in the repo). Which spell gets which badge: DebuffIconTable.inc `badge`
(scripts/gen_debuff_icon_table.py).

Writes patch_manager_mods/buff_duration_hud_src/BadgeIconTex.inc (uncompressed 32-bit TGA, same format as PoisonIconTex.inc):
  bh_badge_launch   three warm speed lines trailing to the lower left, outside the grenade sphere (launched grenade)
  bh_badge_t2..t4   2-4 upright gold bars side by side in the upper right, dark rim (tier II-IV, reads like the Roman numeral)
  kBadgeTex[] / kBadgeTexCount   embtex::Tex table in that order (index 0 = launch, 1..3 = tier 2..4)

  (no args)  write the .inc
  --check    regenerate in memory and compare with the existing .inc (exit 0 identical, 1 otherwise)
  --png DIR  also write one preview PNG per badge (needs Pillow; the .inc itself is stdlib only)
"""
import argparse
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_shared_icons import tga32   # same TGA writer as GearIconTex.inc / PoisonIconTex.inc  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
INC = REPO / "patch_manager_mods/buff_duration_hud_src/BadgeIconTex.inc"
N = 64
SS = 4   # supersample per axis

STREAK_DARK, STREAK_CORE = (16, 12, 8), (255, 222, 150)
BAR_RIM, BAR_LIGHT, BAR_DEEP = (18, 14, 8), (255, 226, 140), (185, 136, 45)   # gold runs light (left) -> deep (right) across each bar


def _seg(px, py, ax, ay, bx, by):
    """(distance to segment AB, t along it 0..1)."""
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - ax - t * dx, py - ay - t * dy), t


def _over(dst, rgb, a):
    """Premultiplied-free 'over' of (rgb, a) onto dst = [r, g, b, a] (straight alpha)."""
    a = max(0.0, min(1.0, a))
    if a <= 0:
        return dst
    na = a + dst[3] * (1 - a)
    return [(rgb[k] * a + dst[k] * dst[3] * (1 - a)) / na for k in range(3)] + [na]


# travel up-right; three lines offset across the travel direction, heads just outside the sphere rim (r ~21 around 32,32)
UX, UY, PX, PY = 0.7071, -0.7071, 0.7071, 0.7071
STREAKS = [(-7.5, 11.0), (0.0, 16.0), (7.5, 11.0)]


def launch(x, y):
    c = [0.0, 0.0, 0.0, 0.0]
    for off, ln in STREAKS:
        hx, hy = 32 - UX * 24 + PX * off, 32 - UY * 24 + PY * off
        d, t = _seg(x, y, hx - UX * ln, hy - UY * ln, hx, hy)
        c = _over(c, STREAK_DARK, max(0.0, min(1.0, 2.9 - d)) * (0.2 + 0.7 * t))
        c = _over(c, STREAK_CORE, max(0.0, min(1.0, 1.6 - d)) * (0.1 + 0.9 * t))
    return c


def _rrect(px, py, x0, y0, x1, y1, r):
    """Signed distance to a rounded rectangle (negative inside)."""
    qx = abs(px - (x0 + x1) / 2) - ((x1 - x0) / 2 - r)
    qy = abs(py - (y0 + y1) / 2) - ((y1 - y0) / 2 - r)
    return math.hypot(max(qx, 0.0), max(qy, 0.0)) + min(max(qx, qy), 0.0) - r


def tier(n):
    bars = [(57.0 - k * 5.5, 3.0, 60.5 - k * 5.5, 15.0) for k in range(n)]   # rightmost first, growing to the left
    def f(x, y):
        c = [0.0, 0.0, 0.0, 0.0]
        for x0, y0, x1, y1 in bars:
            d = _rrect(x, y, x0, y0, x1, y1, 1.0)
            c = _over(c, BAR_RIM, 1.2 - d)
            t = max(0.0, min(1.0, (x - x0) / (x1 - x0)))
            c = _over(c, tuple(BAR_LIGHT[k] + (BAR_DEEP[k] - BAR_LIGHT[k]) * t for k in range(3)), -0.2 - d)
        return c
    return f


def render(sample):
    """Supersampled pixel(x, y) callable for tga32 (y=0 top)."""
    cache = {}
    for y in range(N):
        for x in range(N):
            acc, asum = [0.0, 0.0, 0.0], 0.0
            for sy in range(SS):
                for sx in range(SS):
                    r, g, b, a = sample(x + (sx + 0.5) / SS, y + (sy + 0.5) / SS)
                    asum += a
                    acc[0] += r * a; acc[1] += g * a; acc[2] += b * a
            rgb = tuple(v / asum for v in acc) if asum > 0 else (0, 0, 0)
            cache[(x, y)] = tuple(max(0, min(255, int(round(v)))) for v in rgb) + (max(0, min(255, int(round(asum / (SS * SS) * 255)))),)
    return lambda x, y: cache[(x, y)]


def build():
    """(resref, identifier, bytes, pixel) per badge, in kBadgeTex order."""
    out = []
    for name, ident, fn in [("bh_badge_launch", "kBadgeLaunchTex", launch), ("bh_badge_t2", "kBadgeT2Tex", tier(2)),
                            ("bh_badge_t3", "kBadgeT3Tex", tier(3)), ("bh_badge_t4", "kBadgeT4Tex", tier(4))]:
        pixel = render(fn)
        out.append((name, ident, tga32(N, N, pixel), pixel))
    return out


def render_inc(blobs) -> str:
    out = ["// GENERATED by scripts/gen_badge_icons.py -- do not edit. Uncompressed 32-bit TGA images served from memory by the DLL.",
           "// Requires embtex::Tex { const char* resref; const unsigned char* data; unsigned size; } (EmbedTex.h).", ""]
    for _, ident, data, _ in blobs:
        out.append(f"static const unsigned char {ident}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
    out.append("")
    out.append("static const embtex::Tex kBadgeTex[] = {   // [0] launch, [1..3] tier 2..4")
    for name, ident, _, _ in blobs:
        out.append(f'    {{ "{name}", {ident}, sizeof {ident} }},')
    out.append("};")
    out.append(f"static const unsigned kBadgeTexCount = {len(blobs)};")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--png", type=Path)
    a = ap.parse_args(argv)
    blobs = build()
    text = render_inc(blobs)
    if a.png:
        from PIL import Image
        a.png.mkdir(parents=True, exist_ok=True)
        for name, _, _, pixel in blobs:
            im = Image.new("RGBA", (N, N))
            im.putdata([pixel(x, y) for y in range(N) for x in range(N)])
            im.save(a.png / f"{name}.png")
    if a.check:
        if INC.exists() and INC.read_text() == text:
            return 0
        print(f"{INC} is missing or differs from regenerated output; run scripts/gen_badge_icons.py")
        return 1
    INC.write_text(text)
    print(f"wrote {INC} ({', '.join(f'{n} {len(d)} B' for n, _, d, _ in blobs)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
