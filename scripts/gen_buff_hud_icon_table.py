"""Generate patch_manager_mods/_shared_src/EffectIconTable.inc from the live spells.2da. (shared via Patches/Common; was Patches/BuffDurationHUD)

Usage: gen_buff_hud_icon_table.py <spells.2da> <texture-name-list.txt> <out.inc>
Buff rows = non-hostile rows (forcehostile empty, hostilesetting 0/empty) with an
iconresref, minus instant/passive rows. ITEM_ABILITY_* rows have no iconresref in the
2DA, so they use the hand-picked resrefs below (lead #4 was negative, see
patch_manager_mods/02_buff_duration_hud.md). Every resref is checked against the
texture list; missing ones are dropped and reported.
"""
import sys
from pykotor.resource.formats.twoda import read_2da

spells, texlist, out = sys.argv[1:4]
tex = set(open(texlist).read().split())
t = read_2da(open(spells, "rb").read())
EXCLUDE = {0, 1, 2, 3, 6, 10, 14, 21, 28, 134}  # master passives, jump, mind-affecting, instant heals
# item-ability rows: inventory icons (ii_<itemclass>_<modelvariation>), NOT the i_* model UV sheets
ITEM_PICKS = {
    69: "ii_adrnaline_001",
    70: "ii_adrnaline_002",
    71: "ii_adrnaline_003",
    72: "ii_adrnaline_004",
    73: "ii_adrnaline_005",
    74: "ii_adrnaline_006",
    75: "ii_cmbtshot_001",
    76: "ii_cmbtshot_002",
    77: "ii_cmbtshot_003",
    129: "ii_medeqpmnt_005",
    99: "ii_frarmbnds_001",
    100: "ii_frarmbnds_002",
    101: "ii_frarmbnds_003",
    102: "ii_frarmbnds_004",
    103: "ii_frarmbnds_005",
    104: "ii_frarmbnds_006",
    105: "ii_frarmbnds_007",
    106: "ii_frarmbnds_008",
    107: "ii_frarmbnds_009",
    132: "ii_frarmbnds_001",
    108: "ip_shield",
    257: "ip_shield",
    110: "ii_drdshld_001",
    111: "ii_drdshld_004",
    112: "ii_drdshld_005",
    113: "ii_drdshld_006",
    114: "ii_drdshld_007",
    115: "ii_drdshld_005",
}
rows, missing = {}, []
for i in range(t.get_height()):
    r = t.get_row(i)
    ic = r.get_string("iconresref").lower()
    if ic and i not in EXCLUDE and not r.get_string("forcehostile") and r.get_string("hostilesetting") in ("", "0"):
        rows[i] = ic
for i, ic in ITEM_PICKS.items():
    assert not t.get_row(i).get_string("iconresref"), i
    rows[i] = ic
for i in sorted(rows):
    if rows[i] not in tex:
        missing.append((i, rows[i])); del rows[i]
n = t.get_height()
with open(out, "w") as f:
    f.write("// GENERATED by scripts/gen_buff_hud_icon_table.py -- do not hand-edit.\n")
    f.write(f"constexpr int kEffectIconTableSize = {n};\n")
    f.write("// index = spells.2da row = CGameEffect+0x1c; nullptr = not a tracked buff.\n")
    f.write("constexpr const char* const kEffectIcons[kEffectIconTableSize] = {\n")
    for i in range(n):
        if i in rows: f.write(f'    /*{i}*/ "{rows[i]}",\n')
        else: f.write("    nullptr,\n")
    f.write("};\n")
print(len(rows), "rows; dropped (missing texture):", missing)
