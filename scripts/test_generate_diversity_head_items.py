sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_diversity_head_items as G  # noqa: E402

# Hand-checked synthetic doc. Items (resref order): a_mask, b_droid, c_gen, d_feat.
#  a_mask: rule 1 (race 6 only), no restrictions            -> allowed where race 6 and gender 0 pass
#  b_droid: rule 2 (race 5 only), restricted                -> restricted where race 5 passes
#  c_gen: rule 0, gender_mask 1 (rejects gender 0)          -> allowed where gender 4 passes
#  d_feat: req_feats [7]                                    -> never allowed or restricted
#  row 10 (B, goggle yes, races [6], genders [0]): a_mask allowed, b_droid/c_gen/d_feat neither
#  row 5 (F, goggle no, races [5], genders [4]): b_droid restricted, c_gen allowed, a_mask/d_feat neither
SYN = {
    "schema": 1,
    "baseitems": {
        "1": {"droid": False, "gender_mask": 0, "label": "Mask", "race_rule": 1, "req_feats": []},
        "2": {"droid": True, "gender_mask": 0, "label": "Droid", "race_rule": 2, "req_feats": []},
        "3": {"droid": False, "gender_mask": 1, "label": "Gen", "race_rule": 0, "req_feats": []},
        "4": {"droid": False, "gender_mask": 0, "label": "Feat", "race_rule": 0, "req_feats": [7]},
    },
    "items": {
        "d_feat": {"baseitem": 4, "model": "m4", "restrictions": []},
        "c_gen": {"baseitem": 3, "model": "m3", "restrictions": []},
        "b_droid": {"baseitem": 2, "model": "m2", "restrictions": [{"subtype": 5, "type": 62}]},
        "a_mask": {"baseitem": 1, "model": "m1", "restrictions": []},
    },
    "appearances": {
        "10": {"label": "X", "modeltype": "B", "has_goggle_hook": "yes", "races": [6], "genders": [0],
               "n_utc": 1, "head_items": ["a_mask"]},
        "5": {"label": "Y", "modeltype": "F", "has_goggle_hook": "no", "races": [5], "genders": [4],
              "n_utc": 2, "head_items": ["b_droid", "zz_missing"]},
    },
}

# Hand-computed from SYN:
#  row 5:  flags = 0x04 (observed), raceMask = 1<<5 = 0x20, allowed = bit2 = 4, restricted = bit1 = 2, observed = bit1 = 2
#  row 10: flags = 0x07 (B | goggle | observed), raceMask = 1<<6 = 0x40, allowed = bit0 = 1, restricted = 0, observed = 1
#  items: a_mask flags 0x00; b_droid flags 0x03 (droid | restrictions), restrictionCount 1; c_gen, d_feat flags 0x00
GOLDEN = "\n".join([
    "// DiversityHeadItems.h -- GENERATED by scripts/generate_diversity_head_items.py from head_items_source.json. Do not edit.",
    "// Head-item rule model per appearance row: base-item race, gender and feat rules, restrictions, vanilla-observed items.",
    "#pragma once",
    "",
    "#include <cstdint>",
    "",
    "namespace diversity_head_items {",
    "",
    "// Items in resref order. flags bit0 = droid item (race rule 2), bit1 = has restrictions.",
    "struct HeadItem { const char* resref; uint16_t baseitem; uint8_t flags; uint8_t restrictionCount; };",
    "inline constexpr HeadItem kHeadItems[4] = {",
    '    {"a_mask", 1, 0x00, 0},',
    '    {"b_droid", 2, 0x03, 1},',
    '    {"c_gen", 3, 0x00, 0},',
    '    {"d_feat", 4, 0x00, 0},',
    "};",
    "inline constexpr unsigned kHeadItemCount = 4;",
    "",
    "// Appearances in ascending row order. flags bit0 = modeltype B, bit1 = has GoggleHook, bit2 = observed wearing.",
    "// raceMask bit r = race r observed (races 0..7). allowed/restricted/observed are bitsets over kHeadItems indices.",
    "struct HeadAppearance { uint16_t row; uint8_t flags; uint8_t raceMask; uint64_t allowed; uint64_t restricted; uint64_t observed; };",
    "inline constexpr HeadAppearance kHeadAppearances[2] = {",
    "    {5, 0x04, 0x20, 0x0000000000000004ULL, 0x0000000000000002ULL, 0x0000000000000002ULL},",
    "    {10, 0x07, 0x40, 0x0000000000000001ULL, 0x0000000000000000ULL, 0x0000000000000001ULL},",
    "};",
    "inline constexpr unsigned kHeadAppearanceCount = 2;",
    "",
    "// Binary search over kHeadAppearances (sorted by row); nullptr when the row has no entry.",
    "inline constexpr const HeadAppearance* findAppearance(uint16_t row) {",
    "    unsigned lo = 0;",
    "    unsigned hi = kHeadAppearanceCount;",
    "    while (lo < hi) {",
    "        unsigned mid = lo + (hi - lo) / 2;",
    "        if (kHeadAppearances[mid].row < row) {",
    "            lo = mid + 1;",
    "        } else {",
    "            hi = mid;",
    "        }",
    "    }",
    "    return (lo < kHeadAppearanceCount && kHeadAppearances[lo].row == row) ? &kHeadAppearances[lo] : nullptr;",
    "}",
    "",
    "// True when head item idx is in the allowed set (base rules pass and the item has no restrictions).",
    "inline constexpr bool itemAllowed(const HeadAppearance& a, unsigned idx) {",
    "    return idx < 64 && ((a.allowed >> idx) & 1ULL) != 0;",
    "}",
    "",
    "} // namespace diversity_head_items",
]) + "\n"


def big_doc(n):
    """n items, all allowed for row 10 (race 6, gender 0)."""
    return {
        "baseitems": {"1": {"droid": False, "gender_mask": 0, "label": "Mask", "race_rule": 1, "req_feats": []}},
        "items": {"i%03d" % i: {"baseitem": 1, "model": "m", "restrictions": []} for i in range(n)},
        "appearances": {"10": {"label": "X", "modeltype": "B", "has_goggle_hook": "no", "races": [6],
                               "genders": [0], "n_utc": 1, "head_items": []}},
    }


class HeadItemsTests(unittest.TestCase):
    def test_race_ok(self):
        self.assertTrue(G.race_ok(0, 2))
        self.assertTrue(G.race_ok(0, 6))
        self.assertTrue(G.race_ok(1, 6))
        self.assertFalse(G.race_ok(1, 5))
        self.assertTrue(G.race_ok(2, 5))
        self.assertFalse(G.race_ok(2, 6))
        self.assertFalse(G.race_ok(3, 6))

    def test_gender_ok(self):
        self.assertTrue(G.gender_ok(0, 4))
        self.assertFalse(G.gender_ok(0b001, 0))
        self.assertTrue(G.gender_ok(0b001, 1))
        self.assertFalse(G.gender_ok(0b100, 2))
        self.assertTrue(G.gender_ok(0b100, 0))

    def test_base_ok(self):
        row = {"race_rule": 1, "gender_mask": 0, "req_feats": []}
        self.assertTrue(G.base_ok(row, {"races": [5, 6], "genders": [0]}))      # one race passes
        self.assertFalse(G.base_ok(row, {"races": [5], "genders": [0]}))        # no race passes
        self.assertFalse(G.base_ok(row, {"races": [6], "genders": []}))         # no gender
        self.assertFalse(G.base_ok(dict(row, req_feats=[7]), {"races": [6], "genders": [0]}))
        self.assertTrue(G.base_ok(dict(row, gender_mask=0b001), {"races": [6], "genders": [0, 1]}))
        self.assertFalse(G.base_ok(dict(row, gender_mask=0b001), {"races": [6], "genders": [0]}))

    def test_golden_render_of_synthetic_doc(self):
        self.assertEqual(G.render(SYN), GOLDEN)

    def test_render_is_deterministic(self):
        self.assertEqual(G.render(SYN), G.render(SYN))
        real = json.loads(G.SOURCE.read_text())
        self.assertEqual(G.render(real), G.render(real))

    def test_unknown_refs_are_ignored_and_noted(self):
        notes = []
        G.render(SYN, notes)
        self.assertEqual(notes, ["note: 1 head_item ref(s) not in items, ignored: row 5 zz_missing"])

    def test_more_than_64_items_raises(self):
        with self.assertRaises(SystemExit):
            G.render(big_doc(65))

    def test_64_items_boundary(self):
        t = G.render(big_doc(64))
        self.assertIn("inline constexpr HeadItem kHeadItems[64] = {", t)
        self.assertIn("inline constexpr unsigned kHeadItemCount = 64;", t)
        self.assertIn("    {10, 0x01, 0x40, 0xFFFFFFFFFFFFFFFFULL, 0x0000000000000000ULL, 0x0000000000000000ULL},", t)

    def test_check_mode(self):
        with tempfile.TemporaryDirectory() as td:
            src, out = Path(td) / "s.json", Path(td) / "o.h"
            src.write_text(json.dumps(SYN))
            args = ["--source", str(src), "--out", str(out)]
            self.assertEqual(G.main(args + ["--check"]), 1)      # missing
            self.assertFalse(out.exists())                        # --check writes nothing
            self.assertEqual(G.main(args), 0)
            self.assertEqual(G.main(args + ["--check"]), 0)
            out.write_text(out.read_text() + "x")
            self.assertEqual(G.main(args + ["--check"]), 1)      # stale
            self.assertTrue(out.read_text().endswith("x"))        # --check did not rewrite it

    def test_committed_header_is_current(self):
        self.assertEqual(G.main(["--check"]), 0)

    def test_vanilla_observed_items_explained_by_rules(self):
        items, apps, _ = G.model(json.loads(G.SOURCE.read_text()))
        bad = []
        for a in apps:
            for i, (resref, _bid, _flags, _count) in enumerate(items):
                if (a["observed"] >> i) & 1 and not ((a["allowed"] | a["restricted"]) >> i) & 1:
                    bad.append((a["row"], resref))
        self.assertEqual(bad, [], "%d observed (row, resref) pairs are neither allowed nor restricted: %s"
                         % (len(bad), bad))

    def test_utc_head_items_respect_race_rule(self):
        doc = json.loads(G.SOURCE.read_text())
        items, baseitems = doc["items"], doc["baseitems"]
        bad = []
        tsv = G.REPO / ".claude/research/npc_equipment/utc_equip.tsv"
        with tsv.open(newline="") as f:
            for rec in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
                race = int(rec["race"])
                for ref in rec["head_item_resrefs"].split(";"):
                    ref = ref.strip()
                    if ref in items and not G.race_ok(baseitems[str(items[ref]["baseitem"])]["race_rule"], race):
                        bad.append((rec["appearance_type"], rec["resref"], ref, race))
        self.assertEqual(bad, [], "%d UTC head-item race-rule violations (appearance_type, utc resref, item, race); "
                                  "first 10: %s" % (len(bad), bad[:10]))


if __name__ == "__main__":
    unittest.main()
