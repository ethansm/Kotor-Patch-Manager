"""Generate patch_manager_mods/_shared_src/DebuffIconTable.inc (negative-effect icons). (shared via Patches/Common; was Patches/BuffDurationHUD)

Usage: gen_debuff_icon_table.py <game dir> <out.inc>
Hostile spells.2da rows (forcehostile set or hostilesetting 1) with an iconresref use it
(force powers, no backing disc). ITEM/DROID_ITEM rows have no icon, so the icon of the
item that grants the spell is used: baseitems.2da itemclass + the UTI model variation ->
i<itemclass>_<variation:03d> (ii_frarmbnds_001, iw_rocket_003), checked against the installed textures (item = true: gets
the round backing disc). Rows with no usable icon stay nullptr (engine arrow remains).
Also writes <out dir>/EffectIconRowTable.inc: effecticon.2da row -> { iconresref, good }, for script SetEffectIcon (effect type 0x43)
debuffs such as Slow that carry no spell id the table above can map.
"""
import sys, glob, os
from pykotor.extract.installation import Installation
from pykotor.resource.type import ResourceType
from pykotor.resource.formats.twoda import read_2da
from pykotor.resource.formats.erf import read_erf
from pykotor.resource.generics.uti import read_uti

game, out = sys.argv[1:3]
inst = Installation(game)
sp = read_2da(inst.resource('spells', ResourceType.TwoDA).data)
bi = read_2da(inst.resource('baseitems', ResourceType.TwoDA).data)
tex = set()
for f in glob.glob(game + "/TexturePacks/*.erf"):
    for x in read_erf(f): tex.add(str(x.resref).lower())
for f in os.listdir(game + "/override"):
    if f.lower().endswith(('.tpc', '.tga')): tex.add(f.rsplit('.', 1)[0].lower())
EXCLUDE = {0, 1, 2, 3, 6, 10, 14, 21, 28, 134}
# Hostile force powers the plain rule misses: spells.2da has no iconresref for BAT_MED_ENEMY (141-143, the ip_battlemed*
# icons exist in override), and DROID_TRICK / DROID_CONFUSION (201, 269) carry neither forcehostile nor hostilesetting.
FORCE_INCLUDE = {201, 269}
ICON_FALLBACK = {141: 'ip_battlemed01', 142: 'ip_battlemed02', 143: 'ip_battlemed03'}
item_icon = {}   # spell -> first existing ii_ icon of a granting item
for r in inst.chitin_resources():
    if r.restype() != ResourceType.UTI: continue
    try: u = read_uti(r.data())
    except Exception: continue
    cls = bi.get_row(u.base_item).get_string('itemclass').lower() if u.base_item < bi.get_height() else ''
    if not cls: continue
    # the item icon is 'i' + itemclass: i_frarmbnds -> ii_frarmbnds, w_rocket -> iw_rocket (grenades, darts, rockets)
    ic = f"i{cls}_{u.model_variation:03d}"
    for p in u.properties:
        if p.property_name == 10 and ic in tex and p.subtype not in item_icon:
            item_icon[p.subtype] = ic
rows, report = {}, []
for i in range(sp.get_height()):
    if i in EXCLUDE: continue
    r = sp.get_row(i)
    if i not in FORCE_INCLUDE and not (r.get_string('forcehostile') or r.get_string('hostilesetting') not in ('', '0')): continue
    ic = r.get_string('iconresref').lower() or ICON_FALLBACK.get(i, '')
    if ic and ic in tex: rows[i] = (ic, False)
    elif i in item_icon: rows[i] = (item_icon[i], True)
    else: report.append((i, r.get_string('label')))
n = sp.get_height()
with open(out, "w") as f:
    f.write("// GENERATED by scripts/gen_debuff_icon_table.py -- do not hand-edit.\n")
    f.write(f"constexpr int kDebuffIconTableSize = {n};\n")
    f.write("struct DebuffIcon { const char* resref; bool item; };\n")
    f.write("constexpr DebuffIcon kDebuffIcons[kDebuffIconTableSize] = {\n")
    for i in range(n):
        if i in rows: f.write(f'    /*{i}*/ {{ "{rows[i][0]}", {"true" if rows[i][1] else "false"} }},\n')
        else: f.write("    { nullptr, false },\n")
    f.write("};\n")
ei = read_2da(inst.resource('effecticon', ResourceType.TwoDA).data)
ne = ei.get_height()
with open(os.path.join(os.path.dirname(os.path.abspath(out)), "EffectIconRowTable.inc"), "w") as f:
    f.write("// GENERATED by scripts/gen_debuff_icon_table.py -- do not hand-edit.\n")
    f.write(f"constexpr int kEffectIconRowCount = {ne};\n")
    f.write("struct EffectIconRow { const char* resref; int good; };   // good: 1 beneficial, 0 harmful, -1 unset\n")
    f.write("constexpr EffectIconRow kEffectIconRows[kEffectIconRowCount] = {\n")
    for i in range(ne):
        r = ei.get_row(i)
        ic = r.get_string('iconresref').strip().lower()
        g = r.get_string('good').strip()
        f.write(f'    /*{i}*/ {{ {chr(34) + ic + chr(34) if ic and ic in tex else "nullptr"}, {int(g) if g.isdigit() else -1} }},\n')
    f.write("};\n")
print(len(rows), "rows;", sum(1 for v in rows.values() if v[1]), "item-derived")
for i, l in report: print("no icon:", i, l)
