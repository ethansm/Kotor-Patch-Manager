"""Generate Patches/BuffDurationHUD/ShieldTable.inc (Shield Bar colors + pool sizes).

Usage: gen_shield_table.py <game dir> <out.inc>
Reads forceshields.2da from the install (pykotor) and emits, per row,
{amount, damageflags, visualeffectdef, r, g, b}. The color is the hue of the shield's own
in-world VFX (visualeffects row 2040..2048/2060, mod #35 textures; see
patch_manager_mods/08_shield_bar.md), falling back by damage coverage for unknown VFX rows
(droid shields): ion/sonic coverage -> enviro blue, else energy red.
"""
import sys
import logging
logging.disable(logging.CRITICAL)
from pykotor.extract.installation import Installation
from pykotor.resource.type import ResourceType
from pykotor.resource.formats.twoda import read_2da

VFX_COLORS = {2040: 0x4CACFF, 2044: 0x7CFFC7, 2045: 0xFF0A0A, 2041: 0x385EFF, 2047: 0xDD92FF,
              2048: 0xCE63FF, 2042: 0x6473FF, 2043: 0x0D0CFF, 2046: 0xFF9B24, 2060: 0xFF450B}
ION, SONIC = 2048, 1024

game, out = sys.argv[1:3]
fs = read_2da(Installation(game).resource('forceshields', ResourceType.TwoDA).data)


def num(row, col):
    v = row.get_string(col)
    return int(v) if v.lstrip('-').isdigit() else 0


rows = []
for i in range(fs.get_height()):
    r = fs.get_row(i)
    flags, vfx = num(r, 'damageflags'), num(r, 'visualeffectdef')
    rgb = VFX_COLORS.get(vfx) or (0x4CACFF if flags & (ION | SONIC) else 0xFF0A0A)
    rows.append((num(r, 'amount'), flags, vfx, rgb, r.get_string('label')))
with open(out, "w") as f:
    f.write("// GENERATED by scripts/gen_shield_table.py -- do not hand-edit.\n")
    f.write(f"constexpr int kShieldTableSize = {len(rows)};\n")
    f.write("struct ShieldRow { int amount, damageFlags, vfx; float rgb[3]; };\n")
    f.write("constexpr ShieldRow kShieldRows[kShieldTableSize] = {\n")
    for i, (amt, fl, vfx, rgb, lab) in enumerate(rows):
        f.write(f"    /*{i} {lab}*/ {{ {amt}, {fl}, {vfx}, {{ {(rgb >> 16) / 255:.4f}f, {((rgb >> 8) & 255) / 255:.4f}f, {(rgb & 255) / 255:.4f}f }} }},\n")
    f.write("};\n")
print(len(rows), "rows")
