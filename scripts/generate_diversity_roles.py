#!/usr/bin/env python3
"""Generate patch_manager_mods/npc_diversity_src/DiversityRoles.h from the NPC registry + Haiku role outputs (stdlib only).

Inputs : .claude/npc_div/registry.jsonl (npc_div_registry.py build), .claude/npc_div/roles/out_*.json
         (list of {tag,name,role,reason} per pairs_*.json batch).
Rule   : only registry rows in the generic commoner tables (fam != "") are considered. A creature is keep-default when its
         (tag,name) pair was classified by Haiku as anything but `generic`, or its rule role is `plot` (Plot=1 or
         Interruptable=0), or its pair has no Haiku verdict and the rule role is not `generic` (safe side).
Output : DiversityRoles.h with
           kKeepTags       sorted unique lower-case tags of keep-default creatures (a tag is keep-default if ANY instance is)
           kKeepPositions  sorted unique (round(x*10), round(y*10)) of keep-default instances (position fallback,
                           match tolerance kKeepPosTol10 = 3 i.e. 0.3 m)
         Both are byte-stable. Roles are data, never hand-written lists.
Usage: generate_diversity_roles.py [--registry F] [--roles-dir D] [--out F] [--check] [--report]
"""
from __future__ import annotations

import argparse
import glob
import json
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REGISTRY = REPO / ".claude/npc_div/registry.jsonl"
ROLES_DIR = REPO / ".claude/npc_div/roles"
OUT = REPO / "patch_manager_mods/npc_diversity_src/DiversityRoles.h"
POS_TOL10 = 3     # 0.3 m in 0.1 m units (registry tolerance 0.25 m, rounded up)
ROLES = {"generic", "named", "merchant", "uniformed", "plot"}


def load_registry(path):
    return [json.loads(l) for l in Path(path).read_text().splitlines() if l.strip()]


def load_verdicts(roles_dir):
    v = {}
    for p in sorted(glob.glob(str(Path(roles_dir) / "out_*.json"))):
        for item in json.loads(Path(p).read_text()):
            if item.get("role") in ROLES:
                v[(item["tag"], item["name"])] = item["role"]
    return v


def classify(row, verdicts):
    """Final role of one registry row: Haiku verdict when present, plot rows always keep."""
    if row.get("plot") or not row.get("interruptable", 1):
        return "plot"
    return verdicts.get((row.get("tag", ""), row.get("name", "")), row.get("role", "generic"))


def keep_sets(rows, verdicts):
    tags, pos, counts = set(), set(), Counter()
    for r in rows:
        if r.get("unresolved") or not r.get("fam"):
            continue
        role = classify(r, verdicts)
        counts[role] += 1
        if role != "generic":
            if r.get("tag"):
                tags.add(r["tag"].lower())
            pos.add((int(round(r["x"] * 10)), int(round(r["y"] * 10))))
    return sorted(tags), sorted(pos), counts


def cpp_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(tags, pos):
    L = [
        "// DiversityRoles.h -- GENERATED by scripts/generate_diversity_roles.py from the NPC registry. Do not edit.",
        "// Keep-default creatures (named, merchant, uniformed, plot) among the generic commoner rows.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace NpcDiversity {",
        "namespace roles {",
        "",
        "// Lower-case creature tags. A tag is keep-default when ANY registry instance with that tag qualifies.",
        "constexpr const char* kKeepTags[] = {",
    ]
    L += ["    %s," % cpp_str(t) for t in tags] or ['    "",']
    L += ["};", "constexpr size_t kKeepTagCount = %d;" % len(tags), "",
          "// Position fallback (0.1 m units): keep-default when an entry lies within kKeepPosTol10 on both axes.",
          "struct KeepPos { int32_t x10; int32_t y10; };",
          "constexpr int32_t kKeepPosTol10 = %d;" % POS_TOL10,
          "constexpr KeepPos kKeepPositions[] = {"]
    L += ["    {%d, %d}," % p for p in pos] or ["    {0, 0},"]
    L += ["};", "constexpr size_t kKeepPositionCount = %d;" % len(pos), "", "} // namespace roles",
          "} // namespace NpcDiversity"]
    return "\n".join(L) + "\n"


def ambiguity(rows, verdicts):
    """Share of generic instances (any module) within the position tolerance of a keep-default instance."""
    _, pos, _ = keep_sets(rows, verdicts)
    gen = [(int(round(r["x"] * 10)), int(round(r["y"] * 10))) for r in rows
           if r.get("fam") and not r.get("unresolved") and classify(r, verdicts) == "generic"]
    hit = sum(1 for g in gen if any(abs(g[0] - p[0]) <= POS_TOL10 and abs(g[1] - p[1]) <= POS_TOL10 for p in pos))
    return len(gen), hit


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--registry", default=str(REGISTRY))
    ap.add_argument("--roles-dir", default=str(ROLES_DIR))
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args(argv)
    rows = load_registry(a.registry)
    verdicts = load_verdicts(a.roles_dir)
    tags, pos, counts = keep_sets(rows, verdicts)
    text = render(tags, pos)
    if a.report:
        gen, hit = ambiguity(rows, verdicts)
        print("verdicts=%d roles=%s keep tags=%d keep positions=%d" % (
            len(verdicts), dict(counts), len(tags), len(pos)))
        print("position ambiguity: %d of %d generic instances fall within %.1f m of a keep position (%.1f%%)" % (
            hit, gen, POS_TOL10 / 10.0, 100.0 * hit / gen if gen else 0))
    out = Path(a.out)
    if a.check:
        if not out.exists() or out.read_text() != text:
            print("DiversityRoles.h is stale: run scripts/generate_diversity_roles.py")
            return 1
        print("DiversityRoles.h up to date")
        return 0
    out.write_text(text)
    print("wrote %s (%d tags, %d positions)" % (out, len(tags), len(pos)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
