"""Generate Patches/Inventory3DViewport/ItemModelTable.inc from the live baseitems.2da.

Usage: gen_inventory_3dview_table.py <game dir> <out.inc>
Also writes ItemFitTable.inc next to <out.inc> (fit bboxes per (row,var), EMPTY flag) and, into <out.inc>,
kItemType[] and kDefaultOrient[][4] = {rx,ry,rz,pitch} degrees (v2 Design 5).
Per baseitems row -> render category for engine function 008cd2c0:
  4 = armor (modeltype == 1 or bodyvar set; fixed male-medium body),
  2 = plain model, if "<itemclass>_001" resolves as an MDL (override, then chitin BIFs),
  0 = no preview.
Category 1 (saber-workbench special) is never emitted. Also emits kIsWeaponOrArmor[] for the
INV3D_ONLY_WEAPONS_ARMOR compile-time kill switch.
"""
import sys, logging
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import inv3d_model_fit as fit
logging.disable(logging.CRITICAL)
from pykotor.extract.installation import Installation
from pykotor.resource.type import ResourceType
from pykotor.resource.formats.twoda import read_2da

game, out = sys.argv[1:3]
inst = Installation(game)

def has_mdl(name):
    try:
        return inst.resource(name, ResourceType.MDL) is not None
    except Exception:
        return False

for n, want in (("w_lngswrd_001", True), ("w_blstrrfl_001", True), ("zz_nonexistent_001", False), ("a_class4_001", False)):
    assert has_mdl(n) == want, f"resolver sanity failed for {n}"

bi = read_2da(inst.resource('baseitems', ResourceType.TwoDA).data)
N = bi.get_height()
cats, weap, lines, itypes = [], [], [], []
for i in range(N):
    r = bi.get_row(i)
    label, icls = r.get_string('label'), r.get_string('itemclass').lower()
    if r.get_string('modeltype') == '1' or r.get_string('bodyvar').strip() not in ('', '****'):
        c = 4
    elif icls and icls != '****' and has_mdl(icls + '_001'):
        c = 2
    else:
        c = 0
    cats.append(c)
    weap.append(1 if (c == 4 or icls.startswith('w_')) else 0)
    lines.append((i, label, icls, c))
    it = r.get_string('itemtype').strip()
    itypes.append(int(it) if it.lstrip('-').isdigit() else -1)

survey = fit.survey_installation(game)
orient, ocount = [], {}
for i, label, icls, c in lines:
    b = survey.get((i, 1))
    if c == 4:
        o, why = (0, 0, 0, 0), "armour: fixed box"
    elif b is None or b.get("empty"):
        o, why = (0, 0, 0, 15), "no _001 bbox"
    else:
        e = b["ext"]; lg = b["longest"]
        flat = min(e) < 0.35 * max(e)
        if lg == "z":
            o, why = (0, 0, 0, 0), "longest z: vertical"
        elif icls.startswith("w_") and lg == "y":
            o, why = (0, 0, 0, 0), "weapon longest y: barrel horizontal"
        elif not icls.startswith("w_") and flat:
            o, why = (0, 0, 0, 55), "non-weapon flat: tilt"
        else:
            o, why = (0, 0, 0, 15), "default tilt"
    orient.append((o, why, b))
    ocount[why] = ocount.get(why, 0) + 1

with open(out, 'w') as f:
    f.write("// Generated by scripts/gen_inventory_3dview_table.py from baseitems.2da - do not edit.\n")
    f.write("// 0 = no preview, 2 = plain model (006d5000), 4 = armor on the male-medium body.\n")
    f.write(f"static const int kItemRows = {N};\n")
    f.write(f"static const unsigned char kItemCategory[{N}] = {{\n")
    for i, label, icls, c in lines:
        f.write(f"    {c}, // {i} {label} ({icls})\n")
    f.write("};\n")
    f.write(f"static const unsigned char kIsWeaponOrArmor[{N}] = {{\n")
    for i, label, icls, c in lines:
        f.write(f"    {weap[i]}, // {i} {label}\n")
    f.write("};\n")
with open(out, 'a') as f:
    f.write(f"static const int kItemType[{N}] = {{\n")
    for (i, label, icls, c), t in zip(lines, itypes):
        f.write(f"    {t}, // {i} {label}\n")
    f.write("};\n")
    f.write(f"// {{rx, ry, rz, pitch}} degrees; qBase = qZ(rz) * qY(ry) * qX(rx)\n")
    f.write(f"static const float kDefaultOrient[{N}][4] = {{\n")
    for (i, label, icls, c), (o, why, b) in zip(lines, orient):
        ext = ("ext=[%.2f %.2f %.2f]" % tuple(b["ext"])) if b and not b.get("empty") else "no bbox"
        f.write("    {%d, %d, %d, %d}, // %d %s (%s) %s; %s\n" % (*o, i, label, icls, ext, why))
    f.write("};\n")

fitp = Path(out).with_name("ItemFitTable.inc")
entries = sorted(survey.items())
nempty = 0
with open(fitp, 'w') as f:
    f.write("// Generated by scripts/gen_inventory_3dview_table.py via inv3d_model_fit.survey_installation - do not edit.\n")
    f.write("// Sorted by (row,var). flags bit0 = EMPTY (model exists but has no mesh). c = bbox centre, e = extent (model space).\n")
    f.write("struct FitEntry { unsigned short row; unsigned char var; unsigned char flags; float c[3]; float e[3]; };\n")
    f.write("static const FitEntry kFit[] = {\n")
    for (row, var), b in entries:
        if b.get("empty"):
            nempty += 1
            f.write("    {%d, %d, 1, {0,0,0}, {0,0,0}}, // %s_%03d EMPTY\n" % (row, var, b["cls"], var))
        else:
            f.write("    {%d, %d, 0, {%.4ff,%.4ff,%.4ff}, {%.4ff,%.4ff,%.4ff}}, // %s_%03d\n" % (
                row, var, *b["centre"], *b["ext"], b["cls"], var))
    f.write("};\n")
    f.write(f"static const int kFitCount = {len(entries)};\n")
print(f"fit entries: {len(entries)}, EMPTY row-entries: {nempty}, distinct EMPTY models: {len({b['model'] for _, b in entries if b.get('empty')})}")
for k, v in sorted(ocount.items()):
    print(f"orientation rule '{k}': {v} rows")
for c in (0, 2, 4):
    rows = [i for i, _, _, cc in lines if cc == c]
    print(f"category {c}: {len(rows)} rows: {rows}")
print("weapon/armor rows:", sum(weap))
