#!/usr/bin/env python3
"""Generate the shared edit-page textures (e3d_gear, e3d_gear_hi, e3d_fill, e3d_trk, e3d_thm) and embed them in the DLL source.

Writes patch_manager_mods/_shared_src/GearIconTex.inc (uncompressed 32-bit TGAs, same layout as LuoTextures.inc):
  kGearTex / kGearHiTex / kFillTex  byte-for-byte copies of the luo_gear / luo_gear_hi / luo_fill arrays, parsed out of
                                    level_up_override_src/LuoTextures.inc (written by gen_luo_textures.py; no PIL needed here)
  kTrackTex                         opaque dark 64x8 bar with a lighter 1 px top and bottom line
  kThumbTex                         opaque gold 16x16 square with a darker 1 px border

  (no args)  write the .inc
  --check    regenerate in memory and compare with the existing .inc (exit 0 identical, 1 otherwise)
"""
import argparse
import re
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
INC = REPO / "patch_manager_mods/_shared_src/GearIconTex.inc"
LUO_INC = REPO / "patch_manager_mods/level_up_override_src/LuoTextures.inc"
TRACK_FILL, TRACK_EDGE = (24, 24, 28), (40, 40, 46)
THUMB_FILL, THUMB_EDGE = (200, 160, 60), (120, 90, 30)
FOOTER = bytes(8) + b"TRUEVISION-XFILE.\x00"   # TGA 2.0 footer: extension and developer offsets (0), signature
ARRAY_RE = re.compile(r"static const unsigned char (\w+)\[(\d+)\] = \{(.*?)\};", re.S)
HEX_RE = re.compile(r"0x([0-9a-fA-F]{2})")


def luo_arrays():
    """identifier -> bytes for every byte array in LuoTextures.inc; declared sizes are checked."""
    arrays = {}
    for ident, size, body in ARRAY_RE.findall(LUO_INC.read_text()):
        data = bytes(int(h, 16) for h in HEX_RE.findall(body))
        if len(data) != int(size):
            raise ValueError(f"{LUO_INC}: {ident} declares {size} bytes but holds {len(data)}")
        arrays[ident] = data
    return arrays


def tga32(w, h, pixel):
    """Uncompressed 32-bit TGA, bottom-left origin (descriptor 0x08) like the luo images. pixel(x, y) -> (r, g, b, a), y=0 is the top row."""
    head = struct.pack("<BBBHHBHHHHBB", 0, 0, 2, 0, 0, 0, 0, 0, w, h, 32, 0x08)
    rows = bytearray()
    for y in range(h - 1, -1, -1):
        for x in range(w):
            r, g, b, a = pixel(x, y)
            rows += bytes((b, g, r, a))
    return head + bytes(rows) + FOOTER


def track_tga():
    w, h = 64, 8
    return tga32(w, h, lambda x, y: (TRACK_EDGE if y in (0, h - 1) else TRACK_FILL) + (255,))


def thumb_tga():
    w = h = 16
    return tga32(w, h, lambda x, y: (THUMB_EDGE if x in (0, w - 1) or y in (0, h - 1) else THUMB_FILL) + (255,))


def build():
    """(resref, identifier, bytes) for the five edit-page textures, in table order."""
    luo = luo_arrays()
    return [
        ("e3d_gear", "kGearTex", luo["kLuoGear"]),
        ("e3d_gear_hi", "kGearHiTex", luo["kLuoGearHi"]),
        ("e3d_fill", "kFillTex", luo["kLuoFill"]),
        ("e3d_trk", "kTrackTex", track_tga()),
        ("e3d_thm", "kThumbTex", thumb_tga()),
    ]


def render_inc(blobs) -> str:
    out = ["// GENERATED by scripts/gen_shared_icons.py -- do not edit. Uncompressed 32-bit TGA images served from memory by the DLL.",
           "// Requires embtex::Tex { const char* resref; const unsigned char* data; unsigned size; } (EmbedTex.h).", ""]
    for _, ident, data in blobs:
        out.append(f"static const unsigned char {ident}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
    out.append("")
    out.append("static const embtex::Tex kEditTex[] = {")
    for name, ident, _ in blobs:
        out.append(f'    {{ "{name}", {ident}, sizeof {ident} }},')
    out.append("};")
    out.append(f"static const unsigned kEditTexCount = {len(blobs)};")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    blobs = build()
    text = render_inc(blobs)
    if a.check:
        if INC.exists() and INC.read_text() == text:
            return 0
        print(f"{INC} is missing or differs from regenerated output; run scripts/gen_shared_icons.py")
        return 1
    INC.write_text(text)
    print(f"wrote {INC} ({', '.join(f'{n} {len(d)} B' for n, _, d in blobs)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
