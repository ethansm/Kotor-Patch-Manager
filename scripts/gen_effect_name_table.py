"""Generate Patches/CharEffectsPanel/EffectNameTable.inc (Mod 14 Active Effects panel names) from the LIVE install.

Usage: gen_effect_name_table.py <game dir> <out.inc>

Two tables, both resolved against the live dialog.tlk (so compatch edits are included):
  kSpellRows[spells.2da row]       name text, iconresref (checked against the installed textures), spelldesc strref
                                   index = CGameEffect+0x1c (spell id of the caster when the effect was made)
  kEffIconRows[effecticon.2da row] name text (namestrref), iconresref, good (1 / 0 / -1 = no value)
                                   index = GetInteger(0) of an EffectIcon effect (type 0x43); this is the key of the
                                   engine's own effect-icon cache (creature+0xffc, FUN_005a43c0, research R2b)
  kFontTexW[256]                   dialogfont16x16 glyph widths in font texels (TXI upperleft/lowerright boxes, the
                                   character_page_mockup.font() reading); the DLL cuts names with "..." like its fit()
Names the bitmap font cannot draw are reduced to ASCII; rows without a name are nullptr.
"""
import glob
import logging
import os
import sys
import unicodedata

logging.disable(logging.CRITICAL)
from pykotor.extract.installation import Installation  # noqa: E402
from pykotor.resource.formats.erf import read_erf  # noqa: E402
from pykotor.resource.formats.twoda import read_2da  # noqa: E402
from pykotor.resource.type import ResourceType  # noqa: E402

game, out = sys.argv[1:3]
inst = Installation(game)
tlk = inst.talktable()
tex = set()
for f in glob.glob(game + "/TexturePacks/*.erf"):
    for x in read_erf(f):
        tex.add(str(x.resref).lower())
for f in os.listdir(game + "/override"):
    if f.lower().endswith((".tpc", ".tga")):
        tex.add(f.rsplit(".", 1)[0].lower())


def text(strref: str) -> str:
    if not strref.strip().lstrip("-").isdigit() or int(strref) < 0:
        return ""
    s = tlk.string(int(strref)) or ""
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return " ".join(s.split())


def c_str(s):
    if not s:
        return "nullptr"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def icon(resref: str):
    r = resref.strip().lower()
    return r if r and r in tex else None


sp = read_2da(inst.resource("spells", ResourceType.TwoDA).data)
ei = read_2da(inst.resource("effecticon", ResourceType.TwoDA).data)
missing = []
lines = ["// GENERATED by scripts/gen_effect_name_table.py -- do not hand-edit.",
         "struct SpellRow { const char* name; const char* icon; int descStrref; };",
         "struct EffIconRow { const char* name; const char* icon; int good; };   // good: 1 beneficial, 0 harmful, -1 unset",
         f"constexpr int kSpellRowCount = {sp.get_height()};",
         "constexpr SpellRow kSpellRows[kSpellRowCount] = {"]
for i in range(sp.get_height()):
    r = sp.get_row(i)
    ic_raw = r.get_string("iconresref")
    ic = icon(ic_raw)
    if ic_raw.strip() and not ic:
        missing.append(("spells", i, ic_raw))
    d = r.get_string("spelldesc").strip()
    lines.append(f"    /*{i}*/ {{ {c_str(text(r.get_string('name')))}, {c_str(ic)}, {int(d) if d.isdigit() else -1} }},")
lines += ["};", f"constexpr int kEffIconRowCount = {ei.get_height()};", "constexpr EffIconRow kEffIconRows[kEffIconRowCount] = {"]
for i in range(ei.get_height()):
    r = ei.get_row(i)
    ic_raw = r.get_string("iconresref")
    ic = icon(ic_raw)
    if ic_raw.strip() and not ic:
        missing.append(("effecticon", i, ic_raw))
    g = r.get_string("good").strip()
    lines.append(f"    /*{i}*/ {{ {c_str(text(r.get_string('namestrref')))}, {c_str(ic)}, {int(g) if g.isdigit() else -1} }},")
lines.append("};")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import character_page_mockup as L  # noqa: E402  (font reader shared with the mock-up)
_, boxes = L.font("dialogfont16x16")
w = [b[2] - b[0] for b in boxes]
lines += ["// dialogfont16x16 glyph widths in font texels (index = byte); drawn at 8/3 px per texel at 1600 px height",
          "constexpr unsigned char kFontTexW[256] = {"]
lines += ["    " + ", ".join(str(max(0, min(255, v))) for v in w[i:i + 16]) + "," for i in range(0, 256, 16)]
lines.append("};")
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"{sp.get_height()} spells rows, {ei.get_height()} effecticon rows -> {out}")
print("icons not installed (nullptr):", missing)
