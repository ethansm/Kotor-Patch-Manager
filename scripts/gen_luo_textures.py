#!/usr/bin/env python3
"""Generate the level-up-override gear button textures (luo_gear / luo_gear_hi) and embed them in the DLL source.

Writes patch_manager_mods/level_up_override_src/LuoTextures.inc (64x64 uncompressed 32-bit TGAs, same flavour as
gen_hotbar_textures.py) plus PNG previews in research/companion_levelup/r10/ui_icon/.

  (no args)  write the .inc and the PNG previews
  --check    regenerate in memory and compare with the existing .inc (exit 0 identical, 1 otherwise)
"""
import argparse
import io
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
INC = REPO / "patch_manager_mods/level_up_override_src/LuoTextures.inc"
PREVIEW = REPO / "research/companion_levelup/r10/ui_icon"
N, S = 64, 4
# name, C identifier, palette. Palette keys follow gen_hotbar_textures.make_edit_textures (the wrench): gradient top/bottom,
# dark outline, glow, lower-right shade, upper-left rim light. "hi" is the warm gold/beige variant (the wrench's hi frame is (208,204,170)).
PAL_NORMAL = dict(top=(175, 252, 228), bot=(28, 150, 122), outline=(6, 60, 50), glow=(60, 210, 175), shade=(10, 90, 74), light=(235, 255, 246))
PAL_HI = dict(top=(255, 246, 205), bot=(196, 156, 70), outline=(74, 56, 14), glow=(235, 200, 110), shade=(130, 98, 30), light=(255, 252, 235))
VARIANTS = (
    ("luo_gear", "kLuoGear", PAL_NORMAL),
    ("luo_gear_hi", "kLuoGearHi", PAL_HI),
)


def gear_mask(teeth=8, margin=5.0, depth=0.20, hole=0.25):
    """Gear body mask (teeth + centre hole cut out) and the final hole-clear disc, at S x supersample."""
    from PIL import Image, ImageDraw
    c = N * S / 2
    R = (N / 2 - margin) * S
    root = R * (1 - depth)
    pitch = 2 * math.pi / teeth
    half_tip = pitch * 0.25 * 0.80
    half_base = pitch * 0.25 * 1.10
    pts = []
    for k in range(teeth):
        a = k * pitch - math.pi / 2
        for ang, r in ((a - half_base, root), (a - half_tip, R), (a + half_tip, R), (a + half_base, root)):
            pts.append((c + r * math.cos(ang), c + r * math.sin(ang)))
    m = Image.new("L", (N * S, N * S), 0)
    d = ImageDraw.Draw(m)
    d.ellipse([c - root - 1, c - root - 1, c + root + 1, c + root + 1], fill=255)
    d.polygon(pts, fill=255)
    hr = R * hole
    clear = Image.new("L", m.size, 0)
    ImageDraw.Draw(clear).ellipse([c - hr, c - hr, c + hr, c + hr], fill=255)
    cut = Image.new("L", m.size, 0)   # body hole is 1 px larger so the dark outline ring sits inside the cleared disc's edge
    ImageDraw.Draw(cut).ellipse([c - hr - S, c - hr - S, c + hr + S, c + hr + S], fill=255)
    from PIL import ImageChops
    return ImageChops.subtract(m, cut), clear


def render(pal):
    """Gear glyph shaded with the wrench recipe: glow, dark outline, mint->teal gradient, lower-right shade, upper-left rim light."""
    from PIL import Image, ImageChops, ImageFilter
    m, clear = gear_mask()
    Z = m.size
    solid = lambda c: Image.new("RGBA", Z, c)
    im = Image.new("RGBA", Z, pal["glow"] + (0,))
    outline = m.filter(ImageFilter.MaxFilter(2 * S + 1))
    glow = m.filter(ImageFilter.MaxFilter(4 * S + 1)).filter(ImageFilter.GaussianBlur(S * 2.2)).point(lambda v: int(v * 0.55))
    im.paste(solid(pal["glow"] + (255,)), (0, 0), glow)
    im.paste(solid(pal["outline"] + (255,)), (0, 0), outline)
    grad = Image.new("RGBA", Z)
    gp = grad.load()
    y0, y1 = 3 * S, (N - 3) * S
    for y in range(Z[1]):
        t = min(1.0, max(0.0, (y - y0) / (y1 - y0)))
        c = tuple(int(pal["top"][i] + (pal["bot"][i] - pal["top"][i]) * t) for i in range(3)) + (255,)
        for x in range(Z[0]):
            gp[x, y] = c
    im.paste(grad, (0, 0), m)
    edge = lambda mk, dx, dy: ImageChops.subtract(mk, ImageChops.offset(mk, int(dx * S), int(dy * S)))
    im.paste(solid(pal["shade"] + (255,)), (0, 0), edge(m, -2.4, -2.4).filter(ImageFilter.GaussianBlur(S * 0.7)))
    im.paste(solid(pal["light"] + (255,)), (0, 0), edge(m, 2.2, 2.2).filter(ImageFilter.GaussianBlur(S * 0.6)))
    r, g, b, a = im.split()
    im = Image.merge("RGBA", (r, g, b, ImageChops.subtract(a, clear)))
    return im.resize((N, N), Image.LANCZOS)


def tga_bytes(im) -> bytes:
    buf = io.BytesIO()
    im.save(buf, format="TGA")
    return buf.getvalue()


def render_inc(blobs) -> str:
    out = ["// GENERATED by scripts/gen_luo_textures.py -- do not edit. Uncompressed 32-bit TGA images served from memory by the DLL.",
           "// Requires embtex::Tex { const char* resref; const unsigned char* data; unsigned size; } (EmbedTex.h).", ""]
    for _, ident, data in blobs:
        out.append(f"static const unsigned char {ident}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
    out.append("")
    out.append("static const embtex::Tex kLuoTex[] = {")
    for name, ident, data in blobs:
        out.append(f'    {{ "{name}", {ident}, sizeof {ident} }},')
    out.append("};")
    out.append(f"static const unsigned kLuoTexCount = {len(blobs)};")
    return "\n".join(out) + "\n"


def build():
    ims = [(n, i, render(p)) for n, i, p in VARIANTS]
    blobs = [(n, i, tga_bytes(im)) for n, i, im in ims]
    return ims, blobs


def compare(ims):
    """family_compare.png: the hotbar wrench (fph_edit / _hi, 72x128 frame) beside the gear glyphs, 4x nearest, on mid-grey."""
    import tempfile
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import gen_hotbar_textures as gh
    from PIL import Image
    with tempfile.TemporaryDirectory() as td:
        wr = [Image.open(p).convert("RGBA") for p in gh.make_edit_textures(Path(td))]
    k = 4
    sheet = Image.new("RGBA", (k * (72 * 2 + 64 * 2) + 5 * 16, k * 128 + 32), (40, 40, 40, 255))
    x = 16
    for im in wr + [i for _, _, i in ims]:
        im = im.resize((im.width * k, im.height * k), Image.NEAREST)
        sheet.alpha_composite(im, (x, 16 + (k * 128 - im.height) // 2))
        x += im.width + 16
    sheet.save(PREVIEW / "family_compare.png")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    ims, blobs = build()
    text = render_inc(blobs)
    if a.check:
        if INC.exists() and INC.read_text() == text:
            return 0
        print(f"{INC} is missing or differs from regenerated output; run scripts/gen_luo_textures.py")
        return 1
    from PIL import Image
    PREVIEW.mkdir(parents=True, exist_ok=True)
    INC.write_text(text)
    for n, _, im in ims:
        im.save(PREVIEW / f"{n}.png")
        im.resize((N * 8, N * 8), Image.NEAREST).save(PREVIEW / f"{n}_x8.png")
    compare(ims)
    print(f"wrote {INC} ({', '.join(f'{n} {len(d)} B' for n, _, d in blobs)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
