#!/usr/bin/env python3
"""Generate the holster-editor slider art textures (hse_sld_frame, hse_sld_wedge, hse_sld_mark) and embed them in the DLL source (stdlib only, deterministic).

Writes patch_manager_mods/_shared_src/SliderArtTex.inc (uncompressed 32-bit TGAs, same layout/format as ResetIconTex.inc / GearIconTex.inc):
  kSliderFrameTex  128x16 rounded-rectangle outline, teal, transparent inside
  kSliderWedgeTex  128x16 tapered wedge (thin at the left, tall at the right, like the vanilla Sound Options slider fill), teal, transparent elsewhere
  kSliderMarkTex   8x32 thin white double-arrow marker (vertical bar, small arrowheads up and down); 32 rather than 24 keeps power-of-two dimensions
  kSliderTex[] / kSliderTexCount   embtex::Tex table in that order

Art: coverage of an analytic shape, 4x4 supersampled for the alpha edge; teal is the gen_reset_icon.py PAL_NORMAL family (top -> bot vertical
gradient; HudKit kAccent {10,96,80} is the same hue family). The wedge sits inside the frame's inner edge so the two can be stacked at one rect.

  (no args)  write the .inc
  --check    regenerate in memory and compare with the existing .inc (exit 0 identical, 1 otherwise)
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_shared_icons import tga32            # same TGA writer as GearIconTex.inc  # noqa: E402
from gen_reset_icon import PAL_NORMAL, _mix   # same teal palette as the reset arrow  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
INC = REPO / "patch_manager_mods/_shared_src/SliderArtTex.inc"
SS = 4                       # supersample per axis
WIDE_W, WIDE_H = 128, 16     # frame and wedge
MARK_W, MARK_H = 8, 32       # marker
WHITE = (255, 255, 255)

# Frame: rounded rectangle outline (px). STROKE is the line width, RADIUS the corner radius (outer edge).
STROKE, RADIUS = 2.0, 6.0
# Wedge: left end x0 / right end x1, vertical half height at each end (centred on the row midline), inside the frame's inner edge (STROKE).
WEDGE_X0, WEDGE_X1 = 5.0, WIDE_W - 5.0
WEDGE_H0, WEDGE_H1 = 1.0, 5.0
# Marker: bar of BAR_W px centred on the texture, arrowheads HEAD_H tall spanning the full width at both ends.
BAR_W, HEAD_H = 2.0, 6.0


def _in_frame(x, y):
    """Inside the outline ring: inside the outer rounded rectangle, outside the inner one."""
    def rr(px, py, x0, y0, x1, y1, r):
        cx = min(max(px, x0 + r), x1 - r)
        cy = min(max(py, y0 + r), y1 - r)
        return (px - cx) ** 2 + (py - cy) ** 2 <= r * r and x0 <= px <= x1 and y0 <= py <= y1
    return rr(x, y, 0, 0, WIDE_W, WIDE_H, RADIUS) and not rr(x, y, STROKE, STROKE, WIDE_W - STROKE, WIDE_H - STROKE, RADIUS - STROKE)


def _in_wedge(x, y):
    if not WEDGE_X0 <= x <= WEDGE_X1:
        return False
    hh = WEDGE_H0 + (WEDGE_H1 - WEDGE_H0) * (x - WEDGE_X0) / (WEDGE_X1 - WEDGE_X0)
    return abs(y - WIDE_H / 2.0) <= hh


def _in_mark(x, y):
    cx = MARK_W / 2.0
    if abs(x - cx) <= BAR_W / 2.0 and HEAD_H - 1.0 <= y <= MARK_H - HEAD_H + 1.0:
        return True
    if y <= HEAD_H:                                   # up arrowhead: apex at the top centre, widening to the full width at y = HEAD_H
        return abs(x - cx) <= (cx - 0.5) * y / HEAD_H
    if y >= MARK_H - HEAD_H:                          # down arrowhead, mirrored
        return abs(x - cx) <= (cx - 0.5) * (MARK_H - y) / HEAD_H
    return False


def _teal(h):
    return lambda y: _mix(PAL_NORMAL["top"], PAL_NORMAL["bot"], min(1.0, max(0.0, y / (h - 1.0))))


SHAPES = (("hse_sld_frame", "kSliderFrameTex", WIDE_W, WIDE_H, _in_frame, _teal(WIDE_H)),
          ("hse_sld_wedge", "kSliderWedgeTex", WIDE_W, WIDE_H, _in_wedge, _teal(WIDE_H)),
          ("hse_sld_mark", "kSliderMarkTex", MARK_W, MARK_H, _in_mark, lambda y: WHITE))


def render(w, h, inside, colour):
    """-> pixel(x, y) callable for tga32 (y=0 top). Alpha = covered fraction of the SSxSS sub-samples."""
    px = {}
    for y in range(h):
        col = tuple(max(0, min(255, int(round(c)))) for c in colour(y + 0.5))
        for x in range(w):
            hit = sum(1 for sy in range(SS) for sx in range(SS) if inside(x + (sx + 0.5) / SS, y + (sy + 0.5) / SS))
            px[(x, y)] = col + (int(round(255.0 * hit / (SS * SS))),)
    return lambda x, y: px[(x, y)]


def build():
    """(resref, identifier, bytes) for the three slider textures, in table order."""
    return [(name, ident, tga32(w, h, render(w, h, inside, colour))) for name, ident, w, h, inside, colour in SHAPES]


def render_inc(blobs) -> str:
    out = ["// GENERATED by scripts/gen_slider_art.py -- do not edit. Uncompressed 32-bit TGA images served from memory by the DLL.",
           "// Requires embtex::Tex { const char* resref; const unsigned char* data; unsigned size; } (EmbedTex.h).", ""]
    for _, ident, data in blobs:
        out.append(f"static const unsigned char {ident}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
    out.append("")
    out.append("static const embtex::Tex kSliderTex[] = {")
    for name, ident, _ in blobs:
        out.append(f'    {{ "{name}", {ident}, sizeof {ident} }},')
    out.append("};")
    out.append(f"static const unsigned kSliderTexCount = {len(blobs)};")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    blobs = build()
    text = render_inc(blobs)
    if a.check:
        if INC.exists() and INC.read_text() == text:
            return 0
        print(f"{INC} is missing or differs from regenerated output; run scripts/gen_slider_art.py")
        return 1
    INC.write_text(text)
    print(f"wrote {INC} ({', '.join(f'{n} {len(d)} B' for n, _, d in blobs)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
