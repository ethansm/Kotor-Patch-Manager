#!/usr/bin/env python3
"""Generate patch_manager_mods/holster_src/HolsterShape.inc from the R17 fit survey.

Usage:
    python3 scripts/gen_holster_shape.py <R17.txt> <out.inc> [--check]

Without --check, writes <out.inc>. With --check, regenerates in memory and exits 0
only if the bytes equal <out.inc>; exits 1 on a mismatch or a missing <out.inc>.
Exits 1 on unreadable or malformed input. Argparse usage errors exit 2.
Stdlib only.
"""

import argparse
import os
import re
import sys
from collections import namedtuple

# Main-table row, e.g. "  8 Lightsaber   w_lghtsbr_001 ext=[x y z] c=[x y z] long=z ...".
# Matched against physical survey lines; the label may hold several tokens.
ROW_RE = re.compile(
    r"^\s*\d+\s+.+?\s+(w_\S+)\s+ext=\[([^\]]+)\]\s+c=\[([^\]]+)\]\s+long=([xyz])\b"
)
# Any line with a w_ stem before ext=[ must match ROW_RE, otherwise it is an error.
W_STEM_RE = re.compile(r"\s(w_\S+)\s+ext=\[")
EMPTY_RE = re.compile(r"\bEMPTY\b")
C_SAFE_RE = re.compile(r"[a-z0-9_]+")
FAMILY_SUFFIX_RE = re.compile(r"_[0-9]+$")
AXIS_BY_LETTER = {"x": 0, "y": 1, "z": 2}
OUTLIER_MARK = "# OUTLIERS"

Row = namedtuple("Row", "lineno stem ext c letter")
Entry = namedtuple("Entry", "stem axis length c exit_sign exit_len")

# (families, exitSign, exitLen metres). exitSign is the sign along the long axis;
# 0 = no long-axis exit or sign not measured. All exitLen values are GUESS per r2 Q4
# (.claude/research/holster_hw29/r2_stems.md:60-66). The -1 on the melee and staff rows
# extends r2:63 ("melee blades (back)"), which was measured on blades only: GUESS.
FAMILY_EXIT_ROWS = (
    (("w_lghtsbr", "w_shortsbr"), 0, 0.08),
    (("w_dblsbr", "w_qtrstaff"), 0, 0.10),
    (
        (
            "w_lngswrd", "w_shortswrd", "w_dblswrd", "w_vbrdblswd", "w_vbroswrd",
            "w_vbroshort", "w_stunbaton", "w_waraxe", "w_gaffi", "w_warblade",
        ),
        -1,
        0.12,
    ),
    (("w_blstrpstl", "w_hvyblstr", "w_hldoblst", "w_ionblstr", "w_dsrptpstl", "w_sonicpstl"), 0, 0.12),
    (("w_blstrrfl", "w_blstrcrbn", "w_bowcstr", "w_ionrfl", "w_dsrptrfl", "w_sonicrfl"), 0, 0.25),
    (("w_rptnblstr", "w_hvrptbltr"), 0, 0.45),
)
# Families not listed (w_forcepike, grenades, w_thermdet, ...) get DEFAULT_EXIT.
DEFAULT_EXIT = (0, 0.0)


def _build_family_exit():
    table = {}
    for families, sign, length in FAMILY_EXIT_ROWS:
        for family in families:
            if family in table:
                raise ValueError(f"family listed twice in FAMILY_EXIT_ROWS: {family}")
            table[family] = (sign, length)
    return table


FAMILY_EXIT = _build_family_exit()


def _floats(text, count):
    values = tuple(float(tok) for tok in text.split())
    if len(values) != count:
        raise ValueError(f"expected {count} numbers, got {text.strip()!r}")
    return values


def parse_rows(lines):
    """Return main-table w_ rows in file order, stopping at the OUTLIERS marker."""
    rows = []
    for lineno, line in enumerate(lines, start=1):
        if line.startswith(OUTLIER_MARK):
            break
        if not line.strip() or EMPTY_RE.search(line):
            continue
        match = ROW_RE.match(line)
        if match:
            stem, ext, c, letter = match.groups()
            rows.append(Row(lineno, stem.lower(), _floats(ext, 3), _floats(c, 3), letter))
        elif W_STEM_RE.search(line):
            raise ValueError(f"line {lineno}: w_ row does not match the survey row format")
    return rows


def dedup(rows):
    """Keep the first row per stem.

    An identical repeat (same ext, c, long) is dropped silently. A repeat that differs
    is dropped and reported as a dup conflict line.
    """
    first = {}
    kept = []
    conflicts = []
    for row in rows:
        prev = first.get(row.stem)
        if prev is None:
            first[row.stem] = row
            kept.append(row)
        elif (prev.ext, prev.c, prev.letter) != (row.ext, row.c, row.letter):
            conflicts.append(
                f"// dup conflict {row.stem}: kept line {prev.lineno}, dropped line {row.lineno}"
            )
    return kept, conflicts


def build_entries(kept):
    entries = []
    for row in kept:
        if not C_SAFE_RE.fullmatch(row.stem):
            raise ValueError(f"line {row.lineno}: stem is not C-safe: {row.stem!r}")
        axis = AXIS_BY_LETTER[row.letter]
        family = FAMILY_SUFFIX_RE.sub("", row.stem)
        exit_sign, exit_len = FAMILY_EXIT.get(family, DEFAULT_EXIT)
        entries.append(Entry(row.stem, axis, row.ext[axis], row.c, exit_sign, exit_len))
    entries.sort(key=lambda e: e.stem)
    return entries


def fmt_float(value):
    text = "%.4f" % value
    if text == "-0.0000":
        text = "0.0000"
    return text + "f"


def render(entries, conflicts, source_name):
    lines = [
        f"// generated by scripts/gen_holster_shape.py from {source_name}; do not edit",
        *conflicts,
        "struct ShapeEntry { const char* stem; unsigned char axis; float len; float c[3]; "
        "signed char exitSign; float exitLen; };",
        "static const ShapeEntry kShapes[] = {",
    ]
    for e in entries:
        c0, c1, c2 = (fmt_float(v) for v in e.c)
        lines.append(
            f'    {{ "{e.stem}", {e.axis}, {fmt_float(e.length)}, {{ {c0}, {c1}, {c2} }}, '
            f"{e.exit_sign}, {fmt_float(e.exit_len)} }},"
        )
    lines.append("};")
    lines.append(f"static const unsigned kShapeCount = {len(entries)};")
    return "\n".join(lines) + "\n"


def generate_text(survey_text, source_name):
    rows = parse_rows(survey_text.splitlines())
    if not rows:
        raise ValueError("no w_ rows found before the '# OUTLIERS' marker")
    kept, conflicts = dedup(rows)
    return render(build_entries(kept), conflicts, source_name)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate HolsterShape.inc from the R17 survey.")
    parser.add_argument("r17", help="path to R17_fit_survey_2026-09-29.txt")
    parser.add_argument("out", help="path of the .inc to write (or check with --check)")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 0 only if <out> already matches the regenerated output",
    )
    args = parser.parse_args(argv)

    try:
        with open(args.r17, encoding="utf-8") as fh:
            survey_text = fh.read()
        text = generate_text(survey_text, os.path.basename(args.r17))
    except (OSError, ValueError) as exc:
        print(f"gen_holster_shape: {exc}", file=sys.stderr)
        return 1

    if args.check:
        try:
            with open(args.out, "rb") as fh:
                current = fh.read()
        except OSError as exc:
            print(f"gen_holster_shape: cannot read {args.out}: {exc}", file=sys.stderr)
            return 1
        if current != text.encode("utf-8"):
            print(
                f"gen_holster_shape: {args.out} is stale; rerun without --check",
                file=sys.stderr,
            )
            return 1
        return 0

    try:
        with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    except OSError as exc:
        print(f"gen_holster_shape: cannot write {args.out}: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
