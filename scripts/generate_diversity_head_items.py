#!/usr/bin/env python3
"""Generate patch_manager_mods/npc_diversity_src/DiversityHeadItems.h from head_items_source.json (stdlib only, byte-stable).

Usage: generate_diversity_head_items.py [--source FILE] [--out FILE] [--check]
  --check  exit 1 (and write nothing) when the header on disk differs from the generated text.

Per appearance row and head item: when base_ok fails the item is in neither set; otherwise it is `restricted` when
the item has restrictions and `allowed` when it has none. `observed` = the head items the vanilla scan lists for the row.
Items are indexed in ascending resref order (uint64 bitsets, so at most 64 items).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "patch_manager_mods/npc_diversity_src"
SOURCE = SRC / "head_items_source.json"
OUT = SRC / "DiversityHeadItems.h"
MAX_ITEMS = 64
RESREF = re.compile(r"[A-Za-z0-9_]+")


def race_ok(rule, race):
    if rule == 0:
        return True
    if rule == 1:
        return race == 6
    if rule == 2:
        return race == 5
    return False


def gender_ok(mask, gender):
    return ((mask >> gender) & 1) == 0


def base_ok(baseitem_row, appearance):
    if baseitem_row["req_feats"]:
        return False
    return (any(race_ok(baseitem_row["race_rule"], r) for r in appearance["races"])
            and any(gender_ok(baseitem_row["gender_mask"], g) for g in appearance["genders"]))


def model(doc):
    """Return (items, apps, unknown).

    items: [(resref, baseitem, flags, restrictionCount)] in resref order.
    apps: [dict(row, flags, raceMask, allowed, restricted, observed)] in ascending row order.
    unknown: [(row, resref)] head_items refs that are not in items (ignored).
    """
    baseitems = doc["baseitems"]
    names = sorted(doc["items"])
    if not 1 <= len(names) <= MAX_ITEMS:
        raise SystemExit("head item count %d outside 1..%d (uint64 bitsets)" % (len(names), MAX_ITEMS))
    index, items, defs = {}, [], []
    for i, name in enumerate(names):
        if not RESREF.fullmatch(name):
            raise SystemExit("resref %r is not a plain identifier" % name)
        it = doc["items"][name]
        if not 0 <= it["baseitem"] <= 0xFFFF:
            raise SystemExit("%s: baseitem %r outside uint16" % (name, it["baseitem"]))
        if len(it["restrictions"]) > 255:
            raise SystemExit("%s: more than 255 restrictions" % name)
        bi = baseitems[str(it["baseitem"])]
        flags = (1 if bi["race_rule"] == 2 else 0) | (2 if it["restrictions"] else 0)
        items.append((name, it["baseitem"], flags, len(it["restrictions"])))
        index[name] = i
        defs.append((bi, bool(it["restrictions"])))
    apps, unknown = [], []
    for key in sorted(doc["appearances"], key=int):
        a = doc["appearances"][key]
        row = int(key)
        if not 0 <= row <= 0xFFFF:
            raise SystemExit("appearance row %d outside uint16" % row)
        if a["modeltype"] not in ("B", "F", "L"):
            raise SystemExit("row %d: modeltype %r not B|F|L" % (row, a["modeltype"]))
        allowed = restricted = observed = 0
        for i, (bi, has_restr) in enumerate(defs):
            if base_ok(bi, a):
                if has_restr:
                    restricted |= 1 << i
                else:
                    allowed |= 1 << i
        for ref in a["head_items"]:
            if ref in index:
                observed |= 1 << index[ref]
            else:
                unknown.append((row, ref))
        race_mask = 0
        for race in a["races"]:
            if not 0 <= race <= 7:
                raise SystemExit("row %d: race %d outside 0..7" % (row, race))
            race_mask |= 1 << race
        flags = ((1 if a["modeltype"] == "B" else 0)
                 | (2 if a["has_goggle_hook"] == "yes" else 0)
                 | (4 if observed else 0))
        apps.append({"row": row, "flags": flags, "raceMask": race_mask,
                     "allowed": allowed, "restricted": restricted, "observed": observed})
    return items, apps, unknown


def render(doc, notes=None):
    items, apps, unknown = model(doc)
    if notes is not None and unknown:
        notes.append("note: %d head_item ref(s) not in items, ignored: %s"
                     % (len(unknown), ", ".join("row %d %s" % p for p in unknown)))
    n, m = len(items), len(apps)
    lines = [
        "// DiversityHeadItems.h -- GENERATED by scripts/generate_diversity_head_items.py from head_items_source.json. Do not edit.",
        "// Head-item rule model per appearance row: base-item race, gender and feat rules, restrictions, vanilla-observed items.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace diversity_head_items {",
        "",
        "// Items in resref order. flags bit0 = droid item (race rule 2), bit1 = has restrictions.",
        "struct HeadItem { const char* resref; uint16_t baseitem; uint8_t flags; uint8_t restrictionCount; };",
        "inline constexpr HeadItem kHeadItems[%d] = {" % n,
    ]
    for name, bid, flags, count in items:
        lines.append('    {"%s", %d, 0x%02X, %d},' % (name, bid, flags, count))
    lines += [
        "};",
        "inline constexpr unsigned kHeadItemCount = %d;" % n,
        "",
        "// Appearances in ascending row order. flags bit0 = modeltype B, bit1 = has GoggleHook, bit2 = observed wearing.",
        "// raceMask bit r = race r observed (races 0..7). allowed/restricted/observed are bitsets over kHeadItems indices.",
        "struct HeadAppearance { uint16_t row; uint8_t flags; uint8_t raceMask; uint64_t allowed; uint64_t restricted; uint64_t observed; };",
        "inline constexpr HeadAppearance kHeadAppearances[%d] = {" % m,
    ]
    for a in apps:
        lines.append("    {%d, 0x%02X, 0x%02X, 0x%016XULL, 0x%016XULL, 0x%016XULL},"
                     % (a["row"], a["flags"], a["raceMask"], a["allowed"], a["restricted"], a["observed"]))
    lines += [
        "};",
        "inline constexpr unsigned kHeadAppearanceCount = %d;" % m,
        "",
        "// Binary search over kHeadAppearances (sorted by row); nullptr when the row has no entry.",
        "inline constexpr const HeadAppearance* findAppearance(uint16_t row) {",
        "    unsigned lo = 0;",
        "    unsigned hi = kHeadAppearanceCount;",
        "    while (lo < hi) {",
        "        unsigned mid = lo + (hi - lo) / 2;",
        "        if (kHeadAppearances[mid].row < row) {",
        "            lo = mid + 1;",
        "        } else {",
        "            hi = mid;",
        "        }",
        "    }",
        "    return (lo < kHeadAppearanceCount && kHeadAppearances[lo].row == row) ? &kHeadAppearances[lo] : nullptr;",
        "}",
        "",
        "// True when head item idx is in the allowed set (base rules pass and the item has no restrictions).",
        "inline constexpr bool itemAllowed(const HeadAppearance& a, unsigned idx) {",
        "    return idx < 64 && ((a.allowed >> idx) & 1ULL) != 0;",
        "}",
        "",
        "} // namespace diversity_head_items",
    ]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--source", default=str(SOURCE))
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    notes = []
    text = render(json.loads(Path(a.source).read_text()), notes)
    for note in notes:
        print(note, file=sys.stderr)
    out = Path(a.out)
    if a.check:
        if not out.exists() or out.read_text() != text:
            print("DiversityHeadItems.h is stale: run scripts/generate_diversity_head_items.py")
            return 1
        print("DiversityHeadItems.h up to date")
        return 0
    out.write_text(text)
    print("wrote %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
