#!/usr/bin/env python3
"""Generate patch_manager_mods/equipment_3d_character_src/EquipWeaponTable.inc from the installed baseitems.2da.

Mod 5 weapons: base item row -> model itemclass (model = "<itemclass>_%03d" with the item's variation) and WeaponWield
(stance idle = "g<weaponwield>r1", verified in animations.2da: g1r1..g10r1 = "*_Melee_Idle", looping)."""
import logging, sys
from pathlib import Path
logging.disable(logging.CRITICAL)
from pykotor.extract.installation import Installation
from pykotor.resource.type import ResourceType
from pykotor.resource.formats.twoda import read_2da

GAME = Path.home() / ".local/share/Steam/steamapps/common/Knights of the Old Republic II"
OUT = Path(__file__).resolve().parent.parent / "patch_manager_mods/equipment_3d_character_src/EquipWeaponTable.inc"
b = read_2da(Installation(str(GAME)).resource("baseitems", ResourceType.TwoDA).data)
n = b.get_height()
lines = ["// Generated by scripts/gen_equip3d_weapon_table.py from baseitems.2da - do not edit.",
         "// {itemclass, weaponwield (0 = not a wieldable weapon)}", f"static const int kWeaponRows = {n};",
         "struct WeaponRow { const char* cls; unsigned char wield; };", "static const WeaponRow kWeapon[] = {"]
for i in range(n):
    d = b.get_row(i)._data
    ww = d.get("weaponwield", "").strip()
    ww = int(ww) if ww.isdigit() else 0
    cls = d.get("itemclass", "").strip() if ww else ""
    lines.append(f'    {{"{cls}", {ww}}}, // {i} {d.get("label","")}')
lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({n} rows, {sum(1 for l in lines if l.startswith('    {\"') and not l.startswith('    {\"\",'))} weapon rows)")
