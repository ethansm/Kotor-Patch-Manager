#!/usr/bin/env python3
"""Generate patch_manager_mods/npc_diversity_src/DiversitySlots.h from texture_labels.json (stdlib only, byte-stable).

Usage: generate_diversity_slots.py [--labels FILE] [--out FILE] [--check]
  --check  exit 1 (and write nothing) when the header on disk differs from the generated text.

Families (by the body of the FINAL appearance row): M (generic male + Twi'lek male), F (generic female + Twi'lek female),
FatM (row 802), FatF (row 803). A slot is listed for a family when its label says layout_ok[family] == "yes".
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "patch_manager_mods/npc_diversity_src"
LABELS = SRC / "texture_labels.json"
OUT = SRC / "DiversitySlots.h"
FAMILIES = (("M", "kMaleSlots"), ("F", "kFemaleSlots"), ("FatM", "kFatMaleSlots"), ("FatF", "kFatFemaleSlots"))
MUST_KEEP = (6, 9)   # vanilla default tv of every commoner: must stay allowed in M and F


def allowlists(doc):
    out = {}
    for fam, _ in FAMILIES:
        out[fam] = sorted(s["slot"] for s in doc["slots"].values() if s["layout_ok"].get(fam) == "yes")
    return out


def render(doc):
    al = allowlists(doc)
    for fam in ("M", "F"):
        for slot in MUST_KEEP:
            if slot not in al[fam]:
                raise SystemExit("slot %02d missing from family %s (vanilla default tv must stay allowed)" % (slot, fam))
    for fam, v in al.items():
        if any(not 1 <= x <= 255 for x in v):
            raise SystemExit("slot out of uint8 range in %s" % fam)
    lines = [
        "// DiversitySlots.h -- GENERATED by scripts/generate_diversity_slots.py from texture_labels.json. Do not edit.",
        "// Per body family, the N_Comm%02d texture slots verified as clothing for that mesh (layout and category).",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace NpcDiversity {",
        "",
    ]
    for fam, name in FAMILIES:
        v = al[fam]
        body = ", ".join(str(x) for x in v) if v else "0"
        lines.append("// %s: %d slot(s)" % (fam, len(v)))
        lines.append("constexpr uint8_t %s[] = {%s};" % (name, body))
        lines.append("constexpr size_t %sCount = %d;" % (name, len(v)))
        lines.append("")
    lines.append("} // namespace NpcDiversity")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--labels", default=str(LABELS))
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render(json.loads(Path(a.labels).read_text()))
    out = Path(a.out)
    if a.check:
        if not out.exists() or out.read_text() != text:
            print("DiversitySlots.h is stale: run scripts/generate_diversity_slots.py")
            return 1
        print("DiversitySlots.h up to date")
        return 0
    out.write_text(text)
    print("wrote %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
