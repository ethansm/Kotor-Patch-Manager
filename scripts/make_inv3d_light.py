#!/usr/bin/env python3
"""Build the `inv3d_light` rig for Mod 1 v2 from the game's `upgitem_light` (byte-level name edits only).

Renames (NUL-padded in place, never longer):
  upgitem_light -> inv3d_light   (every NUL-terminated occurrence: model name, root node, ...)
  rotatehook*   -> xotatehook*   (so the engine never attaches the item to an animated hook)
  camerahook3   -> camerahook    (the fallback hook name: up axis = world Z, so vertical models stay vertical)
  camerahook<other> -> xamerahook<other>
Also writes Patches/Inventory3DViewport/RigCamera.inc (camera rest pose in model space).

  make_inv3d_light.py            build + verify into the staging dir (no game writes)
  make_inv3d_light.py --deploy   also copy to $GAME/override (backup dir records pre-existence)
  make_inv3d_light.py --rollback remove our files / restore the backup
"""
import argparse, datetime, json, logging, re, shutil, struct, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import inv3d_model_fit as fit  # noqa: E402

GAME = Path.home() / ".local/share/Steam/steamapps/common/Knights of the Old Republic II"
WS = Path.home() / "Games/KOTOR2_Mod_Workspace"
STAGE = WS / "staging/inv3d_light"
BACKUPS = WS / "backups"
INC = WS / "tools/kotor-patch-manager/Patches/Inventory3DViewport/RigCamera.inc"
SRC, DST = "upgitem_light", "inv3d_light"


def new_name(old: str):
    if old.lower() == SRC:
        return DST
    if old.lower().startswith("rotatehook"):
        return "xotatehook" + old[len("rotatehook"):]
    if old.lower() == "camerahook3":
        return "camerahook"
    if old.lower().startswith("camerahook"):
        return "xamerahook" + old[len("camerahook"):]
    return None


def patch_bytes(mdl: bytes):
    b = bytearray(mdl)
    d0 = 12
    u32 = lambda o: struct.unpack_from("<I", b, d0 + o)[0]
    names_off, cnt = u32(184), u32(188)
    allowed, log = [], []
    for i in range(cnt):
        p = d0 + u32(names_off + 4 * i)
        e = b.index(b"\0", p)
        old = bytes(b[p:e]).decode("latin1")
        new = new_name(old)
        if new is None:
            continue
        assert len(new) <= len(old), (old, new)
        b[p:e] = new.encode() + b"\0" * (len(old) - len(new))
        allowed.append((p, e + 1))
        log.append((p, old, new))
    # remaining NUL-terminated occurrences of the source model name (32-byte model-name fields, supermodel, anims)
    for m in re.finditer(re.escape(SRC.encode()) + rb"\0", bytes(b), re.I):
        p = m.start()
        b[p:p + len(SRC)] = DST.encode() + b"\0" * (len(SRC) - len(DST))
        allowed.append((p, p + len(SRC) + 1))
        log.append((p, SRC, DST + " (model-name field)"))
    return bytes(b), allowed, log


def find_node(n, name, q=(1, 0, 0, 0), p=(0, 0, 0), top=True):
    q2 = q if top else fit.qnorm(fit.qmul(q, n.quat))
    p2 = p if top else tuple(a + b for a, b in zip(p, fit.qrot(q, n.pos)))
    if n.name == name:
        return n, q2, p2
    for c in n.children:
        r = find_node(c, name, q2, p2, False)
        if r:
            return r
    return None


def emit_inc(path: Path, pos, q):
    fwd, up, right = (fit.qrot(q, v) for v in ((0, 0, -1), (0, 1, 0), (1, 0, 0)))
    f = lambda v: ", ".join("%.6ff" % (0.0 if abs(c) < 1e-6 else c) for c in v)
    path.write_text(
        "// Generated by scripts/make_inv3d_light.py from inv3d_light node 'camerahook' rest pose (model space, w-first quat).\n"
        "// Aurora camera: looks down local -Z, up local +Y, right local +X.\n"
        f"static const float kRigCamPos[3]   = {{ {f(pos)} }};\n"
        f"static const float kRigCamFwd[3]   = {{ {f(fwd)} }};\n"
        f"static const float kRigCamUp[3]    = {{ {f(up)} }};\n"
        f"static const float kRigCamRight[3] = {{ {f(right)} }};\n")
    return fwd, up, right


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--deploy", action="store_true")
    ap.add_argument("--rollback", action="store_true")
    a = ap.parse_args()
    ovr = GAME / "override"

    if a.rollback:
        dirs = sorted(BACKUPS.glob("inv3d_light_*"))
        if not dirs:
            print("no backup dir; removing our files if present")
        rec = json.loads((dirs[0] / "record.json").read_text()) if dirs else {"preexisting": []}
        for ext in ("mdl", "mdx"):
            t = ovr / f"inv3d_light.{ext}"
            if t.name in rec["preexisting"]:
                shutil.copy2(dirs[0] / t.name, t); print("restored", t)
            elif t.exists():
                t.unlink(); print("removed", t)
        return 0

    logging.disable(logging.CRITICAL)
    from pykotor.extract.installation import Installation
    inst = Installation(str(GAME))
    logging.disable(logging.NOTSET)
    for ext in ("mdl", "mdx"):
        hit = [p for p in ovr.iterdir() if p.name.lower() == f"{SRC}.{ext}"]
        print(f"{SRC}.{ext}: {'override copy' if hit else 'BIF copy'}")
    mdl, mdx = fit.load_model(inst, SRC)
    print(f"source sizes: mdl {len(mdl)} mdx {len(mdx)}")
    out, allowed, log = patch_bytes(mdl)
    for p, o, n in log:
        print(f"  @0x{p:x}: {o!r} -> {n!r}")

    # verify
    r0, n0 = fit.parse_model(mdl, mdx)
    r1, n1 = fit.parse_model(out, mdx)
    def flat(n):
        return [n] + [x for c in n.children for x in flat(c)]
    f0, f1 = flat(r0), flat(r1)
    assert len(f0) == len(f1), "node count changed"
    names1 = [n.name for n in f1]
    assert names1.count("camerahook") == 1, names1.count("camerahook")
    assert not [x for x in names1 if x.lower().startswith("rotatehook")]
    assert n1 == DST, n1
    lights0 = sorted(n.name for n in f0 if n.flags & fit.NT_LIGHT)
    assert lights0 and lights0 == sorted(n.name for n in f1 if n.flags & fit.NT_LIGHT)
    o3 = next(n for n in f0 if n.name == "camerahook3")
    ch = next(n for n in f1 if n.name == "camerahook")
    assert o3.pos == ch.pos and o3.quat == ch.quat
    try:
        from pykotor.resource.formats.mdl import read_mdl
        m = read_mdl(out, source_ext=mdx)
        pk = [n.name for n in m.all_nodes()]
        assert pk.count("camerahook") == 1 and not [x for x in pk if x.lower().startswith("rotatehook")]
        print(f"pykotor read_mdl OK ({len(pk)} nodes)")
    except Exception as e:  # pykotor's mdl reader is only a cross-check
        print("pykotor read_mdl cross-check skipped/failed:", repr(e)[:150])
    # byte diff
    diff = [i for i in range(len(mdl)) if mdl[i] != out[i]]
    bad = [i for i in diff if not any(s <= i < e for s, e in allowed)]
    print(f"byte diff: {len(diff)} bytes differ; outside name fields: {len(bad)}")
    assert not bad and len(out) == len(mdl)

    STAGE.mkdir(parents=True, exist_ok=True)
    (STAGE / "inv3d_light.mdl").write_bytes(out)
    (STAGE / "inv3d_light.mdx").write_bytes(mdx)
    print("staged:", STAGE)
    _, q, p = find_node(r1, "camerahook")
    fwd, up, right = emit_inc(INC, p, q)
    print("camerahook world pos", tuple(round(c, 4) for c in p), "quat(w,x,y,z)", tuple(round(c, 4) for c in q))
    print("fwd", tuple(round(c, 3) for c in fwd), "up", tuple(round(c, 3) for c in up), "right", tuple(round(c, 3) for c in right))
    print("wrote", INC)

    if a.deploy:
        bd = BACKUPS / f"inv3d_light_{datetime.datetime.now():%Y%m%d_%H%M%S}"
        bd.mkdir(parents=True)
        pre = []
        for ext in ("mdl", "mdx"):
            t = ovr / f"inv3d_light.{ext}"
            if t.exists():
                pre.append(t.name); shutil.copy2(t, bd / t.name)
            shutil.copy2(STAGE / t.name, t)
        (bd / "record.json").write_text(json.dumps({"preexisting": pre}))
        print("deployed to", ovr, "backup", bd)
    return 0


if __name__ == "__main__":
    sys.exit(main())
