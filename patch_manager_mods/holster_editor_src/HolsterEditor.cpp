// H-O1 0x8A16FE: Options ctor, layout open, all vanilla InitControl calls done; panel = [ebp-0xAC].
extern "C" void __cdecl OptBindView(int panelArg) {
    if (!g_enabled || !panelArg) return;
    saferead::beginScope();
    const uintptr_t P = static_cast<uintptr_t>(static_cast<unsigned>(panelArg));
    uint32_t vt = 0, slot = 0;
    int flags48 = 0, count = 0;
    (void)rd<uint32_t>(P, 0, &vt);
    (void)rd<uint32_t>(P, embedgui::PanelLayoutSlot, &slot);
    (void)rd<int>(P, ctlFlagsOff(), &flags48);
    (void)rd<int>(P, k2addr::off(&K2AddrTable::Panel_CtlCount), &count);
    KP_LOG(chMain, "CTOR panel=%x vt=%x (expect %x) flags48=%x layout=%x controls=%d", static_cast<unsigned>(P), static_cast<unsigned>(vt),
           static_cast<unsigned>(kOptionsVtable), static_cast<unsigned>(flags48), static_cast<unsigned>(slot), count);
    if (g_ed.panel && g_ed.panel != P) KP_LOG(chMain, "CTOR previous panel %x was not destroyed through the hook: state reset", static_cast<unsigned>(g_ed.panel));
    g_ed = Editor();
    if (vt != kOptionsVtable || !(flags48 & 2) || !slot) { KP_LOG(chMain, "CTOR refused: not the open Options layout"); return; }
    g_ed.panel = P;
    g_ed.vanillaCount = count;
    const bool p3 = g_p3.connect(), hol = g_hol.connect();
    KP_LOG(chMain, "CTOR providers preview3d=%d holster=%d", p3 ? 1 : 0, hol ? 1 : 0);

    // Embedded layout window: P+0x30 = our handle only for the preview's InitControl, then restored before anything else.
    embedgui::Handle h = embedgui::Open(reinterpret_cast<unsigned char*>(P), kHseViewGui, static_cast<unsigned>(sizeof kHseViewGui));
    KP_LOG(chEmbed, "EMBED open obj=%p saved=%p bytes=%u", h.obj, h.saved, static_cast<unsigned>(sizeof kHseViewGui));
    if (h.obj && p3) {
        g_ed.token = g_p3.p->CreateView(reinterpret_cast<void*>(P), "HSE_VIEW");
        g_ed.view = g_ed.token ? reinterpret_cast<uintptr_t>(g_p3.p->ViewControl(g_ed.token)) : 0;
        int after = 0;
        (void)rd<int>(P, k2addr::off(&K2AddrTable::Panel_CtlCount), &after);
        KP_LOG(chEmbed, "EMBED view token=%u ctl=%x id=%d (expect -1: not listed) controls=%d (was %d)", g_ed.token, static_cast<unsigned>(g_ed.view),
               ctlId(g_ed.view), after, count);
    }
    embedgui::Close(reinterpret_cast<unsigned char*>(P), h);
    uint32_t back = 0;
    (void)rd<uint32_t>(P, embedgui::PanelLayoutSlot, &back);
    KP_LOG(chEmbed, "EMBED restore layout=%x (expect %x) %s", static_cast<unsigned>(back), static_cast<unsigned>(slot), back == slot ? "ok" : "MISMATCH");
    if (back != slot) {   // never touch the layout again if the restore did not hold
        if (g_ed.token && g_p3.ok()) g_p3.p->Destroy(g_ed.token);   // review F4 (the unlisted view block itself stays: the token still points at it)
        g_ed = Editor();
        return;
    }

    // Buttons and labels from the vanilla layout (open until StopLoadFromLayout right after this hook).
    g_ed.btn = cloneEntry(P, "BTN_GAMEPLAY", "btn_holster", &g_ed.btnIsButton);
    g_ed.back = cloneEntry(P, "BTN_EXIT", "back", &g_ed.backIsButton);
    g_ed.title = cloneLabel(P, "title");
    g_ed.status = cloneLabel(P, "status");
}

// H-O2 0x40EC90: CSWGuiPanel::Draw (ECX = panel). HOT: every panel, every frame.
extern "C" void __cdecl OptTick(int panelArg) {
    if (!g_enabled || !panelArg) return;
    if (*reinterpret_cast<const uint32_t*>(static_cast<uintptr_t>(static_cast<unsigned>(panelArg))) != kOptionsVtable) return;   // ECX is Draw's this
    const uintptr_t P = static_cast<uintptr_t>(static_cast<unsigned>(panelArg));
    saferead::beginScope();
    Editor& e = g_ed;
    if (P != e.panel) {
        static volatile LONG s_other = 0;
        if (InterlockedIncrement(&s_other) <= 4) KP_LOG(chMain, "HIDDENDRAW options draw for an unbound panel %x (bound %x)", static_cast<unsigned>(P), static_cast<unsigned>(e.panel));
        return;
    }
    const DWORD now = GetTickCount();
    const DWORD gap = e.lastTick ? now - e.lastTick : 0;
    e.lastTick = now;
    int flags48 = 0;
    (void)rd<int>(P, ctlFlagsOff(), &flags48);
    static volatile LONG s_hd = 0;
    if ((flags48 != e.lastFlags48 || gap > kTickGapMs) && InterlockedIncrement(&s_hd) <= 32)
        KP_LOG(chMain, "HIDDENDRAW panel=%x flags48=%x (was %x) gap=%lums editor=%d", static_cast<unsigned>(P), static_cast<unsigned>(flags48),
               static_cast<unsigned>(e.lastFlags48), static_cast<unsigned long>(gap), e.editor ? 1 : 0);
    e.lastFlags48 = flags48;
    if (e.editor && gap > kTickGapMs) leaveEditor("tick gap");
    if (!e.appended) firstTick();
    g_p3.poll();
    g_hol.poll();
    applyTargets(e, false);

    int x = 0, y = 0;
    const bool cur = guikit::cursorEngine(&x, &y);
    hoverTick(P, cur, x, y);

    // Clicks act on the RELEASE: LMB up over the control the press went down on. Not-foreground counts as up (GuiKit clickEdge rule).
    const bool down = guikit::g_gk.gameForeground && guikit::g_gk.lbuttonDown && guikit::g_gk.gameForeground() && guikit::g_gk.lbuttonDown();
    const bool overBtn = cur && !e.editor && e.btn && guikit::hit(e.btn, x, y);
    const bool overBack = cur && e.editor && e.back && guikit::hit(e.back, x, y);
    if (down && !e.prevDown) {
        e.pressed = overBtn ? 1 : (overBack ? 2 : 0);
        static volatile LONG s_in = 0;
        if (InterlockedIncrement(&s_in) <= 40)
            KP_LOG(chInput, "INPUTCLASS press cur=%d x=%d y=%d hitBtn=%d hitBack=%d editor=%d", cur ? 1 : 0, x, y, overBtn ? 1 : 0, overBack ? 1 : 0, e.editor ? 1 : 0);
    } else if (!down && e.prevDown) {
        const int pressed = e.pressed;
        e.pressed = 0;
        static volatile LONG s_up = 0;
        if (pressed && InterlockedIncrement(&s_up) <= 40)
            KP_LOG(chInput, "INPUTCLASS release pressed=%d overBtn=%d overBack=%d editor=%d", pressed, overBtn ? 1 : 0, overBack ? 1 : 0, e.editor ? 1 : 0);
        if (pressed == 1 && overBtn) enterEditor();
        else if (pressed == 2 && overBack && e.leaveAt == 0) e.leaveAt = now + kLeaveDelayMs;
    }
    e.prevDown = down;
    // Back: restore the vanilla controls only once the LMB is up and the delay has passed (the release must not land on BTN_EXIT).
    if (e.editor && e.leaveAt && !down && static_cast<LONG>(now - e.leaveAt) >= 0) leaveEditor("back");
}

// H-O4 0x8A1930: Options scalar deleting dtor (ECX = this), on entry, before the children are freed.
extern "C" void __cdecl OptDestroy(int panelArg) {
    if (!g_enabled || !panelArg) return;
    const uintptr_t P = static_cast<uintptr_t>(static_cast<unsigned>(panelArg));
    if (P != g_ed.panel) return;
    saferead::beginScope();
    Editor& e = g_ed;
    KP_LOG(chMain, "DTOR panel=%x token=%u editor=%d appended=%d free_labels=%d free_view=%d", static_cast<unsigned>(P), e.token, e.editor ? 1 : 0,
           e.appended ? 1 : 0, g_cfg.freeLabels ? 1 : 0, g_cfg.freeView ? 1 : 0);
    bool clean = false;
    if (g_cfg.freeLabels || g_cfg.freeView) {
        clean = releaseOwn(P);   // references dropped + list truncated (all or nothing)
        if (clean && g_cfg.freeLabels) {
            if (e.btn) freeCtl(e.btn, "btn");
            if (e.back) freeCtl(e.back, "back");
            if (e.title) freeCtl(e.title, "title");
            if (e.status) freeCtl(e.status, "status");
        }
    }
    const uintptr_t view = e.view;
    if (e.token && g_p3.ok()) g_p3.p->Destroy(e.token);
    if (g_cfg.freeView && clean && view) {
        uint32_t vt = 0, scene = 0, svt = 0, resman = 0, r34 = 0, fn = 0;
        (void)rd<uint32_t>(view, 0, &vt);
        (void)rd<uint32_t>(view, 0x74, &scene);
        if (scene) (void)rd<uint32_t>(scene, 0, &svt);
        if (rd<uint32_t>(gameaddr::ResManGlobal, 0, &resman) && resman) (void)rd<uint32_t>(resman, 0x34, &r34);
        KP_LOG(chMain, "FREEVIEW view=%x vt=%x (expect %x) scene=%x scene_vt=%x resman34=%x", static_cast<unsigned>(view), static_cast<unsigned>(vt),
               static_cast<unsigned>(kSceneViewVtable), static_cast<unsigned>(scene), static_cast<unsigned>(svt), static_cast<unsigned>(r34));
        if (vt == kSceneViewVtable && rd<uint32_t>(vt, 0, &fn) && fn && guikit::g_gkCallLabelDtor) {
            guikit::g_gkCallLabelDtor(fn, view, 1u);
            KP_LOG(chMain, "FREEVIEW freed");
        } else {
            KP_LOG(chMain, "FREEVIEW skipped (vtable mismatch)");
        }
    } else if (g_cfg.freeView) {
        KP_LOG(chMain, "FREEVIEW skipped (list not clean=%d view=%x)", clean ? 0 : 1, static_cast<unsigned>(view));
    }
    g_ed = Editor();
}

