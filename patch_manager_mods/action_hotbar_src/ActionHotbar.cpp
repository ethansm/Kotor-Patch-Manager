// Target-mode button inputs for the edited slot: isHealing / selfOk of its resolved item, cached per slot + item key (classifyItem logs on failure: not per frame).
void modeInputs(int slot, const hb::ActionRef& a, bool* heal, bool* selfOk) {
    Editor& ed = g_bar.ed; *heal = *selfOk = false;
    if (a.kind != hb::K_Item || slot < 0 || slot >= ButtonCount || !g_bar.b[slot].avail) return;   // not resolved (out of stock): nothing to classify
    uint32_t key = (uint32_t)g_bar.b[slot].entry.key;
    if (ed.clsSlot != slot || ed.clsKey != key) {
        ed.clsSlot = slot; ed.clsKey = key; ed.clsHeal = ed.clsSelf = false;
        uintptr_t item = serverItemFor(key & ~ItemKeyFlag);
        if (item) { ItemClass ic = classifyItem(item); ed.clsHeal = ic.healing; ed.clsSelf = ic.selfOk; }
    }
    *heal = ed.clsHeal; *selfOk = ed.clsSelf;
}

// Mode button click on the edited slot: next mode, persisted through assignSlot (same SetSlot + Save + FileWatch accept as a picker assignment).
void modeClick(uintptr_t hud, int slot) {
    Editor& ed = g_bar.ed;
    hb::ActionRef a = g_eff[slot]; bool heal, selfOk; modeInputs(slot, a, &heal, &selfOk);
    hb::ModeBtn st = hb::modeButtonState(a, heal, selfOk);
    if (st != hb::MB_Enabled) { KP_LOG(chTarget, "target: mode click slot %s ignored (%s)", hb::SlotKeyName(0, slot).c_str(), hb::modeBtnWhy(st)); return; }
    hb::TargetSpec n = hb::nextFreeTargetMode(g_eff, hb::Slots, slot, a, heal, selfOk);   // skip modes other slots hold: taking one would move the item off them
    if (n.mode == a.target.mode) { KP_LOG(chTarget, "target: mode click slot %s ignored (every other mode is on another slot)", hb::SlotKeyName(0, slot).c_str()); return; }
    if (hb::dropsCustomSuffix(a.target)) KP_LOG(chEdit, "edit: target mode slot %s drops custom suffix (threshold=%d fallback=%d)", hb::SlotKeyName(0, slot).c_str(), a.target.thresholdPct, a.target.fallback);
    KP_LOG(chEdit, "edit: target mode slot %s %s -> %s", hb::SlotKeyName(0, slot).c_str(), hb::targetModeName(a.target.mode), hb::targetModeName(n.mode));
    Entry t; t.ref = a; t.ref.target = n; t.name = a.name;
    if (!assignSlot(hud, slot, &t)) KP_LOG(chTarget, "target: mode change slot %s refused (%s)", hb::SlotKeyName(0, slot).c_str(), ed.msg.c_str());
    g_bar.refreshLast = -1000;   // badge + dim refresh on the next frame
}

static bool edEnabled(uintptr_t hud, Editor& ed) {
    unsigned& lastKey = ed.lastKey;   // change-only on (panel == hud, built > 0, editBound): map section 4 #5
    unsigned key = (g_bar.panel == hud ? 4u : 0u) | (g_bar.built > 0 ? 2u : 0u) | (g_bar.editBound ? 1u : 0u);
    if (key != 7u) {
        if (key != lastKey) {
            lastKey = key;
            bool miss = g_bar.panel == hud && g_bar.built > 0 && !g_bar.editBound;   // updateButtons already WARNs for the other two cases
            KP_LOGV(chEdit, miss ? KPLOG_WARN : KPLOG_INFO, "edit: editor disabled panel=%08x hud=%08x built=%d editBound=%d (%s)", (unsigned)g_bar.panel, (unsigned)hud, g_bar.built, g_bar.editBound,
                    g_bar.panel != hud ? "bar panel is not this hud" : (g_bar.built == 0 ? "no buttons built" : "editor controls missing"));
        }
        return false;
    }
    lastKey = 7;
    return true;
}

// Cross-block values of one updateEditor frame.
struct EdFrame { POINT pt; bool haveCur, click, down; bool mHeal, mSelf; hb::ModeBtn mst; int oth, maxOff; };
static void edInput(Editor& ed, bool gate, EdFrame& f) {
    ensureWheelHook();
    if (ed.inLastChar != g_charKey) { if (ed.inLastChar != "\x01" && ed.mode != M_Normal) setMode(M_Normal, -1, "character changed"); ed.inLastChar = g_charKey; }
    if (!gate && ed.mode != M_Normal) setMode(M_Normal, -1, "gate closed");
    if (g_escHit) { g_escHit = false; if (ed.mode == M_Pick && ed.choosing) { endChoice("choice cancelled"); KP_LOG(chEdit, "edit: target choice cancelled (Esc)"); } else if (ed.mode == M_Pick) setMode(M_Edit, -1, "Esc"); else if (ed.mode == M_Edit) setMode(M_Normal, -1, "Esc"); else KP_LOG(chEdit, "edit: Esc flag set in Normal mode (ignored)"); }

    f.pt = POINT{0, 0}; f.haveCur = gate && cursorInGame(&f.pt);
    HWND fg = GetForegroundWindow(); DWORD fgPid = 0; if (fg) GetWindowThreadProcessId(fg, &fgPid);
    bool fgOk = fg && fgPid == GetCurrentProcessId();
    if (fgOk != ed.inLastFgOk) { KP_LOG(chEdit, "edit: foreground window %p pid=%lu ours=%d", (void*)fg, (unsigned long)fgPid, (int)fgOk); ed.inLastFgOk = fgOk; }
    if (!gate) ed.inClick.prev = false;
    f.click = gate && guikit::clickEdge(ed.inClick);   // clickEdge = LMB down AND game window foreground (same test as fgOk above)
    f.down = ed.inClick.prev;   // level state (gate && fg && LMB), as the old local `down`
}

