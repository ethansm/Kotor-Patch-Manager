// Textures: a CAurTextureBasic registered under our name (like the engine's own "NormCubeMap") with the decoded pixels already in place
// and +0xE4 "constructed" set, so the engine never asks the resource manager for it; the texture tick uploads it and frees the buffer.
constexpr uintptr_t FnTexBasicCtor = gameaddr::TexBasicCtor;    // CAurTextureBasic ctor thiscall(this 0xF4 B, name, name) RET 8; registers the name globally
constexpr uintptr_t FnEngineMalloc = gameaddr::EngineNewArr;    // engine operator new[]: FreeImage (0x00421C40) releases +0x44 with delete[] when +0xE7 == 0
constexpr uintptr_t FnTexListAdd = gameaddr::TexListAdd, TexPendingList = gameaddr::TexPendingList;   // pending-build list, consumed by the texture tick
constexpr uintptr_t FnTexReset = gameaddr::TexReset;        // CAurTextureBasic::Reset fastcall(basic)
constexpr int TexBasicSize = 0xF4;
constexpr int Tex_GlName = 0x58;   // GL texture name (nonzero = uploaded)
constexpr int Tex_Pixels = 0x44, Tex_MipBytes = 0x5C, Tex_W = 0x68, Tex_H = 0x6C, Tex_Bpp = 0x74, Tex_Format = 0x78;
constexpr int Tex_Cube = 0xDF, Tex_Constructed = 0xE4, Tex_Missing = 0xE5, Tex_FromRes = 0xE7, Tex_Tpc = 0xE9;
constexpr int TexCount = sizeof EmbeddedTextures / sizeof EmbeddedTextures[0];
struct EmbTex { unsigned char* basic = nullptr; int w = 0, h = 0, heals = 0; };
EmbTex g_tex[TexCount]; bool g_texInit = false;

bool fillTexture(int i, const char* why) {
    const EmbeddedTexture& src = EmbeddedTextures[i]; EmbTex& t = g_tex[i]; const unsigned char* d = src.data;
    hb::TgaInfo ti; hb::TgaStatus ts = hb::tgaInspect(d, src.size, &ti);   // 64-bit size math + MaxTgaDim limit (HotbarLogic.h)
    if (ts == hb::TGA_NOT_UNCOMPRESSED32) { KP_LOGV(chBuild, KPLOG_WARN, "tex %s: embedded TGA not uncompressed 32-bit, skipped", src.resref); return false; }
    if (ts == hb::TGA_TRUNCATED) { KP_LOGV(chBuild, KPLOG_WARN, "tex %s: embedded TGA truncated (%dx%d, %u bytes)", src.resref, ti.w, ti.h, src.size); return false; }
    if (ts == hb::TGA_TOO_LARGE) { KP_LOGV(chBuild, KPLOG_WARN, "tex %s: embedded TGA too large (%dx%d, limit %d), skipped", src.resref, ti.w, ti.h, hb::MaxTgaDim); return false; }
    int w = ti.w, h = ti.h; unsigned n = ti.bytes;
    unsigned char* px = static_cast<unsigned char*>(reinterpret_cast<NewFn>(FnEngineMalloc)(n));
    if (!px) { KP_LOGV(chBuild, KPLOG_WARN, "tex %s: engine malloc(%u) failed", src.resref, n); return false; }
    hb::tgaBgraToRgba(d, ti, px);   // BGRA -> RGBA, rows as stored (= CResTGA)
    unsigned char* b = t.basic;
    *reinterpret_cast<unsigned char**>(b + Tex_Pixels) = px;
    *reinterpret_cast<int*>(b + Tex_W) = w; *reinterpret_cast<int*>(b + Tex_H) = h; *reinterpret_cast<int*>(b + Tex_Bpp) = 4;
    *reinterpret_cast<int*>(b + Tex_Format) = 0; *reinterpret_cast<int*>(b + Tex_MipBytes) = 0;
    b[Tex_Cube] = 0; b[Tex_FromRes] = 0; b[Tex_Tpc] = 0; b[Tex_Missing] = 0; b[Tex_Constructed] = 1;
    reinterpret_cast<PtrListAddFn>(FnTexListAdd)(reinterpret_cast<void*>(TexPendingList), b);
    t.w = w; t.h = h;
    KP_LOG(chBuild, "tex %s: %s, %dx%d RGBA queued for upload (basic %p, pending %d)", src.resref, why, w, h, (void*)b, rdInt(S_Tex, TexPendingList, 4));
    return true;
}
void ensureTextures() {   // once per process; the textures outlive every HUD (never freed)
    if (g_texInit) return;
    g_texInit = true;
    for (int i = 0; i < TexCount; ++i) {
        unsigned char* b = static_cast<unsigned char*>(reinterpret_cast<NewFn>(FnNew)(TexBasicSize));
        if (!b) { KP_LOGV(chBuild, KPLOG_WARN, "tex %s: allocation failed", EmbeddedTextures[i].resref); continue; }
        memset(b, 0, TexBasicSize);
        reinterpret_cast<void*(__thiscall*)(void*, const char*, const char*)>(FnTexBasicCtor)(b, EmbeddedTextures[i].resref, EmbeddedTextures[i].resref);
        g_tex[i].basic = b;
        if (fillTexture(i, "created")) imageFor(EmbeddedTextures[i].resref);   // a pooled GUI handle that is never released keeps the texture alive
    }
}
void logTextures(const char* when) {
    for (int i = 0; i < TexCount; ++i) if (unsigned char* b = g_tex[i].basic)
        KP_LOG(chBuild, "tex %s (%s): gl=%u constructed=%d missing=%d pixels=%p %dx%d", EmbeddedTextures[i].resref, when, (unsigned)rdInt(S_Tex, reinterpret_cast<uintptr_t>(b), Tex_GlName),
             (int)b[Tex_Constructed], (int)b[Tex_Missing], *reinterpret_cast<void**>(b + Tex_Pixels), *reinterpret_cast<int*>(b + Tex_W), *reinterpret_cast<int*>(b + Tex_H));
}
// A GL reset (ResetAll 0x00427D90 / SetMem 0x00427DE0) Resets every registered texture (+0xE4 = 0, pixels and GL names freed) and
// re-queues all of them on the work list. If we see it first, refill (the duplicate list entry is a no-op: +0xE4 = 1, +0x44 = NULL after
// the first build). If the engine rebuilt first, its resource lookup missed our name (+0xE5 = 1): Reset and refill. DB lesson 290.
void healTextures() {
    for (int i = 0; i < TexCount; ++i) {
        EmbTex& t = g_tex[i]; unsigned char* b = t.basic;
        if (!b) continue;
        bool built = b[Tex_Constructed] != 0; void* px = *reinterpret_cast<void**>(b + Tex_Pixels); int w = *reinterpret_cast<int*>(b + Tex_W);
        if (built && !px && !b[Tex_Missing] && rdInt(S_Tex, reinterpret_cast<uintptr_t>(b), Tex_GlName)) { t.heals = 0; continue; }   // uploaded: healthy
        if (t.heals >= MaxTexHeals) continue;   // give up after MaxTexHeals consecutive failed refills (art missing, labels still work)
        if (!built && !px) { ++t.heals; if (!fillTexture(i, "refilled after a texture reset")) ++g_widgetFaults; }
        else if (built && !px && (b[Tex_Missing] || w != t.w)) {
            ++t.heals; KP_LOGV(chBuild, KPLOG_WARN, "tex %s: rebuilt without our pixels (missing=%d w=%d), resetting", EmbeddedTextures[i].resref, (int)b[Tex_Missing], w);
            reinterpret_cast<void(__fastcall*)(void*)>(FnTexReset)(b);
            if (!fillTexture(i, "refilled after a missing rebuild")) ++g_widgetFaults;
        }
        if (t.heals == MaxTexHeals) KP_LOGV(chBuild, KPLOG_WARN, "tex %s: giving up after %d failed refills (built=%d missing=%d pixels=%p); art missing, labels still work", EmbeddedTextures[i].resref, MaxTexHeals, (int)b[Tex_Constructed], (int)b[Tex_Missing], *reinterpret_cast<void**>(b + Tex_Pixels));   // crossed once: the line above this loop body skips at >= 20
    }
}

// ---- per-save hotbars: the live INI's profiles are snapshotted into each save folder and restored on load ------------------
// Every save (menu, quicksave, autosave) copies action_hotbar.ini into the save folder; every load replaces the live INI's
// profiles with that save's copy; a save without one keeps the live bar (PS1); a new game empties it. [General] is never touched.
// Detours 0x534527, 0x53C5AA, 0x52FD1E, 0x8529E0, 0x8FACA0 are owned by the save-events library (k2.saveevents@1).
const char* const SnapshotFile = hb::IniName;

// RH1: arm the deferred snapshot (save folder empty or not yet a directory). WARN when a still-pending one is replaced: that save never gets a copy.
static void armPendingSave(const char* dir, const char* why) {
    if (g_pendingSaveSnapshot) KP_LOGV(chCfg, KPLOG_WARN, "persave: %s: previous pending snapshot (%s) replaced", why ? why : "save written", g_pendingSaveDir.empty() ? "unresolved folder" : g_pendingSaveDir.c_str());
    g_pendingSaveDir = dir ? dir : ""; g_pendingSaveWhy = why ? why : "save written"; g_pendingSaveSnapshot = true; g_pendingSaveSince = GetTickCount();
}

static bool snapExistsPath(const std::string& p) { return filewatch::stamp(p.c_str()).exists; }

void runPendingLoad();
void snapshotToSave(const char* dir, const char* why) {
    runPendingLoad();   // PS5: a load still waiting for the HUD tick is applied first, so this save gets the loaded bar
    char cur[260] = {};
    if ((!dir || !*dir) && g_se.currentSaveFolder(cur, sizeof cur) > 0 && cur[0]) {
        dir = cur;
    }
    if (!dir || !*dir) {
        armPendingSave(nullptr, why);
        return;
    }
    DWORD at = GetFileAttributesA(dir);
    if (at == INVALID_FILE_ATTRIBUTES || !(at & FILE_ATTRIBUTE_DIRECTORY)) {
        armPendingSave(dir, why);
        return;
    }
    checkConfig(true);   // a hand edit made in the last second is part of what the player saved
    std::string dst = std::string(dir) + "/" + SnapshotFile;
    BOOL ok = CopyFileA(IniPath, dst.c_str(), FALSE);
    int lv = ok ? KPLOG_INFO : KPLOG_WARN;   // two lines (map section 3): the destination path can be long
    KP_LOGV(chCfg, lv, "%s", hb::fmtPersaveSnapshot(why, ok != 0, (int)g_cfg.profiles.size()).c_str());
    KP_LOGV(chCfg, lv, "%s", hb::fmtPersaveDst(why, dst).c_str());
    if (ok) { g_verifyDir = dir; g_verifyWhy = why ? why : "save written"; g_verifySince = GetTickCount(); }
}

// PS3: called from the HUD tick. A copy the engine removed after the save event (folder rewritten later) is written once more.
void verifySnapshot() {
    if (g_verifyDir.empty()) return;
    const std::string dst = g_verifyDir + "/" + SnapshotFile;
    DWORD at = GetFileAttributesA(g_verifyDir.c_str());
    hb::SnapVerify v = hb::snapVerify(GetTickCount(), g_verifySince, snapExistsPath(dst), at != INVALID_FILE_ATTRIBUTES && (at & FILE_ATTRIBUTE_DIRECTORY));
    if (v == hb::SV_Wait) return;
    std::string dir = g_verifyDir, why = g_verifyWhy; g_verifyDir.clear();
    if (v == hb::SV_Ok) { g_verifyRetried = false; KP_LOGV(chCfg, KPLOG_DEBUG, "persave: %s: copy verified in '%.150s'", why.c_str(), dir.c_str()); return; }
    if (v == hb::SV_Rewrite && !g_verifyRetried) {
        g_verifyRetried = true;
        KP_LOGV(chCfg, KPLOG_WARN, "persave: %s: copy missing from '%.150s' after the save, rewriting", why.c_str(), dir.c_str());
        snapshotToSave(dir.c_str(), why.c_str());
        return;
    }
    g_verifyRetried = false;
    KP_LOGV(chCfg, KPLOG_WARN, "persave: %s: copy missing from '%.150s' (%s), giving up", why.c_str(), dir.c_str(), v == hb::SV_Gone ? "folder gone" : "lost again");
}

// RL26: keep the last 3 load backups (.load.bak newest, .load.bak.1, .load.bak.2): two quick loads no longer lose an unsaved bar edit.
void rotateLoadBak() {
    std::string b1 = hb::loadBakName(LoadBakPath, 1), b2 = hb::loadBakName(LoadBakPath, 2);
    DeleteFileA(b2.c_str()); MoveFileA(b1.c_str(), b2.c_str()); MoveFileA(LoadBakPath, b1.c_str());   // a missing source just fails
}

// Replaces the live INI's profiles with `snap`'s (nullptr = none: empty bar), keeping [General]; the previous file goes to .ini.load.bak.
// Runs from load/new-game hooks, so no widget is touched here: the HUD tick applies the reload (g_pendingReload).
void replaceLiveProfiles(const hb::Config* snap, const char* status, const std::string& path, const char* why) {
    checkConfig(true);
    hb::Config n = hb::mergeSnapshot(g_cfg.general, snap);
    rotateLoadBak();
    BOOL bak = CopyFileA(IniPath, LoadBakPath, FALSE);
    if (snap) {   // BEFORE the save: Parse leaves the offending slot empty and Serialize never writes warnings back (map section 6)
        int nw = (int)snap->warnings.size();
        for (int i = 0; i < nw && i < 10; ++i) KP_LOGV(chCfg, KPLOG_WARN, "persave: %s: snapshot warning [%d/%d] %.160s", why, i + 1, nw, snap->warnings[i].c_str());
        if (nw > 10) KP_LOGV(chCfg, KPLOG_WARN, "persave: %s: snapshot warning (+%d more)", why, nw - 10);
    }
    bool ok = n.Save(IniPath);
    if (ok) { g_cfg = n; g_cfgStale = false; filewatch::accept(g_cfgPoll, IniPath); recomputeBound(); }
    g_pendingReload = true;
    KP_LOGV(chCfg, ok ? KPLOG_INFO : KPLOG_WARN, "%s", hb::fmtPersaveReplace(why, ok, (int)n.profiles.size(), snap ? (int)snap->warnings.size() : 0, bak != 0).c_str());
    KP_LOGV(chCfg, ok ? KPLOG_INFO : KPLOG_WARN, "%s", hb::fmtPersaveSource(why, status, path).c_str());
}


void restoreFromSave(const char* dir, const char* why) {
    char cur[260] = {};
    if ((!dir || !*dir) && g_se.currentSaveFolder(cur, sizeof cur) > 0 && cur[0]) {
        dir = cur;
    }
    if (!dir || !*dir) {
        KP_LOGV(chCfg, KPLOG_WARN, "persave: %s: save folder not recognised ('%s'), live hotbar kept", why, dir ? dir : "?");
        return;
    }
    if (g_pendingSaveSnapshot) {   // RH1: a save made moments ago may still be waiting for its folder; write it before looking for a snapshot
        std::string pd = g_pendingSaveDir;
        if (pd.empty() && g_se.currentSaveFolder(cur, sizeof cur) > 0 && cur[0] && strcmp(cur, dir) != 0) pd = cur;   // never flush into the save being loaded (it would overwrite its snapshot)
        DWORD pat = pd.empty() ? INVALID_FILE_ATTRIBUTES : GetFileAttributesA(pd.c_str());
        if (pat != INVALID_FILE_ATTRIBUTES && (pat & FILE_ATTRIBUTE_DIRECTORY)) { g_pendingSaveSnapshot = false; g_pendingSaveDir.clear(); snapshotToSave(pd.c_str(), g_pendingSaveWhy.c_str()); }
    }
    hb::SnapPick pick = hb::pickSnapshot(dir, snapExistsPath);
    if (pick.src == hb::SS_Absent) {   // PS1: no copy (pre-mod save, or the save event was missed): keep the live bar, never empty it
        KP_LOGV(chCfg, KPLOG_WARN, "%s", hb::fmtPersaveSource(why, hb::snapStatus(pick.src, false), pick.path).c_str());
        return;
    }
    hb::Config snap;
    if (!snap.Load(pick.path)) { KP_LOGV(chCfg, KPLOG_WARN, "%s", hb::fmtPersaveSource(why, hb::snapStatus(pick.src, false), pick.path).c_str()); return; }
    replaceLiveProfiles(&snap, hb::snapStatus(pick.src, true), pick.path, why);
}

// PS5: applies a deferred load / new game; called from the HUD tick and before any snapshot.
void runPendingLoad() {
    PendingLoad k = g_pendingLoad; if (k == PL_None) return;
    std::string dir = g_pendingLoadDir; g_pendingLoad = PL_None; g_pendingLoadDir.clear();
    if (k == PL_Load) restoreFromSave(dir.c_str(), "save loading");
    else replaceLiveProfiles(nullptr, "new game", "-", "new game started");
}

// Runs at the top of every exported hook (once). Not in DllMain: KpLog_Init runs from KPatchInit, so KpLog_HasCore() is always false
// there, and the banner would open the fallback file before the rotation (map section 7).
