// Reads group g's entry list from the hud (guarded) and remembers item icons. Returns count read.
struct GroupFault { int count = -2, base = 0; uintptr_t entry = 0; int idx = -1; int logs = 0; };   // change-only cache per group (map R1)
GroupFault g_gf[HudGroupCount];
constexpr int InvokableGroups = 6;   // groups 0..5 are the invokable lists
static_assert(InvokableGroups < HudGroupCount, "group 6 is not invokable");
int readGroup(uintptr_t hud, int g, std::vector<Entry>* out) {
    out->clear();
    GroupFault& gf = g_gf[(unsigned)g % HudGroupCount];
    bool faulted = false;
    int base = rdInt(S_Hud, hud, Hud_GroupLists + g * 12), count = rdInt(S_Hud, hud, Hud_GroupLists + 4 + g * 12);
    if (count < 0 || count > MaxEntries) {
        if (gf.count != count || gf.base != base) {
            gf.count = count; gf.base = base;
            if (gf.logs < 5) { ++gf.logs; KP_LOGV(chSlots, KPLOG_WARN, "readGroup g=%d: implausible count=%d base=%08x", g, count, (unsigned)base); } else ++g_probeFaults;
        } else ++g_probeFaults;
        return 0;
    }
    gf.count = -2;
    if (base == 0 || count == 0) { gf.entry = 0; gf.idx = -1; return 0; }
    for (int i = 0; i < count; ++i) {
        uintptr_t e = (uintptr_t)base + (uintptr_t)i * EntryStride;
        if (!saferead::probeRead(S_Entry, reinterpret_cast<const void*>(e), EntryStride)) {
            faulted = true;
            if (gf.entry != e || gf.idx != i) {
                gf.entry = e; gf.idx = i;
                if (gf.logs < 5) { ++gf.logs; KP_LOGV(chSlots, KPLOG_WARN, "readGroup g=%d: entry %d at %08x unreadable, stopping", g, i, (unsigned)e); } else ++g_probeFaults;
            } else ++g_probeFaults;
            break;
        }
        Entry en; en.group = g; en.index = i; en.key = rdInt(S_Entry, e, Entry_Key); en.flags = rdInt(S_Entry, e, Entry_Flags);
        en.name = readExoStr(S_Entry, e);
        { char ib[17] = {0}; if (saferead::probeRead(S_Entry, reinterpret_cast<const void*>(e + Entry_Icon), 16)) { memcpy(ib, reinterpret_cast<const void*>(e + Entry_Icon), 16); for (int k = 0; k < 16; ++k) if (ib[k] && (ib[k] < 0x20 || ib[k] > 0x7E)) ib[k] = '?'; }
          else if (++g_iconFaults <= 5) KP_LOGV(chSlots, KPLOG_DEBUG, "readGroup: icon unreadable g=%d i=%d entry=%08x (icon left empty)", g, i, (unsigned)e);
          en.icon = ib; }
        en.ref = decodeKey(en.key, en.name);
        if (en.ref.kind == hb::K_Item && !en.icon.empty()) g_itemIcon[en.ref.name] = en.icon;
        out->push_back(en);
    }
    if (!faulted) { gf.entry = 0; gf.idx = -1; }
    return (int)out->size();
}

