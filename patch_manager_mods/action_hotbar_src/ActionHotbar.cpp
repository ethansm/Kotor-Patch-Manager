// saferead site ids (per DLL; the ring buffer reports them). 0x4800-0x48FF belong to this mod.
enum Site : unsigned { S_Hud = 0x4801, S_Entry, S_Ctl, S_Border, S_Geom, S_Create, S_Save, S_Tex, S_Input, S_Misc, S_Aspect, S_Proj, S_Target,
                       S_WrSel, S_WrActive, S_WrProjSet, S_WrProjRestore,   // 0x480E..0x4811: probeWrite sites
                       S_Mode,     // 0x4812: stance/form watch reads
                       SiteCState, // 0x4813: CSTATE combat flag read (CombatTraceRead.h)
                       S_Count };  // sentinel: size of per-site tables (seen[] below)

int rdInt(unsigned site, uintptr_t base, int off, int dflt = 0) { int v; return saferead::readAt(site, base, off, &v) ? v : dflt; }

// Guarded CExoString read (saferead::readExo: len 1..80, printable, trailing NULs stripped; engine lengths include the trailing NUL (live-verified)); empty on anything implausible.
unsigned g_exoFaults = 0, g_iconFaults = 0, g_probeFaults = 0, g_widgetFaults = 0;   // suppressed/failed-read counters, shown in the heartbeat
std::string readExoStr(unsigned site, uintptr_t addr) {
    char buf[96];
    if (saferead::readExo(site, addr, buf, sizeof buf)) return std::string(buf);
    // readExo cannot say "unreadable" from "rejected (empty, too long, not printable)": log the first 5 per site, count the rest
    static int seen[S_Count - S_Hud];
    ++g_exoFaults;
    unsigned ix = site - (unsigned)S_Hud;
    if (ix < sizeof seen / sizeof seen[0] && seen[ix]++ < 5) KP_LOGV(site == S_Save ? chCfg : chSlots, KPLOG_DEBUG, "exo: CExoString rejected site=%04x addr=%08x", site, (unsigned)addr);
    return std::string();
}

// One WARN line per SafeRead ring entry (map section 5). Do not hand the whole dump to one KP_WARN: KpLog formats into 512 bytes first.
// Game thread only, never per frame: callers are build failures, target failures, the 10 s check and the gate-closed edge.
LONG g_ringDumped = 0;
void dumpRing(const char* why, LONG minNew = 1) {
    static int dumps = 0;
    LONG c = saferead::g_ringCount;
    if (c - g_ringDumped < minNew || dumps >= 8) return;   // nothing new enough, or session cap (WARN is not rate-capped by the core)
    ++dumps; g_ringDumped = c;
    static char buf[8192]; saferead::dump(buf, sizeof buf);
    KP_WARN("saferead: dump #%d reason=%s", dumps, why);
    for (char* p = buf; *p; ) {
        char* e = strchr(p, '\n'); size_t n = e ? (size_t)(e - p) : strlen(p);
        while (n && *p == ' ') { ++p; --n; }
        if (n) {
            if (strncmp(p, "saferead:", 9) == 0) KP_WARN("%.*s", (int)n, p);   // header line already carries the tag
            else KP_WARN("saferead: %.*s", (int)n, p);
        }
        p = e ? e + 1 : p + n;
    }
}

