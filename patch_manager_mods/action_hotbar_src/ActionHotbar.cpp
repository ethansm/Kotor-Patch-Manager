// Per frame: which slot (if any) the cursor is over. Only available slots highlight (frame -> "fph_slot_hi").
void updateHover(bool gate) {
    POINT& lastPt = g_bar.hoverLastPt; long& lastLog = g_bar.hoverLastLog;
    int over = -1; POINT pt = {0, 0};
    if (gate && cursorInGame(&pt)) {
        for (int s = 0; s < ButtonCount && over < 0; ++s) {
            const Widget& w = g_bar.b[s].bg; if (!w.ctl || !w.visible) continue;
            uintptr_t c = reinterpret_cast<uintptr_t>(w.ctl); int x = 0, y = 0, ww = 0, hh = 0; guikit::getExtent(c, &x, &y, &ww, &hh);
            if (pt.x >= x && pt.x < x + ww && pt.y >= y && pt.y < y + hh) over = s;
        }
    }
    if (over != g_bar.hoverLast) { KP_LOGV(chInput, KPLOG_DEBUG, "hover: slot %d -> %d cursor=(%ld,%ld)", g_bar.hoverLast, over, (long)pt.x, (long)pt.y); g_bar.hoverLast = over; g_bar.hoverStart = GetTickCount(); hideTip("hover changed"); if (over >= 0 && (g_bar.b[over].avail || g_bar.ed.mode != M_Normal)) playHoverSound("slot"); }
    else if (KP_ENABLED(chInput, KPLOG_DEBUG) && (pt.x != lastPt.x || pt.y != lastPt.y) && pt.y > HoverLogMinY && g_frame - lastLog > RetryFrames) { lastLog = g_frame; KP_LOGV(chInput, KPLOG_DEBUG, "hover: cursor=(%ld,%ld) over=%d", (long)pt.x, (long)pt.y, over); }
    lastPt = pt;
    for (int s = 0; s < ButtonCount; ++s) {
        Button& b = g_bar.b[s]; bool hov = (s == over) && (b.avail || g_bar.ed.mode != M_Normal);
        bool selected = g_bar.ed.mode == M_Pick && g_bar.ed.slot == s;   // slot being edited stays highlighted
        if (b.bg.ctl && b.bg.visible) setFill(b, b.bg, s, (hov || selected) ? FrameHiResref : FrameResref);
    }
    {   // left click on an available slot = same request as its digit key
        guikit::ClickEdge& clickState = g_bar.ed.slotClick;   // C067: was a function static
        if (!gate) clickState.prev = false;   // as before: a press held while the HUD was inactive does not fire when it becomes active
        bool click = gate && guikit::clickEdge(clickState);   // clickEdge also requires the game window to be foreground
        if (click && over >= 0 && g_bar.ed.mode != M_Normal) KP_LOG(chInput, "click: slot %d in %s mode -> handled by the editor, not invoked", over, ModeName[g_bar.ed.mode]);
        else if (click && over >= 0) {
            bool ok = g_bar.b[over].avail;
            KP_LOG(chInput, "click: slot %d %s", over, ok ? "queued" : "ignored (no action)");
            if (ok) { if (hb::ringFull(g_ringHead, g_ringTail)) KP_LOGV(chInput, KPLOG_WARN, "click: ring full, dropped"); else { hb::ringPush(g_ring, g_ringHead, Req{ over, Src_Click }); } }
        }
    }
    bool refusalLive = g_bar.tipSlot == RefuseTipId && (int)(GetTickCount() - g_refuseUntil) < 0;   // the hover tip must not replace it
    if (over >= 0 && g_bar.b[over].avail && !refusalLive && g_bar.tipSlot != over && GetTickCount() - g_bar.hoverStart >= TipDelayMs) showTipAt(g_bar.b[over].bg, g_bar.b[over].entry, over);
    if ((over < 0 || !g_bar.b[over].avail) && g_bar.tipSlot < CellTipBase) hideTip("no hover");
    if (g_bar.tipSlot == RefuseTipId && (int)(GetTickCount() - g_refuseUntil) >= 0) hideTip("refusal expired");
}

// Per-tick button state. gate = HUD is the active panel. Entries are re-resolved every ButtonRefreshFrames frames or when
// the cached view is stale (config/character/gate change), never per frame.
// LowHp slot with nobody who can take the item (hb::slotEnabled false): the icon is drawn dimmed. Quiet (no logs), called only on the button refresh cadence.
// Anything unreadable / not a healing item = enabled (never dim on a failed read).
bool lowHpSlotEnabled(const Entry& e, const hb::ActionRef& a) {
    uintptr_t itemPtr = serverItemFor((uint32_t)e.key & ~ItemKeyFlag, nullptr, true);
    if (!itemPtr) return true;
    ItemClass ic = classifyItem(itemPtr);
    if (ic.row < 0 || !ic.healing) return true;
    party::Vitals v[3]; int n = party::members(v, 3);
    if (n <= 0) return true;
    hb::Candidate c[3];
    buildCandidates(v, n, itemPtr, c);
    uint32_t mids[3] = {};
    for (int i = 0; i < n; ++i) if (v[i].client) saferead::readAt<uint32_t>(S_Target, v[i].client, Client_ObjectId, &mids[i]);
    applyPendingHeals(v, n, mids, c, false);   // same eligibility as the press (targetedUse)
    return hb::slotEnabled(c, n, 0, a.target, g_cfg.general);
}
