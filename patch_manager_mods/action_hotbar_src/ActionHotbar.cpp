void checkConfig(bool force) {
    bool first = !g_cfgPoll.primed;
    filewatch::Stamp st;
    const filewatch::Stamp prevStamp = g_cfgPoll.last; const bool prevPrimed = g_cfgPoll.primed;   // before changed() consumes it
    if (!filewatch::changed(g_cfgPoll, IniPath, GetTickCount(), force, &st)) return;
    if (first && !st.exists) { writeTemplateIni(); st = filewatch::accept(g_cfgPoll, IniPath); }
    long long mt = st.mtimeMs();
    hb::Config c;
    if (!c.Load(IniPath)) {
        if (!st.exists) { KP_LOGV(chCfg, KPLOG_WARN, "cfg: cannot read %s (mtime=%lld, keeping previous)", IniPath, mt); return; }   // R7: a missing file is harmless (g_cfg stays, assignSlot's Save recreates it): no stale flag, no retry
        if (!g_cfgStale) KP_LOGV(chCfg, KPLOG_WARN, "cfg: cannot read %s (mtime=%lld, keeping previous, retrying)", IniPath, mt);
        else KP_LOG_EVERY(chCfg, 30000, "cfg: still cannot read %s (retrying every poll)", IniPath);
        g_cfgStale = true; g_cfgPoll.last = prevStamp; g_cfgPoll.primed = prevPrimed;   // un-consume: the next poll sees the change again and retries
        return;
    }
    g_cfgStale = false;
    g_cfg = c;
    if (!KpLog_HasCore()) KpLog_SetFallbackLevel(g_cfg.general.verbose ? KPLOG_DEBUG : KPLOG_INFO);   // old core: Verbose=1 keeps its meaning (DEBUG tier)
    else { static bool verboseNoted = false; if (g_cfg.general.verbose && !verboseNoted) { verboseNoted = true; KP_LOG(chCfg, "cfg: Verbose=1 only applies without the kpatch.log core; use kplog.ini [action-hotbar] level=debug"); } }
    KP_LOG(chCfg, "cfg: loaded %s: invoke=%d verbose=%d kbdev=%d profiles=%d warnings=%d",
         IniPath, g_cfg.general.invoke, g_cfg.general.verbose, g_cfg.general.keyboardDevice,
         (int)g_cfg.profiles.size(), (int)g_cfg.warnings.size());
    if (targetProbeMode()) KP_LOG(chCfg, "cfg: TargetProbe=%d", targetProbeMode());
    {   // itemised, capped at 10 (map section 6)
        int nw = (int)g_cfg.warnings.size();
        for (int i = 0; i < nw && i < 10; ++i) KP_LOGV(chCfg, KPLOG_WARN, "cfg: WARNING [%d/%d] %s", i + 1, nw, g_cfg.warnings[i].c_str());
        if (nw > 10) KP_LOGV(chCfg, KPLOG_WARN, "cfg: WARNING (+%d more)", nw - 10);
    }
    int dev = g_cfg.general.keyboardDevice;
    g_kbDevice = dev >= 0 ? dev : rdInt(S_Input, KeyboardDeviceGlobal, 0, 0);
    recomputeBound();
}

// ---- resolver + invoker -------------------------------------------------------------------------------
// Lazy per-tick group snapshot: a group is read only when first asked for (readGroup has change-only fault logging + counters).
struct GroupSnapshot {
    uintptr_t hud; bool loaded[InvokableGroups] = {}; std::vector<Entry> es[InvokableGroups];
    explicit GroupSnapshot(uintptr_t h) : hud(h) {}
    const std::vector<Entry>& get(int g) { if (!loaded[g]) { readGroup(hud, g, &es[g]); loaded[g] = true; } return es[g]; }
};
bool resolve(GroupSnapshot& snap, const hb::ActionRef& want, Entry* out) {
    for (int g = 0; g < InvokableGroups; ++g) {
        for (auto& e : snap.get(g)) if (hb::Same(e.ref, want)) { *out = e; return true; }
    }
    return false;
}

// ---- stance / form watch (vanilla resyncs the action bar only on char switch / panel close / arrow release) ----
