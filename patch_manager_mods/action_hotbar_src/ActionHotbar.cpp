// Writes (or, with e == nullptr, clears) hotbar slot `slot` of the controlled character's profile ([Profile.<key>], key = obj%08x of the creature id) and saves the INI.
// Assigning an action that is already on the bar moves it: the old slot becomes none (hb::moveDuplicates).
// The key is the creature object id (the Exile is objfffffffd, stable; the invalid id objffffffff seen during loads is treated as 'unknown').
bool assignSlot(uintptr_t hud, int slot, const Entry* e) {
    Editor& ed = g_bar.ed;
    checkConfig(true);   // pick up a hand edit made since the last poll before we overwrite the file
    if (g_cfgStale) { KP_LOGV(chEdit, KPLOG_WARN, "edit: assign REFUSED: %s unreadable (stale config), saving would overwrite it", IniPath); ed.msg = "Config file unreadable - not saving (see log)"; return false; }
    if (!g_cfg.warnings.empty()) {
        int nw = (int)g_cfg.warnings.size();
        KP_LOGV(chEdit, KPLOG_WARN, "edit: assign REFUSED: config has %d warning(s); saving would drop the lines they concern", nw);
        for (int i = 0; i < nw && i < 5; ++i) KP_LOGV(chEdit, KPLOG_WARN, "edit: assign REFUSED: cfg warning [%d/%d] %.185s", i + 1, nw, g_cfg.warnings[i].c_str());
        if (nw > 5) KP_LOGV(chEdit, KPLOG_WARN, "edit: assign REFUSED: cfg warning (+%d more)", nw - 5);
        ed.msg = "Config file has warnings - not saving (see log)"; return false;
    }
    if (g_charKey.empty()) { KP_LOGV(chEdit, KPLOG_WARN, "edit: assign REFUSED: character key unknown (load in progress?)"); ed.msg = "Character not identified yet - try again"; return false; }
    hb::Profile& d = g_cfg.profile(g_charKey);   // per-character profile; slotFor falls back to Default for slots it leaves unset
    const hb::Profile backup = d;   // RH3: a failed Save must not leave the edit (or the duplicate it blanked) in g_cfg
    int frozen = hb::freezeEffective(d.slots[0], g_eff);
    hb::ActionRef a; if (e) a = e->ref; else a.blank = true;
    if (e && a.empty()) { KP_LOGV(chEdit, KPLOG_WARN, "edit: assign REFUSED: entry '%s' has no stable ref", e->name.c_str()); d = backup; ed.msg = "That entry cannot be bound"; return false; }
    if (e) for (int from : hb::moveDuplicates(d, 0, slot, a)) KP_LOG(chEdit, "edit: '%s' moved from slot %c to %c", e->name.c_str(), hb::slotDigit(from), hb::slotDigit(slot));   // re-pick of an action already on the bar = move
    g_cfg.SetSlot(g_charKey, 0, slot, a, e ? e->name : "cleared");
    static bool backedUp = false;
    if (!backedUp) { backedUp = true; BOOL ok = CopyFileA(IniPath, BakPath, FALSE); KP_LOGV(chEdit, ok ? KPLOG_INFO : KPLOG_WARN, "edit: backup %.40s -> %.40s: %s", IniPath, BakPath, ok ? "ok" : "FAILED (no ini yet?)"); }
    bool ok = g_cfg.Save(IniPath);
    filewatch::Stamp st = filewatch::stamp(IniPath); long long mt = st.mtimeMs(); if (ok) filewatch::accept(g_cfgPoll, st);
    {   // two lines (map section 3): the Format value (up to 100 bytes) goes on its own line; WARN when the save failed
        int lv = ok ? KPLOG_INFO : KPLOG_WARN;
        KP_LOGV(chEdit, lv, "%s", hb::fmtAssign(slot, hb::SlotKeyName(0, slot), ok, frozen, mt, g_charKey).c_str());
        KP_LOGV(chEdit, lv, "%s", hb::fmtAssignValue(e != nullptr, e ? hb::Format(a) : std::string()).c_str());
    }
    if (!ok) { d = backup; ed.msg = "Saving the config failed (see log)"; return false; }
    recomputeBound(); refreshEffective(hud);
    return true;
}

