// Client item id -> engine CSWSItem* (app -> objTable(+8) -> ClientToServerObjectId -> GetItemByObjectId); 0 + a WARN log on any failure.
uintptr_t serverItemFor(uint32_t clientItem, uint32_t* serverOut = nullptr, bool quiet = false) {   // quiet: periodic UI refresh, no log/ring dump on failure
    uint32_t app = 0, objTable = 0;   // objTable = *(app+8), exactly as 0x77c7aa (NOT app+4, which is the client/party side)
    if (!saferead::readAt<uint32_t>(S_Target, AppGlobal, 0, &app) || !app ||
        !saferead::readAt<uint32_t>(S_Target, app, App_ObjTable, &objTable) || !objTable) { SERVERITEM_FAIL(KP_LOGV(chTarget, KPLOG_WARN, "target: object table unreadable (app=%08x), using it normally", (unsigned)app)); }
    uint32_t serverItem = reinterpret_cast<uint32_t(__thiscall*)(uintptr_t, uint32_t)>(ClientToServerObjectId)(objTable, clientItem);
    if (!serverItem) { SERVERITEM_FAIL(KP_LOGV(chTarget, KPLOG_WARN, "target: no server id for client item %08x, using it normally", (unsigned)clientItem)); }
    uintptr_t itemPtr = reinterpret_cast<uintptr_t(__thiscall*)(uintptr_t, uint32_t)>(GetItemByObjectId)(objTable, serverItem);
    if (!itemPtr) { SERVERITEM_FAIL(KP_LOGV(chTarget, KPLOG_WARN, "target: item %08x (server %08x) not found, using it normally", (unsigned)clientItem, (unsigned)serverItem)); }
    if (serverOut) *serverOut = serverItem;
    return itemPtr;
}

// Item property 0 (count +Item_PropCount, array +Item_PropArray, stride 0x1C: +Prop_Type, +Prop_Row = spells.2da row, +Prop_Usable); unreadable -> count 0.
hb::ItemProp readItemProp(uintptr_t itemPtr) {
    hb::ItemProp p; int32_t cnt = 0; uint32_t arr = 0;
    if (!saferead::readAt<int32_t>(S_Target, itemPtr, Item_PropCount, &cnt) || !saferead::readAt<uint32_t>(S_Target, itemPtr, Item_PropArray, &arr)) return p;
    if (cnt > 0 && arr) {
        int16_t ty = 0, row = 0; uint8_t us = 0;
        if (saferead::readAt<int16_t>(S_Target, arr, Prop_Type, &ty) && saferead::readAt<int16_t>(S_Target, arr, Prop_Row, &row) && saferead::readAt<uint8_t>(S_Target, arr, Prop_Usable, &us)) { p.count = cnt; p.type = ty; p.row = row; p.usable = us; }
    }
    return p;
}

// baseitems.2da itemtype of a server item (GetBaseItem+0xAC), -1 = unreadable. Quiet: callers log.
int itemTypeOf(uintptr_t itemPtr, uintptr_t* baseOut = nullptr) {
    uintptr_t baseItem = itemPtr ? reinterpret_cast<uintptr_t(__thiscall*)(uintptr_t)>(GetBaseItem)(itemPtr) : 0;
    if (baseOut) *baseOut = baseItem;
    uint8_t typeByte = 0;
    if (!baseItem || !saferead::readAt<uint8_t>(S_Target, baseItem, BaseItem_Type, &typeByte)) return -1;
    return typeByte;
}

using hb::ItemClass;
ItemClass classifyItem(uintptr_t itemPtr) {
    hb::ItemProp p = readItemProp(itemPtr);
    int row = hb::usableSpellRow(p); const char* why = hb::itemPropWhy(p);
    if (row < 0) return hb::classifyRow(row, why, 0, "", "", "", "");
    ensureLookups();
    int nRows = (int)g_spells.rows.size();
    if (nRows == 0 || row >= nRows) return hb::classifyRow(row, why, nRows, "", "", "", "");
    ItemClass c = hb::classifyRow(row, why, nRows, g_spells.Get(row, "range"), g_spells.Get(row, "usertype"), g_spells.Get(row, "hostilesetting"), g_spells.Get(row, "category"));
    return hb::applyItemType(c, itemTypeOf(itemPtr));   // energy shields / squad recovery kit: no target modes
}

// CanUseItem(strict) on member idx, then PerformUseItem(item -> member idx) exactly as the original member path. True = handled (also when refused);
// false = a read failed (caller falls back to invokeEntry).
bool useOnMember(int idx, const party::Vitals* v, uint32_t clientItem, uintptr_t itemPtr, const char* why, uint32_t* calledId = nullptr) {
    if (!v[idx].server || !itemPtr || !canUseItem(v[idx].server, itemPtr)) {
        KP_LOG(chTarget, "target: %s: CanUseItem refused member %d", why, idx); g_useRefused = true; return true;
    }
    if (!g_cfg.general.invoke) { KP_LOG(chTarget, "target: %s: (Invoke=0: would use on member %d)", why, idx); return true; }
    uint32_t memberId = 0;
    if (!v[0].client || !v[idx].client || !saferead::readAt<uint32_t>(S_Target, v[idx].client, Client_ObjectId, &memberId) || !memberId) {
        TARGET_FAIL(KP_LOGV(chTarget, KPLOG_WARN, "target: member %d id/client unreadable (self=%08x member=%08x), using it normally", idx, (unsigned)v[0].client, (unsigned)v[idx].client));
    }
    uint8_t posProbe[12];
    if (!saferead::probeRead(S_Target, reinterpret_cast<const void*>(v[idx].client + Client_Pos), sizeof posProbe)) { TARGET_FAIL(KP_LOGV(chTarget, KPLOG_WARN, "target: member %d position unreadable, using it normally", idx)); }
    KP_LOG(chTarget, "target: PerformUseItem(item %08x -> member %d id %08x) called", (unsigned)clientItem, idx, (unsigned)memberId);
    reinterpret_cast<void(__thiscall*)(uintptr_t, uint32_t, int, uint32_t, float*)>(PerformUseItem)(v[0].client, clientItem, 0, memberId, reinterpret_cast<float*>(v[idx].client + Client_Pos));
    KP_LOG(chTarget, "target: PerformUseItem(item %08x -> member %d id %08x) returned", (unsigned)clientItem, idx, (unsigned)memberId);
    if (calledId) *calledId = memberId;
    return true;
}

// "@lowhp" item slot: pick the party member with the lowest HP% and use the item on them via the game's own PerformUseItem.
// True = handled (caller must not invokeEntry); false = fall through to the normal self use. Every failed read logs once and returns false.
bool targetedUse(const Entry& e, const hb::ActionRef& a, int probe) {
    uint32_t clientItem = (uint32_t)e.key & ~ItemKeyFlag, serverItem = 0;
    uintptr_t itemPtr = serverItemFor(clientItem, &serverItem);
    if (!itemPtr) return false;
    uintptr_t baseItem = 0;
    int itemType = itemTypeOf(itemPtr, &baseItem);
    if (itemType < 0) { TARGET_FAIL(KP_LOGV(chTarget, KPLOG_WARN, "target: base item unreadable (item=%08x base=%08x), using it normally", (unsigned)itemPtr, (unsigned)baseItem)); }
    bool targetable = hb::isTargetableItemType(itemType);
    KP_LOG(chTarget, "target: slot item '%s' client=%08x server=%08x item=%08x type=%d targetable=%d", a.name.c_str(), (unsigned)clientItem, (unsigned)serverItem, (unsigned)itemPtr, itemType, targetable);
    if (!targetable) { KP_LOG(chTarget, "target: item type %d is self-only/direct in vanilla, using it normally", itemType); return false; }
    ItemClass ic = classifyItem(itemPtr);
    if (ic.row < 0) { KP_LOG(chTarget, "target: item %08x not usable (%s), vanilla path", (unsigned)itemPtr, ic.why); return false; }
    if (!ic.healing) { KP_LOG(chTarget, "target: not a healing item (spells row %d), lowhp ignored", ic.row); return false; }
    party::Vitals v[3];
    int n = party::members(v, 3);
    if (n <= 0) { TARGET_FAIL(KP_LOGV(chTarget, KPLOG_WARN, "target: party members unreadable, using it normally")); }
    hb::Candidate c[3];
    buildCandidates(v, n, itemPtr, c);
    uint32_t mids[3] = {};
    for (int i = 0; i < n; ++i) {
        uint32_t& mid = mids[i];
        if (v[i].client) saferead::readAt<uint32_t>(S_Target, v[i].client, Client_ObjectId, &mid);
        KP_LOGV(chTarget, KPLOG_TRACE, "target:   [%d] client=%08x id=%08x server=%08x hp=%d/%d ok=%d down=%d eligible=%d", i, (unsigned)v[i].client, (unsigned)mid, (unsigned)v[i].server, v[i].cur, v[i].max, v[i].ok, v[i].down, c[i].eligible);
    }
    int thr = hb::effectiveThreshold(a.target, g_cfg.general);
    bool fbSelf = hb::effectiveFallbackSelf(a.target, g_cfg.general);
    applyPendingHeals(v, n, mids, c, true);
    int idx = hb::chooseTarget(c, n, 0, thr, fbSelf);
    if (idx < 0) KP_LOG(chTarget, "target: lowest-HP below %d%% (else %s) -> nobody", thr, fbSelf ? "self" : "nothing");
    else KP_LOG(chTarget, "target: lowest-HP below %d%% (else %s) -> %d", thr, fbSelf ? "self" : "nothing", idx);
    if (probe <= 1) { KP_LOG(chTarget, "target: TargetProbe=%d, not targeting (normal use on self)", probe); return false; }
    if (idx < 0) {   // TP3: say why on the slot and log each member once (the per-member line above is TRACE only)
        for (int i = 0; i < n; ++i) KP_LOG(chTarget, "target:   nobody: [%d] hp=%d/%d ok=%d down=%d eligible=%d", i, v[i].cur, v[i].max, v[i].ok, v[i].down, c[i].eligible);
        KP_LOG(chTarget, "target: nobody to use it on, skipped");
        g_useRefused = true; g_refuseText = hb::nobodyToHealTip(thr); return true;
    }
    uint32_t calledId = 0; bool handled = useOnMember(idx, v, clientItem, itemPtr, "lowhp", &calledId);
    if (calledId) { notePendingHeal(calledId, v[idx].cur); KP_LOGV(chTarget, KPLOG_DEBUG, "target: lowhp pending heal noted member %d id %08x hp=%d", idx, (unsigned)calledId, v[idx].cur); }
    return handled;
}

// TM_Self item slot: direct PerformUseItem(self) when spells.2da allows self use (vanilla invoke only ARMS portrait-pick with >= 2 members).
bool selfUse(const Entry& e, const hb::ActionRef& a) {
    uint32_t clientItem = (uint32_t)e.key & ~ItemKeyFlag;
    uintptr_t itemPtr = serverItemFor(clientItem);
    if (!itemPtr) return false;
    ItemClass ic = classifyItem(itemPtr);
    if (ic.row < 0) { KP_LOG(chTarget, "target: self '%s': item not usable (%s), vanilla path", a.name.c_str(), ic.why); return false; }
    if (!ic.selfOk) { KP_LOG(chTarget, "target: self not allowed for row %d", ic.row); return false; }
    party::Vitals v[3];
    if (party::members(v, 3) <= 0 || !v[0].client) { TARGET_FAIL(KP_LOGV(chTarget, KPLOG_WARN, "target: party members unreadable, using it normally")); }
    return useOnMember(0, v, clientItem, itemPtr, "self");
}

void showRefusal(int slot);   // RL24: defined after showTipText

void drainRing(uintptr_t hud) {
    while (g_ringTail != g_ringHead) {
        Req r = g_ring[g_ringTail]; g_ringTail = hb::ringNext(g_ringTail);
        hb::ActionRef a = g_eff[r.slot];   // Bottom row (row 0) only
        std::string sk = hb::SlotKeyName(0, r.slot);
        if (a.empty()) { KP_LOG(chSlots, "slot %s: unbound now (config changed?)", sk.c_str()); continue; }
        Entry e;
        GroupSnapshot snap(hud);   // fresh read per request
        if (!resolve(snap, a, &e)) {
            KP_LOG(chSlots, "%s", hb::fmtSlotMiss(sk, hb::Format(a), g_charKey).c_str());
            static int availLogs = 0;   // per process: the full list is only worth dumping a few times
            for (int g = 0; g < InvokableGroups; ++g) { for (auto& x : snap.get(g)) if (availLogs < 20) { ++availLogs; KP_LOG(chSlots, "avail: g%d.%d key=%08x %s%s%s%s", g, x.index, (unsigned)x.key, hb::Format(x.ref).c_str(), x.ref.kind == hb::K_Item ? "" : " \"", x.ref.kind == hb::K_Item ? "" : x.name.c_str(), x.ref.kind == hb::K_Item ? "" : "\""); } }
            continue;
        }
        KP_LOG(chSlots, "%s", hb::fmtSlotResolve(sk, e.group, e.index, (unsigned)e.key, (unsigned)e.flags, g_cfg.general.invoke != 0, hb::Format(a)).c_str());   // ref last: it can be 100 bytes
        if (a.kind != hb::K_Item && a.target.mode != hb::TM_Default) KP_LOG(chTarget, "target: mode ignored for non-item %.100s", hb::Format(a).c_str());
        // @self has no target decision to log, so TargetProbe=1 leaves it on the vanilla path
        // a direct route that returns false still falls through to the vanilla invoke below (when Invoke=1)
        int probe = a.kind == hb::K_Item ? targetProbeMode() : 0;   // only item slots consult TargetProbe (its bad-value WARN fires once, already at cfg load)
        hb::UseRoute route = hb::useRoute(a, probe, g_cfg.general.invoke != 0);
        if (!hb::directRouteAllowed(route, e.flags)) { KP_LOG(chTarget, "target: %s: @self entry not usable (flags %x), vanilla path reports why", sk.c_str(), (unsigned)e.flags); route = hb::UR_Invoke; }
        g_useRefused = false; g_refuseText.clear();
        if (route == hb::UR_SelfDirect && selfUse(e, a)) { if (g_useRefused) showRefusal(r.slot); continue; }
        if (route == hb::UR_LowHpDirect && targetedUse(e, a, probe)) { if (g_useRefused) showRefusal(r.slot); continue; }
        if (g_cfg.general.invoke) invokeEntry(hud, e, r.src);
    }
}

