const char* g_gateDetail = "";
// Diagnostic only: structured gate reason, logged on change by gateLog (never per frame, capped; past GateLogCap a 30 s heartbeat of the current state).
struct GateInfo { bool open = false; const char* why = "other"; uintptr_t hud = 0, top = 0; uint32_t f48 = 0, topF48 = 0; bool f48Bad = false; uintptr_t rawTop = 0; uint32_t rawTopVt = 0, rawTopF48 = 0; };
// A genuine panel flags dword is small (0x45/0x47/0x145); the first HUD build of a process can carry stale heap garbage (0xFF8FB4xx) that keeps bit 0x400 set forever.
bool hudFlagsPlausible(uint32_t f48) { return (f48 >> 12) == 0; }
constexpr int GateLogCap = 64;
void gateLog(const GateInfo& g) {
    static uint32_t lastRawVt = 0xFFFFFFFFu; static uintptr_t lastRaw = 0;
    if (g.rawTop && (g.rawTopVt != lastRawVt || g.rawTop != lastRaw)) { lastRawVt = g.rawTopVt; lastRaw = g.rawTop; KP_LOGV(chGate, KPLOG_DEBUG, "GATE rawtop=%08x vt=%08x f48=%08x ignored=%d (gate open=%d why=%s)", (unsigned)g.rawTop, (unsigned)g.rawTopVt, (unsigned)g.rawTopF48, (int)((g.rawTopF48 & PanelIgnoredByInput) != 0), (int)g.open, g.why); }   // RH5
    static GateInfo last; static bool have = false; static int lines = 0;
    const bool same = have && last.open == g.open && strcmp(last.why, g.why) == 0 && last.hud == g.hud && last.f48 == g.f48 && last.f48Bad == g.f48Bad && last.top == g.top && last.topF48 == g.topF48;
    // past the cap keep a 30 s heartbeat of the current state so late gate state stays visible
    if (lines > GateLogCap) { last = g; have = true; KP_LOG_EVERY(chGate, 30000, "GATE late open=%d why=%s hud=%08x f48=%08x top=%08x topf48=%08x", (int)g.open, g.why, (unsigned)g.hud, (unsigned)g.f48, (unsigned)g.top, (unsigned)g.topF48); return; }
    if (same) return;
    last = g; have = true;
    if (lines == GateLogCap) { ++lines; KP_LOG(chGate, "GATE cap reached"); return; }
    if (g.f48Bad) { ++lines; KP_LOG(chGate, "GATE hud flags implausible f48=%08x -> treated as not ignored", (unsigned)g.f48); if (lines >= GateLogCap) return; }
    ++lines;
    KP_LOG(chGate, "GATE open=%d why=%s hud=%08x f48=%08x bits=%03x top=%08x topf48=%08x", (int)g.open, g.why, (unsigned)g.hud, (unsigned)g.f48, (unsigned)(g.f48 & PanelIgnoredByInput), (unsigned)g.top, (unsigned)g.topF48);
}
bool gateEval(uintptr_t hud, GateInfo& g) {
    g = GateInfo(); g.hud = hud;
    if (!hud) { g.why = "no-hud"; g_gateDetail = "no hud"; return false; }
    g.f48 = (uint32_t)rdInt(S_Hud, hud, Panel_Flags);
    uintptr_t mgr; if (!saferead::readAt(S_Hud, hud, Hud_Manager, &mgr) || !mgr) { g_gateDetail = "no manager"; return false; }
    int modals = rdInt(S_Hud, mgr, Mgr_Modals), modalCount = rdInt(S_Hud, mgr, Mgr_ModalCount);
    if (modalCount < 0 || modalCount > 64) { g_gateDetail = "bad modal count"; return false; }
    for (int i = modalCount - 1; i >= 0; --i) {
        uintptr_t p; if (!saferead::readAt(S_Hud, (uintptr_t)modals, i * 4, &p) || !p) { g_gateDetail = "bad modal ptr"; return false; }
        if (!isIgnored(p)) { g.why = "modal-open"; g.top = p; g.topF48 = (uint32_t)rdInt(S_Hud, p, Panel_Flags); g_gateDetail = "modal open"; return false; }
    }
    int panels = rdInt(S_Hud, mgr, Mgr_Panels), panelCount = rdInt(S_Hud, mgr, Mgr_PanelCount);
    if (panelCount < 0 || panelCount > 256) { g_gateDetail = "bad panel count"; return false; }
    bool sawHudIgnored = false;
    for (int i = panelCount - 1; i >= 0; --i) {
        uintptr_t p; if (!saferead::readAt(S_Hud, (uintptr_t)panels, i * 4, &p) || !p) { g_gateDetail = "bad panel ptr"; return false; }
        if (i == panelCount - 1) { g.rawTop = p; g.rawTopF48 = (uint32_t)rdInt(S_Hud, p, Panel_Flags); uintptr_t vt = 0; saferead::readAt(S_Hud, p, 0, &vt); g.rawTopVt = (uint32_t)vt; }   // RH5: topmost panel even when its ignore bits hide it from the gate
        if (p == hud && !hudFlagsPlausible(g.f48)) g.f48Bad = true;   // garbage flags dword: do not trust the ignore bits (read-only; no engine write)
        else if (isIgnored(p)) { if (p == hud) sawHudIgnored = true; continue; }
        if (!g.top) { g.top = p; g.topF48 = (uint32_t)rdInt(S_Hud, p, Panel_Flags); }   // first non-ignored panel from the top
        if (p == hud) { g.why = "open"; g.open = true; g_gateDetail = "hud on top"; return true; }
        if (!isWhitelisted(p)) { g.why = "other-panel-on-top"; g.top = p; g.topF48 = (uint32_t)rdInt(S_Hud, p, Panel_Flags); g_gateDetail = "other panel on top"; return false; }
    }
    g.why = sawHudIgnored ? "hud-ignored" : "not-found";
    g_gateDetail = "hud not in list"; return false;
}
bool gameplayHudActive(uintptr_t hud) {
    GateInfo g; bool r = gateEval(hud, g);
    gateLog(g);
    return r;
}

