void updateButtons(uintptr_t hud, bool gate) {
    static uintptr_t lastMissingHud = 0;   // stays process-wide: it is read while g_bar belongs to a different HUD
    bool& lastGateSeen = g_bar.refreshLastGate; std::string& lastChar = g_bar.refreshLastChar; int& lastMode = g_bar.refreshLastMode;
    if (g_bar.panel != hud || g_bar.built == 0) {
        if (lastMissingHud != hud) { lastMissingHud = hud; KP_LOGV(chSlots, KPLOG_WARN, "buttons: no usable bar for hud %08x (bar panel=%08x built=%d/%d) -- HUD ctor hook did not run for it, or no button bound", (unsigned)hud, (unsigned)g_bar.panel, g_bar.built, ButtonCount); }
        return;
    }
    bool settling = hb::isSettling(g_charChangeTick, GetTickCount(), SettleMs);
    bool& wasSettling = g_bar.wasSettling; bool settleEdge = settling != wasSettling; wasSettling = settling;
    bool stale = settling || settleEdge || g_frame - g_bar.refreshLast >= ButtonRefreshFrames || gate != lastGateSeen || g_charKey != lastChar || g_bar.ed.mode != lastMode;
    if (!stale) return;
    GroupSnapshot snap(hud);   // one lazy snapshot per tick
    g_bar.refreshLast = g_frame; lastGateSeen = gate; lastChar = g_charKey; lastMode = g_bar.ed.mode;
    for (int s = 0; s < ButtonCount; ++s) {
        Button& b = g_bar.b[s];
        if (!b.bg.ctl && !b.ic.ctl) continue;
        if (!gate) { hideSlot(b, s, "hud not active"); continue; }
        // frame + digit are always shown while the HUD is active (an empty slot reads as a dim frame)
        hb::ActionRef want = g_eff[s];
        if (want.empty() && g_bar.ed.mode == M_Normal) {   // unassigned slots are invisible during play; edit mode shows them so they can be filled
            hideSlot(b, s, "unassigned"); continue;
        }
        Entry e; bool have = !want.empty() && resolve(snap, want, &e);
        hb::SlotView sv = hb::slotView(want.empty(), want.kind == hb::K_Item, have, have ? e.flags : 0, have ? e.key : 0, have ? e.name : std::string(), settling && g_bar.ed.mode == M_Normal);
        if (sv.hideSettling) { hideSlot(b, s, "settling after character switch"); continue; }
        if (!want.empty()) {   // change-only per slot (map section 4 #18); skipped while settling (that branch continued above)
            int h = have ? 1 : 0;
            if (b.lastHave != h) {
                if (!have) KP_LOG(chSlots, "slot %s: resolve miss ref=%s char='%s'", hb::SlotKeyName(0, s).c_str(), hb::Format(want).c_str(), g_charKey.c_str());
                else if (b.lastHave == 0) KP_LOG(chSlots, "slot %s: resolve ok group=%d index=%d", hb::SlotKeyName(0, s).c_str(), e.group, e.index);
                b.lastHave = h;
            }
        } else b.lastHave = -1;
        const char* state = sv.state;
        b.avail = have; if (have) b.entry = e;
        if (have && g_bar.tipSlot == s && slotTipText(s, e, false) != g_bar.tipText) { KP_LOGV(chTip, KPLOG_DEBUG, "tip: slot %d entry changed while hovered, refreshing", s); showTipAt(b.bg, e, s); }
        // An item that left the HUD's lists is out of stock: keep its (dimmed) icon from the last time it was seen and show "0"; it is not
        // hoverable or clickable (avail = false) and comes back by itself on the next refresh once the party has one again.
        std::string icon = have ? e.icon : (sv.outOfStock ? itemIconFor(want.name) : std::string());
        setVisible(b, b.bg, s, true, state); setVisible(b, b.ic, s, true, state); setVisible(b, b.num, s, true, state);
        if (sv.showQty) { wText(b.qty, "qty", std::to_string(sv.qty)); wTextColor(b.qty, "qty", sv.grayQty ? QtyOutOfStockRgb : b.qty.textRgb); setVisible(b, b.qty, s, true, state); }
        else setVisible(b, b.qty, s, false, sv.qtyHideWhy);
        setAlpha(b, b.bg, s, b.bg.baseAlpha * sv.bgFactor);
        setFill(b, b.ic, s, icon);
        bool lowHpDim = have && want.kind == hb::K_Item && want.target.mode == hb::TM_LowHp && !lowHpSlotEnabled(e, want);   // once per refresh, only for @lowhp item slots
        setAlpha(b, b.ic, s, b.ic.baseAlpha * (lowHpDim ? std::min(sv.icFactor, DimAlpha) : sv.icFactor));
        const char* badge = want.kind == hb::K_Item ? hb::badgeFor(want.target) : nullptr;
        if (badge) { setFill(b, b.tgt, s, badge); setAlpha(b, b.tgt, s, b.tgt.baseAlpha); setVisible(b, b.tgt, s, true, state); }
        else setVisible(b, b.tgt, s, false, want.kind == hb::K_Item ? "default target" : "not an item");
    }
}


