PendHeal g_pendHeal[3];
void notePendingHeal(uint32_t id, int hp) {
    int pick = -1;
    for (int i = 0; i < 3 && pick < 0; ++i) if (g_pendHeal[i].id == id) pick = i;   // pass 1: same member, update in place (no duplicate)
    for (int i = 0; i < 3 && pick < 0; ++i) if (!g_pendHeal[i].id) pick = i;        // pass 2: a free slot
    if (pick < 0) { pick = 0; for (int i = 1; i < 3; ++i) if ((int)(g_pendHeal[pick].since - g_pendHeal[i].since) > 0) pick = i; }   // pass 3: the oldest (wrap-safe)
    g_pendHeal[pick].id = id; g_pendHeal[pick].since = GetTickCount(); g_pendHeal[pick].hp = hp;
}
// RH4: members with a live pending heal become ineligible; resolved entries are cleared. log = false for the quiet dim check.
void applyPendingHeals(const party::Vitals* v, int n, const uint32_t* mids, hb::Candidate* c, bool log) {
    DWORD nowT = GetTickCount();
    for (int i = 0; i < n; ++i)
        for (PendHeal& p : g_pendHeal) if (p.id && p.id == mids[i]) {
            if (hb::pendingHealLive(nowT, p.since, v[i].cur, p.hp)) { c[i].eligible = false; if (log) KP_LOG(chTarget, "target: member %d id %08x has a pending heal (age %lu ms), skipped", i, (unsigned)p.id, (unsigned long)(nowT - p.since)); }
            else { if (log) KP_LOGV(chTarget, KPLOG_DEBUG, "target: pending heal cleared member id %08x", (unsigned)p.id); p.id = 0; }
        }
}
