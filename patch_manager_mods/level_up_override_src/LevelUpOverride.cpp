uint64_t fileStamp(const char* path) {   // 0 = missing
    WIN32_FILE_ATTRIBUTE_DATA d;
    if (!GetFileAttributesExA(path, GetFileExInfoStandard, &d)) return 0;
    return (static_cast<uint64_t>(d.ftLastWriteTime.dwHighDateTime) << 32 | d.ftLastWriteTime.dwLowDateTime) ^ d.nFileSizeLow;
}

char* trim(char* s) {
    while (*s == ' ' || *s == '\t') ++s;
    char* e = s + strlen(s);
    while (e > s && (e[-1] == ' ' || e[-1] == '\t' || e[-1] == '\r' || e[-1] == '\n')) *--e = 0;
    return s;
}
void lower(char* s) { for (; *s; ++s) if (*s >= 'A' && *s <= 'Z') *s += 32; }

void reloadConfig() {
    uint64_t st = fileStamp("levelup_override.ini");
    if (st == g_cfgStamp) return;
    g_cfgStamp = st;
    Config c;
    if (FILE* f = fopen("levelup_override.ini", "r")) {
        char line[512];
        while (fgets(line, sizeof line, f)) {
            char* l = trim(line);
            if (!*l || *l == ';' || *l == '#') continue;
            char* eq = strchr(l, '=');
            if (!eq) continue;
            *eq = 0;
            char* k = trim(l); char* v = trim(eq + 1);
            lower(k);
            if (!strcmp(k, "mode")) {
                lower(v);
                c.mode = !strcmp(v, "off") ? Mode::Off : !strcmp(v, "rewrite") ? Mode::Rewrite : Mode::Log;
            } else if (!strcmp(k, "verbose")) {
                c.verbose = atoi(v) != 0;
            } else if (!strcmp(k, "table")) {
                snprintf(c.table, sizeof c.table, "%s", v);
            } else if (!strcmp(k, "tags")) {
                lower(v);
                for (char* t = strtok(v, ","); t && c.nAllow < MaxAllow; t = strtok(nullptr, ",")) {
                    t = trim(t);
                    if (*t) snprintf(c.allow[c.nAllow++], 32, "%s", t);
                }
            }
        }
        fclose(f);
    }
    g_cfg = c;
    Buf b;
    for (int i = 0; i < c.nAllow; ++i) b.add("%s%s", i ? "," : "", c.allow[i]);
    logLine("CONFIG %s mode=%s verbose=%d table=%s tags=%s", st ? "loaded" : "missing (defaults)",
            c.mode == Mode::Off ? "off" : c.mode == Mode::Rewrite ? "rewrite" : "log", c.verbose, c.table, b.s);
}
bool allowed(const char* tag) {
    for (int i = 0; i < g_cfg.nAllow; ++i) if (!_stricmp(g_cfg.allow[i], tag)) return true;
    return false;
}

// ---- runtime table (levelup_paths.ini; format in gen_runtime_table.py docstring) -------------------------
constexpr int NumSkills = 8, MaxLevel = 50, MaxTags = 8, MaxList = 16, MaxGranted = 24, MaxClass = 256;
struct Rec {
    bool present; uint8_t cls, ability;
    int nFeats, nPowers, nSkills, nGranted;
    uint16_t feats[MaxList]; uint32_t powers[MaxList]; uint8_t skIdx[NumSkills], skRank[NumSkills];
    uint16_t granted[MaxGranted];
};
struct TagPaths { char tag[32]; Rec lv[MaxLevel + 1]; };
TagPaths g_tags[MaxTags];
int g_nTags = 0;
uint8_t g_cs[MaxClass][NumSkills];
bool g_csHave[MaxClass];
bool g_tableOk = false;
uint64_t g_tableStamp = ~0ULL;
char g_tableErr[160] = "";
char g_fileBuf[64 * 1024];

// Parses "1,2,3" (may be empty) into out; false on a non-digit token or overflow.
template <typename T> bool parseIds(char* s, T* out, int cap, int* n, uint32_t maxv) {
    *n = 0;
    if (!*s) return true;
    for (char* p = s;;) {
        char* comma = strchr(p, ',');
        if (comma) *comma = 0;
        if (!*p || *n >= cap) return false;
        for (char* q = p; *q; ++q) if (*q < '0' || *q > '9') return false;
        unsigned long v = strtoul(p, nullptr, 10);
        if (v > maxv) return false;
        out[(*n)++] = static_cast<T>(v);
        if (!comma) return true;
        p = comma + 1;
    }
}

// L<n>=cls|ability|feats|powers|skill:ranks|granted
bool parseRec(char* v, Rec* r) {
    char* f[6]; int nf = 0;
    f[nf++] = v;
    for (char* p = v; *p; ++p) if (*p == '|') { *p = 0; if (nf == 6) return false; f[nf++] = p + 1; }
    if (nf != 6) return false;
    uint8_t one[1]; int n;
    if (!parseIds(f[0], one, 1, &n, 255) || n != 1) return false;
    r->cls = one[0];
    if (!parseIds(f[1], one, 1, &n, 6) || n != 1) return false;
    r->ability = one[0];
    if (!parseIds(f[2], r->feats, MaxList, &r->nFeats, 0xFFFF)) return false;
    if (!parseIds(f[3], r->powers, MaxList, &r->nPowers, 0xFFFFFF)) return false;
    if (!parseIds(f[5], r->granted, MaxGranted, &r->nGranted, 0xFFFF)) return false;
    r->nSkills = 0;
    if (*f[4]) {
        for (char* p = f[4];;) {
            char* comma = strchr(p, ',');
            if (comma) *comma = 0;
            char* colon = strchr(p, ':');
            if (!colon || r->nSkills >= NumSkills) return false;
            *colon = 0;
            uint8_t a[1], b[1]; int na, nb;
            if (!parseIds(p, a, 1, &na, NumSkills - 1) || na != 1) return false;
            if (!parseIds(colon + 1, b, 1, &nb, 255) || nb != 1) return false;
            r->skIdx[r->nSkills] = a[0]; r->skRank[r->nSkills] = b[0]; ++r->nSkills;
            if (!comma) break;
            p = comma + 1;
        }
    }
    r->present = true;
    return true;
}

bool parseTable(const char* path) {
    g_nTags = 0;
    memset(g_csHave, 0, sizeof g_csHave);
    FILE* f = fopen(path, "rb");
    if (!f) { snprintf(g_tableErr, sizeof g_tableErr, "cannot open %s", path); return false; }
    size_t len = fread(g_fileBuf, 1, sizeof g_fileBuf - 1, f);
    bool full = feof(f) != 0;
    fclose(f);
    if (!full) { snprintf(g_tableErr, sizeof g_tableErr, "%s larger than %u bytes", path, (unsigned)sizeof g_fileBuf - 1); return false; }
    g_fileBuf[len] = 0;
    enum { None, ClassSkills, Tag } sec = None;
    TagPaths* cur = nullptr;
    int lineNo = 0;
    for (char* line = g_fileBuf; line;) {
        char* nl = strchr(line, '\n');
        if (nl) *nl = 0;
        ++lineNo;
        char* l = trim(line);
        line = nl ? nl + 1 : nullptr;
        if (!*l || *l == ';') continue;
        if (*l == '[') {
            char* e = strchr(l, ']');
            if (!e) goto bad;
            *e = 0; ++l; lower(l);
            if (!strcmp(l, "classskills")) { sec = ClassSkills; continue; }
            if (g_nTags >= MaxTags || strlen(l) >= 32 || !*l) goto bad;
            cur = &g_tags[g_nTags++];
            memset(cur, 0, sizeof *cur);
            snprintf(cur->tag, sizeof cur->tag, "%s", l);
            sec = Tag;
            continue;
        }
        char* eq = strchr(l, '=');
        if (!eq) goto bad;
        *eq = 0;
        char* k = trim(l); char* v = trim(eq + 1);
        if (sec == ClassSkills) {
            if (k[0] != 'c' || k[1] != 's') goto bad;
            uint8_t c[1]; int n;
            if (!parseIds(k + 2, c, 1, &n, MaxClass - 1) || n != 1 || strlen(v) != NumSkills) goto bad;
            for (int i = 0; i < NumSkills; ++i) {
                if (v[i] != '0' && v[i] != '1') goto bad;
                g_cs[c[0]][i] = v[i] == '1';
            }
            g_csHave[c[0]] = true;
        } else if (sec == Tag) {
            if (!strcmp(k, "name")) continue;
            if (k[0] != 'L') goto bad;
            uint8_t lv[1]; int n;
            if (!parseIds(k + 1, lv, 1, &n, MaxLevel) || n != 1) goto bad;
            if (!parseRec(v, &cur->lv[lv[0]])) goto bad;
        } else {
            goto bad;
        }
    }
    return true;
bad:
    snprintf(g_tableErr, sizeof g_tableErr, "%s line %d malformed", path, lineNo);
    g_nTags = 0;
    return false;
}

void reloadTable() {
    uint64_t st = fileStamp(g_cfg.table);
    if (st == g_tableStamp) return;
    g_tableStamp = st;
    g_tableOk = parseTable(g_cfg.table);
    if (g_tableOk) {
        Buf b;
        for (int t = 0; t < g_nTags; ++t) {
            int n = 0;
            for (int i = 0; i <= MaxLevel; ++i) n += g_tags[t].lv[i].present;
            b.add(" %s:%d", g_tags[t].tag, n);
        }
        logLine("TABLE loaded %s records%s", g_cfg.table, b.s);
    } else {
        logLine("TABLE ERROR %s -> rewrite disabled", g_tableErr);
    }
}

const TagPaths* findTag(const char* tag) {
    if (!g_tableOk) return nullptr;
    for (int t = 0; t < g_nTags; ++t) if (!_stricmp(g_tags[t].tag, tag)) return &g_tags[t];
    return nullptr;
}
const Rec* lookupRecord(const char* tag, int keyLevel) {
    const TagPaths* tp = findTag(tag);
    if (!tp || keyLevel < 0 || keyLevel > MaxLevel || !tp->lv[keyLevel].present) return nullptr;
    return &tp->lv[keyLevel];
}

// ---- dry-run algorithm (twin: simulate_rewrite.py compute_rewrite) ------------------------------------------
constexpr int MaxPend = 64;
struct Pend {
    int cls, ability, unspent;
    int nFeats, nSpells;
    uint16_t feats[MaxPend]; uint32_t spells[MaxPend];
    int deltas[NumSkills];
};
struct Result { const char* status; Pend p; };

int skillCost(const int* d, int cls) {
    int c = 0;
    for (int i = 0; i < NumSkills; ++i) c += d[i] * ((cls >= 0 && cls < MaxClass && g_csHave[cls] && !g_cs[cls][i]) ? 2 : 1);
    return c;
}
template <typename T> bool has(const T* a, int n, uint32_t v) { for (int i = 0; i < n; ++i) if (a[i] == v) return true; return false; }

Result computeRewrite(const Rec* r, const Pend& in) {
    Result res{"rewrite", in};
    if (!r) { res.status = "no-record"; return res; }
    if (r->cls != in.cls) { res.status = "class-mismatch"; return res; }
    Pend& o = res.p;
    o.nFeats = 0;
    for (int i = 0; i < in.nFeats; ++i) if (has(r->granted, r->nGranted, in.feats[i])) o.feats[o.nFeats++] = in.feats[i];
    for (int i = 0; i < r->nFeats; ++i) if (!has(o.feats, o.nFeats, r->feats[i]) && o.nFeats < MaxPend) o.feats[o.nFeats++] = r->feats[i];
    o.nSpells = 0;
    for (int i = 0; i < in.nSpells; ++i) if (isEngineGrantPower(in.spells[i])) o.spells[o.nSpells++] = in.spells[i];
    for (int i = 0; i < r->nPowers; ++i) if (!has(o.spells, o.nSpells, r->powers[i]) && o.nSpells < MaxPend) o.spells[o.nSpells++] = r->powers[i];
    for (int i = 0; i < NumSkills; ++i) o.deltas[i] = 0;
    for (int i = 0; i < r->nSkills; ++i) o.deltas[r->skIdx[i]] = r->skRank[i];
    o.unspent = in.unspent + skillCost(in.deltas, in.cls) - skillCost(o.deltas, in.cls);
    if (o.unspent < 0) { res.status = "negative-unspent"; res.p = in; return res; }
    o.ability = r->ability != 6 ? r->ability : in.ability;
    bool same = o.nFeats == in.nFeats && o.nSpells == in.nSpells && o.unspent == in.unspent && o.ability == in.ability &&
                !memcmp(o.feats, in.feats, sizeof(uint16_t) * in.nFeats) && !memcmp(o.spells, in.spells, sizeof(uint32_t) * in.nSpells) &&
                !memcmp(o.deltas, in.deltas, sizeof o.deltas);
    if (same) res.status = "already";
    return res;
}

void formatDry(Buf& b, const char* tag, int key, const Result& r) {
    b.add("DRY tag=%s key=%d status=%s feats=[", tag, key, r.status);
    for (int i = 0; i < r.p.nFeats; ++i) b.add("%s%u", i ? "," : "", r.p.feats[i]);
    b.add("] spells=[");
    for (int i = 0; i < r.p.nSpells; ++i) b.add("%s%u", i ? "," : "", r.p.spells[i]);
    b.add("] deltas=[");
    for (int i = 0; i < NumSkills; ++i) b.add("%s%d", i ? "," : "", r.p.deltas[i]);
    b.add("] unspent=%d ability=%d", r.p.unspent, r.p.ability);
}

// ---- dump helpers (every read SafeRead-guarded) -------------------------------------------------------------
enum Site : unsigned { S_Tag = 1, S_Class, S_Stats, S_Ranks, S_FeatList, S_Pend, S_PendArr, S_Rules, S_Frame };

bool readTag(uintptr_t stats, char* out, int cap) {
    out[0] = 0;
    uintptr_t cr = 0, str = 0; uint32_t len = 0;
    if (!readAt(S_Tag, stats, St_Creature, &cr) || !readAt(S_Tag, cr, Cr_Tag, &str) || !readAt(S_Tag, cr, Cr_Tag + 4, &len)) return false;
    if (!str || len == 0 || len >= static_cast<uint32_t>(cap) || !probeRead(S_Tag, reinterpret_cast<const void*>(str), len)) return false;
    memcpy(out, reinterpret_cast<const void*>(str), len);
    out[len] = 0;
    return true;
}

// Reads an engine {ptr,count,cap} array header + up to MaxPend elements of size esz into out (as uint32).
bool readArr(uintptr_t base, int off, int esz, uint32_t* out, int* n, uint32_t* count, uint32_t* cap) {
    uintptr_t p = 0;
    *n = 0;
    if (!readAt(S_PendArr, base, off, &p) || !readAt(S_PendArr, base, off + 4, count) || !readAt(S_PendArr, base, off + 8, cap)) return false;
    int take = *count > static_cast<uint32_t>(MaxPend) ? MaxPend : static_cast<int>(*count);
    if (take == 0) return true;
    if (!p || !probeRead(S_PendArr, reinterpret_cast<const void*>(p), static_cast<size_t>(take) * esz)) return false;
    for (int i = 0; i < take; ++i)
        out[i] = esz == 2 ? reinterpret_cast<const uint16_t*>(p)[i] : reinterpret_cast<const uint32_t*>(p)[i];
    *n = take;
    return true;
}

void listAdd(Buf& b, const uint32_t* v, int n, bool hex = false) {
    for (int i = 0; i < n; ++i) b.add(hex ? "%s0x%x" : "%s%u", i ? "," : "", v[i]);
}

volatile LONG g_calls = 0;
bool g_headerDone = false;

void rotateIfLarge() {
    WIN32_FILE_ATTRIBUTE_DATA d;
    if (GetFileAttributesExA(LogName, GetFileExInfoStandard, &d) && (d.nFileSizeHigh || d.nFileSizeLow > static_cast<DWORD>(RotateBytes))) {
        DeleteFileA("levelup_override_log.old.txt");
        MoveFileA(LogName, "levelup_override_log.old.txt");
    }
}

// Returns the flow name from the direct return address and the EBP chain (nearest frame that names a flow wins).
const char* classify(uintptr_t ret, const uintptr_t* frames, int nFrames) {
    const Fn* d = findFn(ret);
    if (d && d->flow) return d->flow;
    for (int i = 0; i < nFrames; ++i) {
        const Fn* f = findFn(frames[i]);
        if (f && f->flow) return f->flow;
    }
    for (int i = 0; i < nFrames; ++i) {
        const Fn* f = findFn(frames[i]);
        if (f && f->lo == 0x006BEDF0) return "auto-other";
    }
    return "unknown";
}

void onLevelUp(uintptr_t stats, uintptr_t ret, uintptr_t pending, int addToList, uintptr_t ebp) {
    LONG call = InterlockedIncrement(&g_calls);
    if (!g_headerDone) {
        g_headerDone = true;
        rotateIfLarge();
        logLine("== LevelUpOverride %s loaded; first LevelUp call (dry-run build, apply=%d) ==", Version, ApplyEnabled);
    }
    reloadConfig();
    if (g_cfg.mode == Mode::Off) return;
    reloadTable();
    if (!logOpen()) return;
    const bool v = g_cfg.verbose;

    // -- caller chain: EBP at hook time = LevelUp's caller frame; [ebp+4] = caller's return address
    uintptr_t frames[4]; int nFrames = 0;
    for (uintptr_t e = ebp; nFrames < 4;) {
        uintptr_t next = 0, r = 0;
        if (!readAt(S_Frame, e, 4, &r) || !readAt(S_Frame, e, 0, &next)) break;
        frames[nFrames++] = r;
        if (next <= e || next - e > 0x100000) break;
        e = next;
    }
    const char* flow = classify(ret, frames, nFrames);
    Buf chain;
    const Fn* rf = findFn(ret);
    chain.add("ret=%08x(%s)", (unsigned)ret, rf ? rf->name : "?");
    for (int i = 0; i < nFrames; ++i) {
        const Fn* f = findFn(frames[i]);
        chain.add(" <- %08x(%s)", (unsigned)frames[i], f ? f->name : "?");
    }

    // -- creature
    char tag[32];
    bool tagOk = readTag(stats, tag, sizeof tag);
    if (!tagOk) strcpy(tag, "?");
    uint8_t nClass = 0;
    int total = 0;
    Buf cls;
    if (readAt(S_Class, stats, St_ClassCount, &nClass)) {
        if (nClass > 4) { cls.add("count=%u?", nClass); total = -1; nClass = 0; }
        for (int i = 0; i < nClass; ++i) {
            uint8_t id = 0, lv = 0, neg = 0;
            if (!readAt(S_Class, stats, St_ClassId + i * St_ClassStride, &id) || !readAt(S_Class, stats, St_ClassLevel + i * St_ClassStride, &lv) ||
                !readAt(S_Class, stats, St_ClassNeg + i * St_ClassStride, &neg)) { cls.add(" ?"); total = -1; break; }
            cls.add("%s%u:%u%s", i ? "," : "", id, lv, neg ? "(neg)" : "");
            if (neg) cls.add("%u", neg);
            total += lv;
        }
    } else {
        total = -1;
    }
    uint32_t xp = 0; uint16_t stUnspent = 0;
    readAt(S_Stats, stats, St_XP, &xp);
    readAt(S_Stats, stats, St_Unspent, &stUnspent);

    uintptr_t rules = 0; uint8_t nSkills = 0;
    if (readAt(S_Rules, RulesGlobal, 0, &rules)) readAt(S_Rules, rules, Rules_SkillCount, &nSkills);
    if (nSkills > 32) nSkills = 32;

    // -- pending
    uint8_t raw[Pd_Size];
    bool pendOk = pending && probeRead(S_Pend, reinterpret_cast<const void*>(pending), Pd_Size);
    if (pendOk) memcpy(raw, reinterpret_cast<const void*>(pending), Pd_Size);
    int key = total >= 0 ? total + 1 : -1;

    logf("[%lu] #%ld tid=%lu flow=%s %s stats=%08x pending=%08x addToList=%d tag=%s classes=%s total=%d key=%d xp=%u unspent170=%u",
         GetTickCount(), call, GetCurrentThreadId(), flow, chain.s, (unsigned)stats, (unsigned)pending, addToList, tag, cls.s, total, key,
         xp, stUnspent);

    if (!pendOk) { logf("  pending unreadable -> vanilla"); logClose(); return; }
    Pend pd{};
    pd.cls = raw[Pd_Class];
    pd.ability = raw[Pd_Ability];
    pd.unspent = *reinterpret_cast<uint16_t*>(raw + Pd_Unspent);
    uint32_t tmp[MaxPend], cnt = 0, cap = 0; int n = 0;
    bool featsOk = readArr(pending, Pd_Feats, 2, tmp, &n, &cnt, &cap);
    pd.nFeats = n;
    for (int i = 0; i < n; ++i) pd.feats[i] = static_cast<uint16_t>(tmp[i]);
    uint32_t fCnt = cnt, fCap = cap;
    bool spellsOk = readArr(pending, Pd_SpellsAdd, 4, pd.spells, &n, &cnt, &cap);
    pd.nSpells = n;
    uint32_t sCnt = cnt, sCap = cap;
    uint32_t rem[MaxPend]; int nRem = 0; uint32_t rCnt = 0, rCap = 0;
    bool remOk = readArr(pending, Pd_SpellsRem, 4, rem, &nRem, &rCnt, &rCap);
    uintptr_t deltasP = *reinterpret_cast<uint32_t*>(raw + Pd_Deltas);
    uint8_t deltas[32] = {};
    bool deltasOk = nSkills && deltasP && probeRead(S_PendArr, reinterpret_cast<const void*>(deltasP), nSkills);
    if (deltasOk) memcpy(deltas, reinterpret_cast<const void*>(deltasP), nSkills);
    for (int i = 0; i < NumSkills; ++i) pd.deltas[i] = deltas[i];

    if (v) {
        Buf b;
        b.add("  pend: class=%u ability=%u hp=%u force=%u unspent28=%u skills(n=%u)%s=[", raw[Pd_Class], raw[Pd_Ability], raw[Pd_HP],
              raw[Pd_Force], pd.unspent, nSkills, deltasOk ? "" : "UNREADABLE");
        for (int i = 0; i < nSkills; ++i) b.add("%s%u", i ? "," : "", deltas[i]);
        b.add("]");
        logf("%s", b.s);
        Buf f;
        f.add("  pend.feats%s count=%u cap=%u [", featsOk ? "" : " UNREADABLE", fCnt, fCap);
        listAdd(f, tmp, pd.nFeats);
        f.add("]");
        logf("%s", f.s);
        Buf s;
        s.add("  pend.spellsAdd%s count=%u cap=%u [", spellsOk ? "" : " UNREADABLE", sCnt, sCap);
        listAdd(s, pd.spells, pd.nSpells, true);
        s.add("] spellsRem%s count=%u cap=%u [", remOk ? "" : " UNREADABLE", rCnt, rCap);
        listAdd(s, rem, nRem, true);
        s.add("]");
        logf("%s", s.s);
        Buf h;
        h.add("  pend.raw");
        for (int i = 0; i < Pd_Size; ++i) h.add("%s%02x", (i % 4) ? "" : " ", raw[i]);
        logf("%s", h.s);

        // creature skill ranks and feat list (before LevelUp applies anything)
        Buf r;
        uintptr_t ranksP = 0;
        r.add("  stats.ranks=[");
        if (readAt(S_Ranks, stats, St_SkillRanks, &ranksP) && nSkills && probeRead(S_Ranks, reinterpret_cast<const void*>(ranksP), nSkills))
            for (int i = 0; i < nSkills; ++i) r.add("%s%u", i ? "," : "", reinterpret_cast<const uint8_t*>(ranksP)[i]);
        else
            r.add("UNREADABLE");
        r.add("]");
        logf("%s", r.s);
        // feat lists: +0x00 full list, +0x18 second list (both {ushort*, count}; HasFeat 0x6B83F0 checks both)
        const int lists[2] = {St_FeatList, St_FeatList2};
        for (int L = 0; L < 2; ++L) {
            Buf fb;
            uintptr_t fl = 0; uint32_t fc = 0;
            fb.add("  stats.feats%s", L ? "2" : "");
            if (readAt(S_FeatList, stats, lists[L], &fl) && readAt(S_FeatList, stats, lists[L] + 4, &fc)) {
                uint32_t take = fc > 200 ? 200 : fc;
                fb.add(" count=%u [", fc);
                if (take && fl && probeRead(S_FeatList, reinterpret_cast<const void*>(fl), take * 2))
                    for (uint32_t i = 0; i < take; ++i) fb.add("%s%u", i ? "," : "", reinterpret_cast<const uint16_t*>(fl)[i]);
                fb.add("]");
            } else {
                fb.add(" UNREADABLE");
            }
            logf("%s", fb.s);
        }
    }

    // -- dry run for tags that have a table section
    if (tagOk && findTag(tag)) {
        if (nSkills != NumSkills || !deltasOk || !featsOk || !spellsOk || fCnt > static_cast<uint32_t>(MaxPend) || sCnt > static_cast<uint32_t>(MaxPend)) {
            logf("  DRY tag=%s key=%d status=skipped-unreadable (skills=%u feats=%u spells=%u)", tag, key, nSkills, fCnt, sCnt);
        } else {
            char lt[32]; snprintf(lt, sizeof lt, "%s", tag); lower(lt);
            Result res = computeRewrite(lookupRecord(tag, key), pd);
            Buf d;
            formatDry(d, lt, key, res);
            logf("  %s", d.s);
            if (g_cfg.mode == Mode::Rewrite && allowed(tag) && !strcmp(res.status, "rewrite"))
                logf("  WOULD REWRITE %s key=%d (this build is dry-run only; apply=%d)", lt, key, ApplyEnabled);
        }
    } else if (g_cfg.mode == Mode::Rewrite && tagOk && allowed(tag)) {
        logf("  tag %s allowed but no table section (table %s)", tag, g_tableOk ? "ok" : "ERROR");
    }
    logClose();
}

