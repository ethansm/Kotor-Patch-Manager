uint64_t fileStamp(const char* path) {   // 0 = missing
    WIN32_FILE_ATTRIBUTE_DATA d;
    if (!GetFileAttributesExA(path, GetFileExInfoStandard, &d)) return 0;
    return (static_cast<uint64_t>(d.ftLastWriteTime.dwHighDateTime) << 32 | d.ftLastWriteTime.dwLowDateTime) ^ d.nFileSizeLow;
}

// True when a file check is due: always on the first call and when forced, else at most once per ReloadThrottleMs.
bool reloadDue(DWORD* last, bool* checked, bool force) {
    DWORD now = GetTickCount();
    if (*checked && !force && now - *last < ReloadThrottleMs) return false;
    *last = now; *checked = true;
    return true;
}

char* trim(char* s) {
    while (*s == ' ' || *s == '\t') ++s;
    char* e = s + strlen(s);
    while (e > s && (e[-1] == ' ' || e[-1] == '\t' || e[-1] == '\r' || e[-1] == '\n')) *--e = 0;
    return s;
}
void lower(char* s) { for (; *s; ++s) if (*s >= 'A' && *s <= 'Z') *s += 32; }

void resolvePresets();   // below (needs the table)

// Entry for `tag` (lowercase) in a Config being built; creates it (hold default 1, instant 0) when missing. nullptr when full.
int cfgEntry(Config& c, const char* tag, bool create = true) {
    for (int i = 0; i < c.nTags; ++i) if (!_stricmp(c.tags[i].tag, tag)) return i;
    if (!create || c.nTags >= MaxTagCfg) return -1;
    TagCfg& t = c.tags[c.nTags];
    snprintf(t.tag, sizeof t.tag, "%s", tag);
    t.preset = -1; t.instant = false; t.hold = true; t.pause = 0;
    c.presetId[c.nTags][0] = 0;
    return c.nTags++;
}

void reloadConfig(bool force = false) {
    if (!reloadDue(&g_cfgLast, &g_cfgChecked, force)) return;
    uint64_t st = fileStamp("levelup_override.ini");
    if (st == g_cfgStamp) return;
    g_cfgStamp = st;
    Config c;
    char legacy[MaxTagCfg][32]; int nLegacy = 0;
    bool hasInstant[MaxTagCfg] = {}, hasHold[MaxTagCfg] = {};
    if (FILE* f = fopen("levelup_override.ini", "r")) {
        char line[512];
        while (fgets(line, sizeof line, f)) {
            char* l = trim(line);
            if (!*l || *l == ';' || *l == '#') continue;
            char* eq = strchr(l, '=');
            if (!eq) continue;
            *eq = 0;
            char* k = trim(l); char* v = trim(eq + 1);
            lower(k);
            if (!strcmp(k, "mode")) {
                char raw[48]; snprintf(raw, sizeof raw, "%s", v);
                lower(v);
                if (!strcmp(v, "off")) c.mode = Mode::Off;
                else if (!strcmp(v, "log")) c.mode = Mode::Log;
                else {
                    c.mode = Mode::Rewrite;   // F17: same as a missing key; only an explicit mode=rewrite is silent
                    if (strcmp(v, "rewrite")) logLine("CONFIG WARNING unknown mode=%s - using rewrite", raw);
                }
            } else if (!strcmp(k, "dev")) {
                c.dev = atoi(v) != 0;
            } else if (!strcmp(k, "r10probe")) {
                c.r10probe = atoi(v) != 0;
            } else if (!strcmp(k, "r10")) {
                c.r10 = atoi(v) != 0;
            } else if (!strcmp(k, "r10.profile")) {
                lower(v); snprintf(c.r10Profile, sizeof c.r10Profile, "%s", v);
            } else if (!strcmp(k, "r10.feats")) {
                lower(v); c.r10Feats = r10f::parseMode(v);
            } else if (!strcmp(k, "r10.powers")) {
                lower(v); c.r10Powers = r10f::parseMode(v);
            } else if (!strcmp(k, "ui.icon")) {
                lower(v); if (*v && strlen(v) < sizeof c.uiIcon) snprintf(c.uiIcon, sizeof c.uiIcon, "%s", v);
            } else if (!strcmp(k, "verbose")) {
                c.verbose = atoi(v) != 0;
            } else if (!strcmp(k, "apply")) {
                c.apply = atoi(v) != 0;
            } else if (!strcmp(k, "table")) {
                snprintf(c.table, sizeof c.table, "%s", v);
            } else if (!strcmp(k, "tags")) {
                lower(v);
                for (char* t = strtok(v, ","); t && nLegacy < MaxTagCfg; t = strtok(nullptr, ",")) {
                    t = trim(t);
                    if (*t) snprintf(legacy[nLegacy++], 32, "%s", t);
                }
            } else if (!strncmp(k, "preset.", 7) && k[7]) {
                int i = cfgEntry(c, k + 7);
                if (i >= 0) { lower(v); snprintf(c.presetId[i], sizeof c.presetId[i], "%s", v); }
            } else if (!strncmp(k, "instant.", 8) && k[8]) {
                int i = cfgEntry(c, k + 8);
                if (i >= 0) { c.tags[i].instant = atoi(v) != 0; hasInstant[i] = true; }
            } else if (!strncmp(k, "hold.", 5) && k[5]) {
                int i = cfgEntry(c, k + 5);
                if (i >= 0) { c.tags[i].hold = atoi(v) != 0; hasHold[i] = true; }
            } else if (!strncmp(k, "pause.", 6) && k[6]) {
                int i = cfgEntry(c, k + 6);
                if (i >= 0) { const int n = atoi(v); c.tags[i].pause = n > 0 ? n : 0; }   // garbage / negative = 0 (preset default)
            }
        }
        fclose(f);
    }
    if (!c.dev) { c.nTags = 0; nLegacy = 0; }   // dev keys (any order in the file) count only with dev=1
    // Legacy allow-list: a tag without a preset key behaves as in 0.2.1 (preset <tag>__live, no instant, no hold).
    for (int j = 0; j < nLegacy; ++j) {
        int i = cfgEntry(c, legacy[j]);
        if (i < 0 || c.presetId[i][0]) continue;
        snprintf(c.presetId[i], sizeof c.presetId[i], "%s__live", c.tags[i].tag);
        if (!hasInstant[i]) c.tags[i].instant = false;
        if (!hasHold[i]) c.tags[i].hold = false;
    }
    g_cfg = c;
    resolvePresets();
    Buf b;
    for (int i = 0; i < c.nTags; ++i) b.add("%s%s:%s/i%d/h%d/p%d", i ? "," : "", c.tags[i].tag, c.presetId[i][0] ? c.presetId[i] : "-", c.tags[i].instant, c.tags[i].hold, c.tags[i].pause);
    logLine("CONFIG %s mode=%s apply=%d verbose=%d table=%s tags=%s", st ? "loaded" : "missing (defaults)",
            c.mode == Mode::Off ? "off" : c.mode == Mode::Rewrite ? "rewrite" : "log", c.apply, c.verbose, c.table, b.s);
    if (c.r10) logLine("R10 config r10=1 profile=%s feats=%s powers=%s", c.r10Profile[0] ? c.r10Profile : "-", r10f::modeName(c.r10Feats), r10f::modeName(c.r10Powers));
    if (c.dev) logLine("DEV keys enabled (dev=1): preset./instant./hold./pause.<tag>= and tags= are read");
}

// Per-tag configuration lookup (case-insensitive); nullptr = unconfigured -> every gate passes through.
// Playthrough section of the current GUID wins outright (g_ptActive); else the dev keys of levelup_override.ini.
const TagCfg* tagConfig(const char* tag) {
    if (!tag || !*tag) return nullptr;
    Config& c = g_ptActive ? g_ptCfg : g_cfg;
    for (int i = 0; i < c.nTags; ++i) if (!_stricmp(c.tags[i].tag, tag)) return &c.tags[i];
    return nullptr;
}
// Requested preset id of an entry returned by tagConfig (either source).
const char* presetIdOf(const TagCfg* t) {
    if (t >= g_ptCfg.tags && t < g_ptCfg.tags + MaxTagCfg) return g_ptCfg.presetId[t - g_ptCfg.tags];
    return g_cfg.presetId[t - g_cfg.tags];
}

// ---- runtime table v3 (levelup_paths.ini; format in gen_runtime_table.py docstring; v3 = v2 + [featrules]/[powerrules]) ----------------------
