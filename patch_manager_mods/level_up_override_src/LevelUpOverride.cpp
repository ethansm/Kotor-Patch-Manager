//   hold gate    CanLevelUp 0x6B9790 at 13 sites: result forced to 0 while levelNow()==HOLD (mode=rewrite; mode=log logs WOULD HOLD)
//   instant gate options accessor 0x72FB00 at 4 sites: returns a copy of the options with bit0 of +8 set (instant.<tag>=1, not held)
//   GUI guards   GetCharacterChangeInProgress 0x740FC0 at 0x84FD2F / 0x84F9FE: nonzero for a held leader (button/hotkey/confirm box)
//   Auto OK      0x77D800 at 0x850062: returns 0 for a held leader so DoAutoLevelup skips AutoLevelup
// All handlers pass through to the real function on any unreadable pointer, for the PC (empty tag) and for unconfigured tags.
