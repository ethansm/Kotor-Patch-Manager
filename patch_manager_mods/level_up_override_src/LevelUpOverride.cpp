// Hook 0x006B9870 (CSWSCreatureStats::LevelUp entry). Params in hooks.toml order: ecx, [esp+0], [esp+4], [esp+8], ebp.
void __cdecl LevelUpOverrideEntry(void* stats, void* ret, void* pending, int addToList, void* ebp) {
    saferead::beginScope();
    onLevelUp(reinterpret_cast<uintptr_t>(stats), reinterpret_cast<uintptr_t>(ret), reinterpret_cast<uintptr_t>(pending), addToList,
              reinterpret_cast<uintptr_t>(ebp));
}

