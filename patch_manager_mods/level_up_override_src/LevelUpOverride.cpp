// The creature's class entries (engine order, newest last) and total level; false when unreadable or not 1..4 classes.
bool readClasses(uintptr_t stats, uint8_t* ids, uint8_t* lvls, int* n, int* total) {
    uint8_t cnt = 0;
    *n = 0; *total = 0;
    if (!readAt(S_Class, stats, St_ClassCount, &cnt) || cnt < 1 || cnt > 4) return false;
    for (int i = 0; i < cnt; ++i) {
        if (!readAt(S_Class, stats, St_ClassId + i * St_ClassStride, &ids[i]) || !readAt(S_Class, stats, St_ClassLevel + i * St_ClassStride, &lvls[i])) return false;
        *total += lvls[i];
    }
    *n = cnt;
    return true;
}

// Bit i set = the creature already has the Class Skill feat (183-189) of skill i (both creature feat lists, as HasFeat 0x6B83F0 checks).
uint8_t classSkillMask(uintptr_t stats) {
    uint8_t mask = 0;
    const int lists[2] = {St_FeatList, St_FeatList2};
    for (int L = 0; L < 2; ++L) {
        uint32_t fl = 0, fc = 0;
        if (!readAt(S_FeatList, stats, lists[L], &fl) || !readAt(S_FeatList, stats, lists[L] + 4, &fc) || !fl) continue;
        uint32_t take = fc > 200 ? 200 : fc;
        const uintptr_t a = fl;
        if (!take || !probeRead(S_FeatList, reinterpret_cast<const void*>(a), take * 2)) continue;
        for (uint32_t i = 0; i < take; ++i) {
            int sk = classSkillFeatSkill(reinterpret_cast<const uint16_t*>(a)[i]);
            if (sk >= 0) mask |= static_cast<uint8_t>(1u << sk);
        }
    }
    return mask;
}

// The creature's known feats (both lists, as HasFeat 0x6B83F0 checks) and known powers (one engine array per class entry, see St_ClassSpells) for carry-over.
// Returns false when a feat list is unreadable or over its cap (carry skipped); *pkOk = every class entry's power array was read (false: powers stay plain).
constexpr int MaxFeatListRead = 200, MaxPowersPerClass = 100;
bool readKnown(uintptr_t stats, int nClass, KnownSet* ks, bool* pkOk) {
    ks->nf = ks->np = 0;
    *pkOk = false;
    const int lists[2] = {St_FeatList, St_FeatList2};
    for (int L = 0; L < 2; ++L) {
        uint32_t fl = 0, fc = 0;
        if (!readAt(S_FeatList, stats, lists[L], &fl) || !readAt(S_FeatList, stats, lists[L] + 4, &fc) || fc > static_cast<uint32_t>(MaxFeatListRead)) return false;
        if (!fc) continue;
        const uintptr_t a = fl;
        if (!a || !probeRead(S_FeatList, reinterpret_cast<const void*>(a), fc * 2)) return false;
        for (uint32_t i = 0; i < fc; ++i) ks->f[ks->nf++] = reinterpret_cast<const uint16_t*>(a)[i];
    }
    bool ok = nClass >= 1 && nClass <= 4;
    for (int c = 0; ok && c < nClass; ++c) {
        uint32_t pa = 0, pc = 0, pcap = 0;
        const int off = St_ClassSpells + c * St_ClassStride;
        if (!readAt(S_Class, stats, off, &pa) || !readAt(S_Class, stats, off + 4, &pc) || !readAt(S_Class, stats, off + 8, &pcap) ||
            pc > static_cast<uint32_t>(MaxPowersPerClass) || pc > pcap || pcap >= 4096) { ok = false; break; }   // {ptr, count, cap}: count <= cap < 4096 or it is not a power array
        if (!pc) continue;
        const uintptr_t a = pa;
        if (!a || !probeRead(S_Class, reinterpret_cast<const void*>(a), pc * 4)) { ok = false; break; }
        for (uint32_t i = 0; i < pc; ++i) ks->p[ks->np++] = reinterpret_cast<const uint32_t*>(a)[i];
    }
    // sanity: a Jedi class past its first level always has powers (Force powers from the class table); none at all = the array is not what we think it is
    for (int c = 0; ok && c < nClass; ++c) {
        uint8_t id = 0, lv = 0;
        if (!readAt(S_Class, stats, St_ClassId + c * St_ClassStride, &id) || !readAt(S_Class, stats, St_ClassLevel + c * St_ClassStride, &lv)) { ok = false; break; }
        if (isJediClass(id) && lv >= 2 && !ks->np) ok = false;
    }
    *pkOk = ok;
    if (!ok) ks->np = 0;
    return true;
}

// ---- M3 save binding: playthrough GUID in 32 Boolean globals + levelup_playthroughs.ini ------------------------
// The table (CSWGlobalVariableTable) is saved/loaded by name by the engine and re-adds unknown names on load, so LUO_G00..LUO_G31 round-trip
// through a save without a globalcat.2da row (doc 08 Item 7). All engine calls are thiscall with CExoString names built by the engine ctor.
constexpr unsigned S_Glob = 110;
constexpr uintptr_t TableOffset = 0x100FC;   // CServerExoAppInternal -> globals table (an address inside the object, not a pointer)
typedef void* (__thiscall* StrCtor_t)(void* buf, const char* s);
typedef void (__thiscall* StrDtor_t)(void* buf);
typedef int (__thiscall* GFind_t)(void* table, void* name);
typedef int (__thiscall* GAdd_t)(void* table, void* name);
typedef void (__thiscall* GSet_t)(void* table, void* name, uint32_t v);
typedef void (__thiscall* GGet_t)(void* table, void* name, int* out);
typedef int (__thiscall* ServerInit_t)(void* app);

int g_guidEngState = 0;   // 0 unchecked, 1 verified, 2 mismatch (save binding disabled; the gates keep working)
bool guidEngineOk() {
    if (!g_eng.checkCode) return true;
    if (!g_guidEngState) {
        const bool ok = codeMatches(g_eng.guidFind, kGuidFindCode, sizeof kGuidFindCode) && codeMatches(g_eng.guidAdd, kGuidAddCode, sizeof kGuidAddCode) &&
                        codeMatches(g_eng.guidSet, kGuidSetCode, sizeof kGuidSetCode) && codeMatches(g_eng.guidGet, kGuidGetCode, sizeof kGuidGetCode) &&
                        codeMatches(g_eng.strCtor, kStrCtorCode, sizeof kStrCtorCode) && codeMatches(g_eng.strDtor, kStrDtorCode, sizeof kStrDtorCode) &&
                        codeMatches(g_eng.serverInit, kServerInitCode, sizeof kServerInitCode);
        g_guidEngState = ok ? 1 : 2;
        if (!ok) logLine("GUID ENGINE mismatch - save binding disabled (gates keep working)");
    }
    return g_guidEngState == 1;
}

// Live globals table: *(*(*[appGlobal]+8)+4) + 0x100FC; 0 on any null / unreadable link (main menu: server app is 0).
uintptr_t liveTable() {
    uint32_t app = 0, srv = 0, intl = 0;
    if (!readAt(S_Glob, g_eng.appGlobal, 0, &app) || !app || !readAt(S_Glob, app, 8, &srv) || !srv || !readAt(S_Glob, srv, 4, &intl) || !intl) return 0;
    return intl + TableOffset;
}

// Writes the 32 bits (Find first: AddBoolean has no duplicate check), then reads each back. True when every bit reads back as written.
bool writeGuid(void* table, uint32_t guid) {
    uint8_t bits[32];
    pt::unpackBits(guid, bits);
    bool ok = true;
    for (int i = 0; i < 32; ++i) {
        char nm[8]; uint32_t cs[2] = {0, 0};
        pt::bitName(i, nm);
        reinterpret_cast<StrCtor_t>(g_eng.strCtor)(cs, nm);
        if (reinterpret_cast<GFind_t>(g_eng.guidFind)(table, cs) < 0 && reinterpret_cast<GAdd_t>(g_eng.guidAdd)(table, cs) < 0) {
            ok = false;
        } else {
            int back = 0;
            reinterpret_cast<GSet_t>(g_eng.guidSet)(table, cs, bits[i]);
            reinterpret_cast<GGet_t>(g_eng.guidGet)(table, cs, &back);
            if (back != bits[i]) ok = false;
        }
        reinterpret_cast<StrDtor_t>(g_eng.strDtor)(cs);
    }
    return ok;
}
// Reads the bits of the names that exist; *found = how many of the 32 names exist (0 = no GUID saved).
void readGuid(void* table, uint32_t* guid, int* found) {
    uint8_t bits[32] = {};
    *found = 0;
    for (int i = 0; i < 32; ++i) {
        char nm[8]; uint32_t cs[2] = {0, 0};
        pt::bitName(i, nm);
        reinterpret_cast<StrCtor_t>(g_eng.strCtor)(cs, nm);
        if (reinterpret_cast<GFind_t>(g_eng.guidFind)(table, cs) >= 0) {
            int v = 0;
            reinterpret_cast<GGet_t>(g_eng.guidGet)(table, cs, &v);
            bits[i] = v != 0;
            ++*found;
        }
        reinterpret_cast<StrDtor_t>(g_eng.strDtor)(cs);
    }
    *guid = pt::packBits(bits);
}

