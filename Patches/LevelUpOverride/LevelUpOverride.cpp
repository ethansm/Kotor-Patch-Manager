DWORD g_cfgLast = 0, g_tableLast = 0;
bool g_cfgChecked = false, g_tableChecked = false;

uint64_t fileStamp(const char* path) {   // 0 = missing
    WIN32_FILE_ATTRIBUTE_DATA d;
    if (!GetFileAttributesExA(path, GetFileExInfoStandard, &d)) return 0;
    return (static_cast<uint64_t>(d.ftLastWriteTime.dwHighDateTime) << 32 | d.ftLastWriteTime.dwLowDateTime) ^ d.nFileSizeLow;
}

// True when a file check is due: always on the first call and when forced, else at most once per ReloadThrottleMs.
bool reloadDue(DWORD* last, bool* checked, bool force) {
    DWORD now = GetTickCount();
    if (*checked && !force && now - *last < ReloadThrottleMs) return false;
    *last = now; *checked = true;
    return true;
}

char* trim(char* s) {
    while (*s == ' ' || *s == '\t') ++s;
    char* e = s + strlen(s);
    while (e > s && (e[-1] == ' ' || e[-1] == '\t' || e[-1] == '\r' || e[-1] == '\n')) *--e = 0;
    return s;
}
void lower(char* s) { for (; *s; ++s) if (*s >= 'A' && *s <= 'Z') *s += 32; }

void resolvePresets();   // below (needs the table)

// Entry for `tag` (lowercase) in a Config being built; creates it (hold default 1, instant 0) when missing. nullptr when full.
int cfgEntry(Config& c, const char* tag, bool create = true) {
    for (int i = 0; i < c.nTags; ++i) if (!_stricmp(c.tags[i].tag, tag)) return i;
    if (!create || c.nTags >= MaxTagCfg) return -1;
    TagCfg& t = c.tags[c.nTags];
    snprintf(t.tag, sizeof t.tag, "%s", tag);
    t.preset = -1; t.instant = false; t.hold = true;
    c.presetId[c.nTags][0] = 0;
    return c.nTags++;
}

void reloadConfig(bool force = false) {
    if (!reloadDue(&g_cfgLast, &g_cfgChecked, force)) return;
    uint64_t st = fileStamp("levelup_override.ini");
    if (st == g_cfgStamp) return;
    g_cfgStamp = st;
    Config c;
    char legacy[MaxTagCfg][32]; int nLegacy = 0;
    bool hasInstant[MaxTagCfg] = {}, hasHold[MaxTagCfg] = {};
    if (FILE* f = fopen("levelup_override.ini", "r")) {
        char line[512];
        while (fgets(line, sizeof line, f)) {
            char* l = trim(line);
            if (!*l || *l == ';' || *l == '#') continue;
            char* eq = strchr(l, '=');
            if (!eq) continue;
            *eq = 0;
            char* k = trim(l); char* v = trim(eq + 1);
            lower(k);
            if (!strcmp(k, "mode")) {
                lower(v);
                c.mode = !strcmp(v, "off") ? Mode::Off : !strcmp(v, "rewrite") ? Mode::Rewrite : Mode::Log;
            } else if (!strcmp(k, "verbose")) {
                c.verbose = atoi(v) != 0;
            } else if (!strcmp(k, "apply")) {
                c.apply = atoi(v) != 0;
            } else if (!strcmp(k, "table")) {
                snprintf(c.table, sizeof c.table, "%s", v);
            } else if (!strcmp(k, "tags")) {
                lower(v);
                for (char* t = strtok(v, ","); t && nLegacy < MaxTagCfg; t = strtok(nullptr, ",")) {
                    t = trim(t);
                    if (*t) snprintf(legacy[nLegacy++], 32, "%s", t);
                }
            } else if (!strncmp(k, "preset.", 7) && k[7]) {
                int i = cfgEntry(c, k + 7);
                if (i >= 0) { lower(v); snprintf(c.presetId[i], sizeof c.presetId[i], "%s", v); }
            } else if (!strncmp(k, "instant.", 8) && k[8]) {
                int i = cfgEntry(c, k + 8);
                if (i >= 0) { c.tags[i].instant = atoi(v) != 0; hasInstant[i] = true; }
            } else if (!strncmp(k, "hold.", 5) && k[5]) {
                int i = cfgEntry(c, k + 5);
                if (i >= 0) { c.tags[i].hold = atoi(v) != 0; hasHold[i] = true; }
            }
        }
        fclose(f);
    }
    // Legacy allow-list: a tag without a preset key behaves as in 0.2.1 (preset <tag>__live, no instant, no hold).
    for (int j = 0; j < nLegacy; ++j) {
        int i = cfgEntry(c, legacy[j]);
        if (i < 0 || c.presetId[i][0]) continue;
        snprintf(c.presetId[i], sizeof c.presetId[i], "%s__live", c.tags[i].tag);
        if (!hasInstant[i]) c.tags[i].instant = false;
        if (!hasHold[i]) c.tags[i].hold = false;
    }
    g_cfg = c;
    resolvePresets();
    Buf b;
    for (int i = 0; i < c.nTags; ++i) b.add("%s%s:%s/i%d/h%d", i ? "," : "", c.tags[i].tag, c.presetId[i][0] ? c.presetId[i] : "-", c.tags[i].instant, c.tags[i].hold);
    logLine("CONFIG %s mode=%s apply=%d verbose=%d table=%s tags=%s", st ? "loaded" : "missing (defaults)",
            c.mode == Mode::Off ? "off" : c.mode == Mode::Rewrite ? "rewrite" : "log", c.apply, c.verbose, c.table, b.s);
}

