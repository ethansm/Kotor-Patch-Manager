// True when CSWSCreatureStats::AutoLevelup (0x6BEDF0) is on the call chain: the engine chose the picks (Auto button, Auto Level Up
// NPCs, XP-award auto levels). Only those level-ups are rewritten; a player's manual GUI picks (and SetExperience replays of them) are kept.
bool viaAutoLevelup(uintptr_t ret, const uintptr_t* frames, int nFrames) {
    const Fn* d = findFn(ret);
    if (d && d->lo == 0x006BEDF0) return true;
    for (int i = 0; i < nFrames; ++i) {
        const Fn* f = findFn(frames[i]);
        if (f && f->lo == 0x006BEDF0) return true;
    }
    return false;
}

// Returns the flow name from the direct return address and the EBP chain (nearest frame that names a flow wins).
const char* classify(uintptr_t ret, const uintptr_t* frames, int nFrames) {
    const Fn* d = findFn(ret);
    if (d && d->flow) return d->flow;
    for (int i = 0; i < nFrames; ++i) {
        const Fn* f = findFn(frames[i]);
        if (f && f->flow) return f->flow;
    }
    for (int i = 0; i < nFrames; ++i) {
        const Fn* f = findFn(frames[i]);
        if (f && f->lo == 0x006BEDF0) return "auto-other";
    }
    return "unknown";
}

// Once per process, from whichever hook runs first (the gates run every frame, before the first LevelUp call).
void ensureHeader() {
    if (g_headerDone) return;
    g_headerDone = true;
    rotateIfLarge();
    logLine("== LevelUpOverride %s loaded; first hook call (build apply=%d) ==", Version, ApplyEnabled);
}

// The creature's class entries (engine order, newest last) and total level; false when unreadable or not 1..4 classes.
bool readClasses(uintptr_t stats, uint8_t* ids, uint8_t* lvls, int* n, int* total) {
    uint8_t cnt = 0;
    *n = 0; *total = 0;
    if (!readAt(S_Class, stats, St_ClassCount, &cnt) || cnt < 1 || cnt > 4) return false;
    for (int i = 0; i < cnt; ++i) {
        if (!readAt(S_Class, stats, St_ClassId + i * St_ClassStride, &ids[i]) || !readAt(S_Class, stats, St_ClassLevel + i * St_ClassStride, &lvls[i])) return false;
        *total += lvls[i];
    }
    *n = cnt;
    return true;
}

// Bit i set = the creature already has the Class Skill feat (183-189) of skill i (both creature feat lists, as HasFeat 0x6B83F0 checks).
uint8_t classSkillMask(uintptr_t stats) {
    uint8_t mask = 0;
    const int lists[2] = {St_FeatList, St_FeatList2};
    for (int L = 0; L < 2; ++L) {
        uint32_t fl = 0, fc = 0;
        if (!readAt(S_FeatList, stats, lists[L], &fl) || !readAt(S_FeatList, stats, lists[L] + 4, &fc) || !fl) continue;
        uint32_t take = fc > 200 ? 200 : fc;
        const uintptr_t a = fl;
        if (!take || !probeRead(S_FeatList, reinterpret_cast<const void*>(a), take * 2)) continue;
        for (uint32_t i = 0; i < take; ++i) {
            int sk = classSkillFeatSkill(reinterpret_cast<const uint16_t*>(a)[i]);
            if (sk >= 0) mask |= static_cast<uint8_t>(1u << sk);
        }
    }
    return mask;
}

void onLevelUp(uintptr_t stats, uintptr_t ret, uintptr_t pending, int addToList, uintptr_t ebp) {
    LONG call = InterlockedIncrement(&g_calls);
    ensureHeader();
    reloadConfig(true);
    if (g_cfg.mode == Mode::Off) return;
    reloadTable(true);
    if (!logOpen()) return;
    const bool v = g_cfg.verbose;

    // -- caller chain: EBP at hook time = LevelUp's caller frame; [ebp+4] = caller's return address
    uintptr_t frames[4]; int nFrames = 0;
    for (uintptr_t e = ebp; nFrames < 4;) {
        uintptr_t next = 0, r = 0;
        if (!readAt(S_Frame, e, 4, &r) || !readAt(S_Frame, e, 0, &next)) break;
        frames[nFrames++] = r;
        if (next <= e || next - e > 0x100000) break;
        e = next;
    }
    const char* flow = classify(ret, frames, nFrames);
    const bool viaAuto = viaAutoLevelup(ret, frames, nFrames);
    Buf chain;
    const Fn* rf = findFn(ret);
    chain.add("ret=%08x(%s)", (unsigned)ret, rf ? rf->name : "?");
    for (int i = 0; i < nFrames; ++i) {
        const Fn* f = findFn(frames[i]);
        chain.add(" <- %08x(%s)", (unsigned)frames[i], f ? f->name : "?");
    }

    // -- creature
    char tag[32];
    bool tagOk = readTag(stats, tag, sizeof tag);
    if (!tagOk) strcpy(tag, "?");
    uint8_t nClass = 0;
    int total = 0;
    uint8_t cIds[4] = {}, cLvls[4] = {};
    int nGot = 0;
    Buf cls;
    if (readAt(S_Class, stats, St_ClassCount, &nClass)) {
        if (nClass > 4) { cls.add("count=%u?", nClass); total = -1; nClass = 0; }
        for (int i = 0; i < nClass; ++i) {
            uint8_t id = 0, lv = 0, neg = 0;
            if (!readAt(S_Class, stats, St_ClassId + i * St_ClassStride, &id) || !readAt(S_Class, stats, St_ClassLevel + i * St_ClassStride, &lv) ||
                !readAt(S_Class, stats, St_ClassNeg + i * St_ClassStride, &neg)) { cls.add(" ?"); total = -1; break; }
            cIds[i] = id; cLvls[i] = lv; nGot = i + 1;
            cls.add("%s%u:%u%s", i ? "," : "", id, lv, neg ? "(neg)" : "");
            if (neg) cls.add("%u", neg);
            total += lv;
        }
    } else {
        total = -1;
    }
    uint32_t xp = 0; uint16_t stUnspent = 0;
    readAt(S_Stats, stats, St_XP, &xp);
    readAt(S_Stats, stats, St_Unspent, &stUnspent);

    uintptr_t rules = 0; uint8_t nSkills = 0;
    if (readAt(S_Rules, RulesGlobal, 0, &rules)) readAt(S_Rules, rules, Rules_SkillCount, &nSkills);
    if (nSkills > 32) nSkills = 32;

    // -- pending
    PendDump dp;
    readPend(pending, nSkills, &dp);
    int key = total >= 0 ? total + 1 : -1;

    logf("[%lu] #%ld tid=%lu flow=%s %s stats=%08x pending=%08x addToList=%d tag=%s classes=%s total=%d key=%d xp=%u unspent170=%u",
         GetTickCount(), call, GetCurrentThreadId(), flow, chain.s, (unsigned)stats, (unsigned)pending, addToList, tag, cls.s, total, key,
         xp, stUnspent);

    if (!dp.ok) { logf("  pending unreadable -> vanilla"); logClose(); return; }
    const Pend& pd = dp.pd;

    if (v) {
        logPend("pend", dp, nSkills);

        // creature skill ranks and feat list (before LevelUp applies anything)
        Buf r;
        uintptr_t ranksP = 0;
        r.add("  stats.ranks=[");
        if (readAt(S_Ranks, stats, St_SkillRanks, &ranksP) && nSkills && probeRead(S_Ranks, reinterpret_cast<const void*>(ranksP), nSkills))
            for (int i = 0; i < nSkills; ++i) r.add("%s%u", i ? "," : "", reinterpret_cast<const uint8_t*>(ranksP)[i]);
        else
            r.add("UNREADABLE");
        r.add("]");
        logf("%s", r.s);
        // feat lists: +0x00 full list, +0x18 second list (both {ushort*, count}; HasFeat 0x6B83F0 checks both)
        const int lists[2] = {St_FeatList, St_FeatList2};
        for (int L = 0; L < 2; ++L) {
            Buf fb;
            uintptr_t fl = 0; uint32_t fc = 0;
            fb.add("  stats.feats%s", L ? "2" : "");
            if (readAt(S_FeatList, stats, lists[L], &fl) && readAt(S_FeatList, stats, lists[L] + 4, &fc)) {
                uint32_t take = fc > 200 ? 200 : fc;
                fb.add(" count=%u [", fc);
                if (take && fl && probeRead(S_FeatList, reinterpret_cast<const void*>(fl), take * 2))
                    for (uint32_t i = 0; i < take; ++i) fb.add("%s%u", i ? "," : "", reinterpret_cast<const uint16_t*>(fl)[i]);
                fb.add("]");
            } else {
                fb.add(" UNREADABLE");
            }
            logf("%s", fb.s);
        }
    }

    // -- decision + dry run for tags configured with a preset; rewrite when mode=rewrite (auto level-ups only)
    const TagCfg* cfg = tagOk ? tagConfig(tag) : nullptr;
    const Preset* preset = cfg && cfg->preset >= 0 && g_tableOk ? &g_presets[cfg->preset] : nullptr;
    const bool rewriteTag = g_cfg.mode == Mode::Rewrite && preset;
    if (preset) {
        const Rec* rec = nullptr; int recLevel = -1;
        Decision dec = Decision::Vanilla;
        if (total >= 0 && nGot == nClass && nClass > 0) dec = levelNow(cIds, cLvls, nGot, preset, key, cfg->hold, &rec, &recLevel);
        const bool midloop = dec == Decision::Hold;   // the LevelUp hook can never veto: HOLD here = vanilla (engine picks)
        if (midloop) { rec = nullptr; recLevel = -1; }
        char recS[16]; if (recLevel >= 0) snprintf(recS, sizeof recS, "%d", recLevel); else strcpy(recS, "-");
        logf("  DECIDE tag=%s preset=%s key=%d decision=%s rec=%s", tag, preset->id, key, midloop ? "HOLD_MIDLOOP" : decisionName(dec), recS);
        const char* lt = preset->id;
        if (nSkills != NumSkills || !dp.deltasOk || !dp.featsOk || !dp.spellsOk || dp.fCnt > static_cast<uint32_t>(MaxPend) ||
            dp.sCnt > static_cast<uint32_t>(MaxPend)) {
            logf("  DRY tag=%s key=%d status=skipped-unreadable (skills=%u feats=%u spells=%u)", lt, key, nSkills, dp.fCnt, dp.sCnt);
            if (rewriteTag) logf("  SKIP skipped-unreadable %s key=%d - vanilla", lt, key);
        } else {
            Result res = computeRewrite(rec, pd, classSkillMask(stats));
            Buf d;
            formatDry(d, lt, key, res);
            logf("  %s", d.s);
            if (rewriteTag) {
                if (!viaAuto) {
                    logf("  SKIP manual %s key=%d flow=%s - player's picks kept (rewrite only under AutoLevelup)", lt, key, flow);
                } else if (!strcmp(res.status, "already")) {
                    logf("  ALREADY (replay) %s key=%d - no write", lt, key);
                } else if (strcmp(res.status, "rewrite")) {
                    logf("  SKIP %s %s key=%d - vanilla", res.status, lt, key);
                } else if (!ApplyEnabled || !g_cfg.apply) {
                    logf("  WOULD REWRITE %s key=%d (apply=0)", lt, key);
                } else if (applyRewrite(pending, pd, res, nSkills)) {
                    saferead::beginScope();   // the engine push helpers may have reallocated the arrays
                    PendDump after;
                    readPend(pending, nSkills, &after);
                    const bool ok = after.ok && after.featsOk && after.spellsOk && after.deltasOk && samePend(after.pd, res.p);
                    logf("  APPLIED tag=%s key=%d ok=%d", lt, key, ok);
                    logPend("after", after, nSkills);
                }
            }
        }
    } else if (cfg) {
        logf("  tag %s configured but preset %s not in table (table %s)", tag, g_cfg.presetId[cfg - g_cfg.tags], g_tableOk ? "ok" : "ERROR");
    }
    logClose();
}

// ---- gates (0.3.0-a): hold gate, instant gate, GUI guards, Auto OK backstop -------------------------------
// Every handler replaces a 5-byte `call rel32` (skip_original_bytes): it calls the real function itself and its return value becomes EAX.
// The handlers run every frame (hold gate) or on clicks (guards); they never write the log except on a state change.
constexpr int Cr_Stats = 0x1198;   // creature -> CSWSCreatureStats*
enum GateSite : unsigned { S_Opt = 100, S_Chain };
typedef int (__thiscall* CanLevelUp_t)(void* stats);
typedef void* (__thiscall* OptAccessor_t)(void* ecx);
typedef int (__thiscall* CharChange_t)(void* ecx);
typedef void* (__thiscall* GetCreature_t)(void* ecx);
typedef void* (__thiscall* PartyGet_t)(void* ecx, int idx);
typedef void* (__thiscall* TableGet_t)(void* ecx);

int g_engState = 0;   // 0 unchecked, 1 gate functions verified, 2 mismatch (all gates pass through)
bool engineOk() {
    if (!g_eng.checkCode) return true;
    if (!g_engState) {
        const bool ok = codeMatches(g_eng.canLevelUp, kCanLevelUpCode, sizeof kCanLevelUpCode) && codeMatches(g_eng.optAccessor, kOptAccessorCode, sizeof kOptAccessorCode) &&
                        codeMatches(g_eng.charChange, kCharChangeCode, sizeof kCharChangeCode) && codeMatches(g_eng.getCreature, kGetCreatureCode, sizeof kGetCreatureCode) &&
                        codeMatches(g_eng.partyGet, kPartyGetCode, sizeof kPartyGetCode) && codeMatches(g_eng.tableGet, kTableGetCode, sizeof kTableGetCode);
        g_engState = ok ? 1 : 2;
        if (!ok) logLine("ENGINE gate function bytes differ from the expected build - gates pass through (vanilla)");
    }
    return g_engState == 1;
}

// Common prologue: header, throttled config/table reload. False = pass through.
bool gateActive() {
    ensureHeader();
    reloadConfig();
    if (g_cfg.mode == Mode::Off) return false;
    reloadTable();
    return engineOk();
}

struct Eval {
    bool ok = false;            // tag readable, tag configured with a resolved preset, classes readable, decision valid
    char tag[32] = "";
    const TagCfg* cfg = nullptr;
    const Preset* p = nullptr;
    int key = 0;
    Decision d = Decision::Vanilla;
};
// creature may be 0 (tag then via stats+0x24); when given, its own +0x18 tag is tried first.
Eval evalStats(uintptr_t stats, uintptr_t creature) {
    Eval e;
    if (!stats) return e;
    if (!((creature && readCreatureTag(creature, e.tag, sizeof e.tag)) || readTag(stats, e.tag, sizeof e.tag))) return e;
    e.cfg = tagConfig(e.tag);
    if (!e.cfg || e.cfg->preset < 0 || !g_tableOk) return e;
    e.p = &g_presets[e.cfg->preset];
    uint8_t ids[4], lv[4]; int n, total;
    if (!readClasses(stats, ids, lv, &n, &total)) return e;
    e.key = total + 1;
    e.d = levelNow(ids, lv, n, e.p, e.key, e.cfg->hold, nullptr, nullptr);
    e.ok = true;
    return e;
}

// Log-on-change state (never per frame).
struct HoldState { char tag[32]; bool held; int key; };
HoldState g_holdState[MaxTagCfg];
int g_nHoldState = 0;
void noteHold(const char* tag, int key, bool held, unsigned site, bool real) {
    HoldState* s = nullptr;
    for (int i = 0; i < g_nHoldState; ++i) if (!_stricmp(g_holdState[i].tag, tag)) s = &g_holdState[i];
    if (!s) {
        if (g_nHoldState >= MaxTagCfg) return;
        s = &g_holdState[g_nHoldState++];
        snprintf(s->tag, sizeof s->tag, "%s", tag);
        s->held = false; s->key = 0;
    }
    if (held && (!s->held || s->key != key)) logLine("%s tag=%s key=%d site=0x%X", real ? "HOLD" : "WOULD HOLD", tag, key, site);
    else if (!held && s->held) logLine("UNHOLD tag=%s", tag);
    s->held = held; s->key = key;
}

int holdGate(unsigned site, void* stats) {
    saferead::beginScope();
    const int r = reinterpret_cast<CanLevelUp_t>(g_eng.canLevelUp)(stats);
    if (!r || !gateActive()) return r;
    Eval e = evalStats(reinterpret_cast<uintptr_t>(stats), 0);
    if (!e.ok) return r;
    const bool held = e.d == Decision::Hold, real = g_cfg.mode == Mode::Rewrite;
    noteHold(e.tag, e.key, held, site, real);
    return held && real ? 0 : r;
}

struct InstantKey { char tag[32]; int key; };
InstantKey g_instSeen[32];
int g_nInstSeen = 0, g_instNext = 0;
uint8_t g_instBuf[16];   // options copy handed back to the engine (read-only use: [p+8] & 1)

void* instantGate(unsigned site, int ebpOff, void* ecx, uintptr_t ebp) {
    saferead::beginScope();
    void* const p = reinterpret_cast<OptAccessor_t>(g_eng.optAccessor)(ecx);
    if (!p || !gateActive() || g_cfg.mode != Mode::Rewrite) return p;
    uint32_t cr = 0, stats = 0, flags = 0;
    if (!readAt(S_Chain, ebp, ebpOff, &cr) || !cr || !readAt(S_Stats, cr, Cr_Stats, &stats) || !stats) return p;
    Eval e = evalStats(stats, cr);
    if (!e.ok || !e.cfg->instant || e.d == Decision::Hold) return p;
    const uintptr_t pa = reinterpret_cast<uintptr_t>(p);
    if (!readAt(S_Opt, pa, 8, &flags) || (flags & 1) || !probeRead(S_Opt, p, sizeof g_instBuf)) return p;
    memcpy(g_instBuf, p, sizeof g_instBuf);
    g_instBuf[8] |= 1;
    bool seen = false;
    for (int i = 0; i < g_nInstSeen; ++i) if (g_instSeen[i].key == e.key && !_stricmp(g_instSeen[i].tag, e.tag)) seen = true;
    if (!seen) {
        InstantKey& k = g_instSeen[g_nInstSeen < 32 ? g_nInstSeen++ : (g_instNext++ & 31)];
        snprintf(k.tag, sizeof k.tag, "%s", e.tag); k.key = e.key;
        logLine("INSTANT tag=%s key=%d site=0x%X", e.tag, e.key, site);
    }
    return g_instBuf;
}

// Leader creature as the GUI sees it: 0x77D800(0x7E5DA0(0x73FB90([[0xA1B4A4]+4]), 0)); 0 on any null / unreadable link.
uintptr_t leaderCreature() {
    uint32_t app = 0, client = 0;
    if (!readAt(S_Chain, g_eng.appGlobal, 0, &app) || !app || !readAt(S_Chain, app, 4, &client) || !client) return 0;
    void* party = reinterpret_cast<TableGet_t>(g_eng.tableGet)(reinterpret_cast<void*>(static_cast<uintptr_t>(client)));
    if (!party) return 0;
    void* member = reinterpret_cast<PartyGet_t>(g_eng.partyGet)(party, 0);
    if (!member) return 0;
    return reinterpret_cast<uintptr_t>(reinterpret_cast<GetCreature_t>(g_eng.getCreature)(member));
}
// Held (hold enabled + rule says HOLD) evaluation of a creature object.
Eval evalCreature(uintptr_t cr) {
    uint32_t stats = 0;
    if (!cr || !readAt(S_Stats, cr, Cr_Stats, &stats)) return Eval();
    return evalStats(stats, cr);
}

int g_probeLines = 0;
int guiGuard(unsigned site, const char* what, void* ecx) {
    saferead::beginScope();
    const int r = reinterpret_cast<CharChange_t>(g_eng.charChange)(ecx);
    if (r || !gateActive()) return r;
    const uintptr_t cr = leaderCreature();
    uint32_t stats = 0;
    if (cr) readAt(S_Stats, cr, Cr_Stats, &stats);
    Eval e = evalStats(stats, cr);
    if (g_probeLines < 300) {   // the tag offset on this path is unverified: log what each route reads on every trigger (clicks, not frames)
        ++g_probeLines;
        char tc[32] = "", ts[32] = "";
        const bool okC = cr && readCreatureTag(cr, tc, sizeof tc);
        const bool okS = stats && readTag(stats, ts, sizeof ts);
        logLine("GUARD-PROBE %s site=0x%X leader=%08x stats=%08x tagCreature=%s tagStats=%s decision=%s", what, site, (unsigned)cr, (unsigned)stats,
                okC ? tc : "?", okS ? ts : "?", e.ok ? decisionName(e.d) : "n/a");
    }
    if (e.ok && e.d == Decision::Hold && g_cfg.mode == Mode::Rewrite) {
        logLine("GUARD %s tag=%s key=%d site=0x%X", what, e.tag, e.key, site);
        return 1;
    }
    return r;
}

void* autoOkBackstop(void* ecx) {
    saferead::beginScope();
    void* const c = reinterpret_cast<GetCreature_t>(g_eng.getCreature)(ecx);
    if (!c || !gateActive()) return c;
    Eval e = evalCreature(reinterpret_cast<uintptr_t>(c));
    if (e.ok && e.d == Decision::Hold && g_cfg.mode == Mode::Rewrite) {
        logLine("GUARD autook tag=%s key=%d site=0x850062", e.tag, e.key);
        return nullptr;
    }
    return c;
}

