// Textures: a CAurTextureBasic registered under our name (like the engine's own "NormCubeMap") with the decoded pixels already in place
// and +0xE4 "constructed" set, so the engine never asks the resource manager for it; the texture tick uploads it and frees the buffer.
constexpr uintptr_t FnTexBasicCtor = 0x00423000;    // CAurTextureBasic ctor thiscall(this 0xF4 B, name, name) RET 8; registers the name globally
constexpr uintptr_t FnEngineMalloc = 0x0091D288;    // engine operator new[]: FreeImage (0x00421C40) releases +0x44 with delete[] when +0xE7 == 0
constexpr uintptr_t FnTexListAdd = 0x004491C0, TexPendingList = 0x00A1BC2C;   // pending-build list, consumed by the texture tick
constexpr uintptr_t FnTexReset = 0x00423990;        // CAurTextureBasic::Reset fastcall(basic)
constexpr int TexBasicSize = 0xF4;
constexpr int Tex_Pixels = 0x44, Tex_MipBytes = 0x5C, Tex_W = 0x68, Tex_H = 0x6C, Tex_Bpp = 0x74, Tex_Format = 0x78;
constexpr int Tex_Cube = 0xDF, Tex_Constructed = 0xE4, Tex_Missing = 0xE5, Tex_FromRes = 0xE7, Tex_Tpc = 0xE9;
constexpr int TexCount = sizeof EmbeddedTextures / sizeof EmbeddedTextures[0];
struct EmbTex { unsigned char* basic = nullptr; int w = 0, h = 0, heals = 0; };
EmbTex g_tex[TexCount]; bool g_texInit = false;

bool fillTexture(int i, const char* why) {
    const EmbeddedTexture& src = EmbeddedTextures[i]; EmbTex& t = g_tex[i]; const unsigned char* d = src.data;
    if (src.size < 18 || d[1] != 0 || d[2] != 2 || d[16] != 32) { logf("tex %s: embedded TGA not uncompressed 32-bit, skipped", src.resref); return false; }
    int w = d[12] | d[13] << 8, h = d[14] | d[15] << 8; unsigned off = 18u + d[0], n = (unsigned)w * h * 4;
    if (w <= 0 || h <= 0 || off + n > src.size) { logf("tex %s: embedded TGA truncated (%dx%d, %u bytes)", src.resref, w, h, src.size); return false; }
    unsigned char* px = static_cast<unsigned char*>(reinterpret_cast<NewFn>(FnEngineMalloc)(n));
    if (!px) { logf("tex %s: engine malloc(%u) failed", src.resref, n); return false; }
    for (unsigned j = 0; j < n; j += 4) { px[j] = d[off + j + 2]; px[j + 1] = d[off + j + 1]; px[j + 2] = d[off + j]; px[j + 3] = d[off + j + 3]; }   // BGRA -> RGBA, rows as stored (= CResTGA)
    unsigned char* b = t.basic;
    *reinterpret_cast<unsigned char**>(b + Tex_Pixels) = px;
    *reinterpret_cast<int*>(b + Tex_W) = w; *reinterpret_cast<int*>(b + Tex_H) = h; *reinterpret_cast<int*>(b + Tex_Bpp) = 4;
    *reinterpret_cast<int*>(b + Tex_Format) = 0; *reinterpret_cast<int*>(b + Tex_MipBytes) = 0;
    b[Tex_Cube] = 0; b[Tex_FromRes] = 0; b[Tex_Tpc] = 0; b[Tex_Missing] = 0; b[Tex_Constructed] = 1;
    reinterpret_cast<PtrListAddFn>(FnTexListAdd)(reinterpret_cast<void*>(TexPendingList), b);
    t.w = w; t.h = h;
    logf("tex %s: %s, %dx%d RGBA queued for upload (basic %p, pending %d)", src.resref, why, w, h, (void*)b, rdInt(TexPendingList, 4));
    return true;
}
void ensureTextures() {   // once per process; the textures outlive every HUD (never freed)
    if (g_texInit) return;
    g_texInit = true;
    for (int i = 0; i < TexCount; ++i) {
        unsigned char* b = static_cast<unsigned char*>(reinterpret_cast<NewFn>(FnNew)(TexBasicSize));
        if (!b) { logf("tex %s: allocation failed", EmbeddedTextures[i].resref); continue; }
        memset(b, 0, TexBasicSize);
        reinterpret_cast<void*(__thiscall*)(void*, const char*, const char*)>(FnTexBasicCtor)(b, EmbeddedTextures[i].resref, EmbeddedTextures[i].resref);
        g_tex[i].basic = b;
        if (fillTexture(i, "created")) imageFor(EmbeddedTextures[i].resref);   // a pooled GUI handle that is never released keeps the texture alive
    }
}
void logTextures(const char* when) {
    for (int i = 0; i < TexCount; ++i) if (unsigned char* b = g_tex[i].basic)
        logf("tex %s (%s): gl=%u constructed=%d missing=%d pixels=%p %dx%d", EmbeddedTextures[i].resref, when, (unsigned)rdInt(reinterpret_cast<uintptr_t>(b), 0x58),
             (int)b[Tex_Constructed], (int)b[Tex_Missing], *reinterpret_cast<void**>(b + Tex_Pixels), *reinterpret_cast<int*>(b + Tex_W), *reinterpret_cast<int*>(b + Tex_H));
}
// A GL reset (ResetAll 0x00427D90 / SetMem 0x00427DE0) Resets every registered texture (+0xE4 = 0, pixels and GL names freed) and
// re-queues all of them on the work list. If we see it first, refill (the duplicate list entry is a no-op: +0xE4 = 1, +0x44 = NULL after
// the first build). If the engine rebuilt first, its resource lookup missed our name (+0xE5 = 1): Reset and refill. DB lesson 290.
void healTextures() {
    for (int i = 0; i < TexCount; ++i) {
        EmbTex& t = g_tex[i]; unsigned char* b = t.basic;
        if (!b) continue;
        bool built = b[Tex_Constructed] != 0; void* px = *reinterpret_cast<void**>(b + Tex_Pixels); int w = *reinterpret_cast<int*>(b + Tex_W);
        if (built && !px && !b[Tex_Missing] && rdInt(reinterpret_cast<uintptr_t>(b), 0x58)) { t.heals = 0; continue; }   // uploaded: healthy
        if (t.heals >= 20) continue;   // give up after 20 consecutive failed refills (art missing, labels still work)
        if (!built && !px) { ++t.heals; fillTexture(i, "refilled after a texture reset"); }
        else if (built && !px && (b[Tex_Missing] || w != t.w)) {
            ++t.heals; logf("tex %s: rebuilt without our pixels (missing=%d w=%d), resetting", EmbeddedTextures[i].resref, (int)b[Tex_Missing], w);
            reinterpret_cast<void(__fastcall*)(void*)>(FnTexReset)(b);
            fillTexture(i, "refilled after a missing rebuild");
        }
    }
}

