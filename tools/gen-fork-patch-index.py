#!/usr/bin/env python3
"""Build docs/FORK_PATCHES.md, the index of the patches this fork adds, from each patch's
manifest.toml and README STATUS banner.

A fork patch is one whose manifest author is in FORK_AUTHORS. Run from the repo root:
    python3 tools/gen-fork-patch-index.py           # rewrite docs/FORK_PATCHES.md
    python3 tools/gen-fork-patch-index.py --check   # exit 1 if the file is out of date
"""
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PATCHES = ROOT / "Patches"
OUT = ROOT / "docs" / "FORK_PATCHES.md"
FORK_AUTHORS = {"ethansm", "local"}

# Section order. Patches not named here go to Providers (kind = "provider") or Other.
SECTIONS = {
    "HUD and menus": ["ActionHotbar", "CombatHotbar", "QueueHud", "BuffDurationHud", "ShieldBar",
                      "CharacterEffectsPanel", "EnemyEffectsStrip", "LevelUpOverride", "RichMenuTypography",
                      "K2EquipIconFix", "K2DialogueLetterboxFix", "K2WrapMeasureFix"],
    "Inventory, items and equipment": ["InventorySortFilter", "QuickLoot", "Inventory3dViewport",
                                       "Equipment3dCharacter", "WorkbenchUpgrade", "K2Holster"],
    "Companions, AI and NPCs": ["CompanionAI", "CompanionSelfHeal", "RangedAI", "NpcDiversity", "CharacterPacks"],
    "Rendering and performance": ["K2FogDistance", "K2GrassDrawDistance", "K2ShadowDistance", "K2FramePacing",
                                  "K2EnginePerf", "K2TextureMemoryRelease"],
    "Engine and input fixes": ["K2ActivationFix", "K2EbonHawkAreaScriptFix", "K2RobustnessFixes", "MouseProbe"],
    "Providers": [],
    "Diagnostics and probes": ["AreaHookProbe", "CmdqProbe", "K1SpawnProbe", "LoadHangProbe", "NpcWorldProbe",
                               "PerfLab", "VoiceProbe"],
    "Other": [],
}
BUILDS = {
    "kotor2_steam_aspyr": "Steam", "kotor2_gog_aspyr": "GOG", "kotor2_steam_aspyr_linux": "Steam Linux",
    "kotor2_steam_aspyr_macos": "Steam macOS", "kotor1_steam_103": "K1 Steam", "kotor1_gog_103": "K1 GOG",
    "kotor1_cdcrack_103": "K1 CD", "kotor1_steam_aspyr_macos": "K1 macOS",
}
BLURB_MAX = 220
# Track for patches whose README has no STATUS banner (written in the upstream PR style).
TRACK_FALLBACK = {"K2EbonHawkAreaScriptFix": "Shippable", "K2TextureMemoryRelease": "Shippable"}


def banner(readme: Path, key: str) -> str:
    if not readme.exists():
        return ""
    m = re.search(rf"^> \*\*{re.escape(key)}:?\*\*:? ?(.*)$", readme.read_text(encoding="utf-8"), re.M)
    return m.group(1).strip() if m else ""


def first_sentence(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    m = re.match(r"(.{40,}?[.!?])(\s|$)", text)  # at least 40 chars, so "Infrastructure provider." takes the next sentence too
    s = m.group(1) if m else text
    if len(s) > BLURB_MAX:
        s = s[:BLURB_MAX].rsplit(" ", 1)[0].rstrip(",;:") + "..."
    return s.replace("|", "\\|")


def collect():
    by_id, rows = {}, []
    for d in sorted(p for p in PATCHES.iterdir() if (p / "manifest.toml").exists()):
        with open(d / "manifest.toml", "rb") as f:
            m = tomllib.load(f)["patch"]
        by_id[m.get("id", "")] = d.name
        if m.get("author", "") not in FORK_AUTHORS:
            continue
        readme = d / "README.md"
        track = re.match(r"([A-Z-]+)", banner(readme, "STATUS") .removeprefix("Track: ") or "")
        what = banner(readme, "What it does / explores") or m.get("description", "")
        rows.append({
            "dir": d.name, "name": m.get("name", d.name), "id": m.get("id", ""), "version": m.get("version", "?"),
            "kind": m.get("kind", "patch"), "track": track.group(1).title() if track else TRACK_FALLBACK.get(d.name, ""),
            "what": first_sentence(what), "requires": m.get("requires", []),
            "builds": [BUILDS.get(k, k) for k in m.get("supported_versions", {})],
        })
    return rows, by_id


def section_of(row):
    for sec, names in SECTIONS.items():
        if row["dir"] in names:
            return sec
    return "Providers" if row["kind"] == "provider" else "Other"


def render(rows, by_id):
    L = ["# Patches added in this fork", "",
         "<!-- Generated by tools/gen-fork-patch-index.py from each patch's manifest.toml and README STATUS banner."
         " Do not edit by hand: change the patch, then re-run the script. -->", "",
         f"This fork ([ethansm/Kotor-Patch-Manager](https://github.com/ethansm/Kotor-Patch-Manager)) adds {len(rows)} patches"
         " on top of upstream [LaneDibello/Kotor-Patch-Manager](https://github.com/LaneDibello/Kotor-Patch-Manager)."
         " Almost all of them target KOTOR II (Steam/Aspyr); the GOG builds are mostly address-mapped but not played.", "",
         "Each patch folder has a README with a STATUS banner (track, version, requirements, known limits, install notes)."
         " Read it before installing.", "",
         "**Tracks:** *Shippable* is meant for normal play. *Experimental* works but is still changing or has open issues."
         " *Diagnostic* is a probe or measurement build: don't install it for normal play.", "",
         "**Providers** are shared libraries that other patches build on (`requires`). KPM installs them like any patch;"
         " install a provider before the patches that need it.", ""]
    counts = {}
    for r in rows:
        counts[r["track"] or "Unlabelled"] = counts.get(r["track"] or "Unlabelled", 0) + 1
    L += ["| Track | Patches |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(counts.items())] + [""]
    for sec in SECTIONS:
        group = [r for r in rows if section_of(r) == sec]
        if not group:
            continue
        L += [f"## {sec}", "", "| Patch | What it does | Track | Version | Requires | Builds |", "|---|---|---|---|---|---|"]
        for r in sorted(group, key=lambda r: r["name"].lower()):
            req = ", ".join(f"[{by_id.get(x, x)}](../Patches/{by_id[x].replace(' ', '%20')}/)" if x in by_id else f"`{x}`"
                            for x in r["requires"]) or "none"
            link = f"[{r['name']}](../Patches/{r['dir'].replace(' ', '%20')}/README.md)"
            L.append(f"| {link} | {r['what']} | {r['track'] or 'see README'} | {r['version']} | {req} | {', '.join(r['builds'])} |")
        L.append("")
    return "\n".join(L)


def main():
    rows, by_id = collect()
    text = render(rows, by_id)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tools/gen-fork-patch-index.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date ({len(rows)} patches)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} patches)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
