#!/usr/bin/env python3
"""R10 PC level-up filter: feat/power TAG TABLE generator (doc 25 sections 2 + 11). OFFLINE: reads feat/spells 2DA + TLK of the
live install via levelup_rules.py (read-only). Rules are documented in r10/README.md.

  python3 r10/gen_r10_tags.py            write runtime/r10_tags.ini
  python3 r10/gen_r10_tags.py --check    regenerate in memory, diff vs ini, coverage + preset-fit check (exit 0 only if clean)
  python3 r10/gen_r10_tags.py --selftest line format / sorting / fits rule (no game files needed)
Run from research/companion_levelup with ../../.venv/bin/python3.
"""
import glob
import os
import re
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
INI = os.path.join(ROOT, "runtime", "r10_tags.ini")
OVR = os.path.join(HERE, "tag_overrides.toml")
PRESETS = os.path.join(ROOT, "paths", "presets", "*.toml")

ROLE = ["melee", "ranged", "caster", "support", "tank"]
STYLE = ["single", "dual", "double", "unarmed", "pistols", "rifle"]
ALIGN = ["light", "dark", "neutral"]
OTHER = ["general", "force", "combat"]
VOCAB = ROLE + STYLE + ALIGN + OTHER
HEADER = "; generated by r10/gen_r10_tags.py -- do not edit; overrides in r10/tag_overrides.toml"

# feat.2da class-list columns (<abbr>_list): 0/1 = selectable by that class (levelup_rules.CLASS_ABBR + prestige + NPC classes)
FEAT_LIST_COLS = ["scd", "sol", "sct", "jcn", "jgd", "jsn", "sas", "sld", "sma", "jwa", "jma", "jwm", "tec", "drx", "drc"]
# spells.2da per-class minimum-level columns; -1 = class cannot learn it, 99 = never selectable
SPELL_CLASS_COLS = ["guardian", "consular", "sentinel", "weapmstr", "jedimaster", "watchman", "marauder", "sithlord", "assassin"]

RANGED_ALL = ["ranged", "pistols", "rifle", "combat"]
MELEE_STYLES = ["melee", "single", "dual", "double", "combat"]

# ordered first-match-wins label rules for FEATS: (rule id, regex on feat.2da label, tags)
FEAT_RULES = [
    ("F1 jedi-defense", r"^(ADVANCED_|MASTER_)?JEDI_DEFENSE$", ["melee", "tank", "combat"]),
    ("F2 two-weapon", r"^TWO_WEAPON_|^SUPER_WEAPON_FOCUS_2_WEAPON", ["melee", "dual", "pistols", "combat"]),
    ("F3 dual-strike", r"DUAL_STRIKE$", ["melee", "dual", "combat"]),
    ("F4 armour-prof", r"^ARMOUR_PROF_", ["melee", "ranged", "tank", "support", "combat"]),
    ("F5 melee-feats", r"^(IMPROVED_|MASTER_)?(CRITICAL_STRIKE|POWER_ATTACK|FLURRY)$|^WHIRLWIND_ATTACK$", ["melee", "tank", "combat"]),
    ("F6 ranged-feats", r"^(IMPROVED_|MASTER_)?(POWER_BLAST|SNIPER_SHOT|RAPID_SHOT)$|^MULTI_SHOT$|PRECISE_SHOT_|^(IMPROVED_)?CLOSE_COMBAT$",
     RANGED_ALL),
    ("F7 blaster-rifle", r"^WEAPON_(FOCUS|PROF|SPEC)_BLASTER_RIFLE$", ["ranged", "rifle", "combat"]),
    ("F8 blaster-pistol", r"^WEAPON_(FOCUS|PROF|SPEC)_BLASTER$", ["ranged", "pistols", "combat"]),
    ("F9 saber/melee-weapon", r"^WEAPON_(FOCUS|PROF|SPEC)_(LIGHTSABER|MELEE_WEAPONS)$|^FINESSE_|^SUPER_WEAPON_FOCUS_LIGHTSABER",
     MELEE_STYLES),
    ("F10 dueling", r"DUELING$", ["melee", "single", "combat"]),
    ("F11 force-feats", r"^REGENERATE_FORCE_POINTS$|^(XXXX_)?FORCE_", ["force", "caster", "support"]),
    ("F12 passive/skill", r"CONDITIONING$|TOUGHNESS$|CAUTION$|^CAUTIOUS$|EMPATHY$|^GEAR_HEAD|^CLASS_SKILL_|MOBILITY$|^REGENERATE_VITALITY|^STEALTH_RUN$",
     ["general"]),
]

# POWERS: every Force power is tagged force + ALL five roles + alignment(goodevil). Reason (found by the preset check, 2026-10-04):
# the 80 companion presets give melee/ranged/tank builds the same offensive and control powers as casters (Choke, Wound, Stun, Speed,
# Suppress Force ...), so any Force-using build can take any power and ONLY alignment narrows the power list. The label rules below were
# tried as role narrowing and produced hundreds of preset conflicts; they are kept as documentation of the dropped idea (POWER_ROLE_NARROWING).
POWER_ROLE_NARROWING = False
POWER_ADD_RULES = []


def canon(tags):
    s = set(tags)
    bad = s - set(VOCAB)
    if bad:
        raise ValueError("unknown tags %s" % sorted(bad))
    return [t for t in VOCAB if t in s]


def format_ini(feats, powers):
    """feats/powers: {id: [tags]} -> deterministic ini text (ids ascending numeric, canonical tag order, LF, ASCII)."""
    out = [HEADER, "[feats]"]
    out += ["%d=%s" % (i, ",".join(canon(feats[i]))) for i in sorted(feats)]
    out.append("[powers]")
    out += ["%d=%s" % (i, ",".join(canon(powers[i]))) for i in sorted(powers)]
    txt = "\n".join(out) + "\n"
    txt.encode("ascii")
    assert all(len(l) <= 200 for l in txt.split("\n"))
    return txt


def parse_ini(txt):
    sec, d = None, {"feats": {}, "powers": {}}
    for ln in txt.split("\n"):
        if not ln or ln.startswith(";"):
            continue
        if ln.startswith("["):
            sec = ln.strip("[]")
        else:
            k, v = ln.split("=", 1)
            d[sec][int(k)] = v.split(",") if v else []
    return d


def fits(tags, role, style, alignment):
    """THE FILTER RULE (must match the C++ filter): a row FITS a build when it has `general`, or (any role tag == build.role or any
    style tag == build.style) AND its alignment tag is not opposite to build.alignment (light<->dark only; neutral/untagged never conflict)."""
    t = set(tags)
    if "general" in t:
        return True
    if not ((role in t) or (style in t)):
        return False
    if "light" in t and alignment == "dark":
        return False
    if "dark" in t and alignment == "light":
        return False
    return True


# ---------------------------------------------------------------- game data
def load_rules():
    sys.path.insert(0, ROOT)
    from levelup_rules import Rules
    fd = os.dup(2)
    dn = os.open(os.devnull, os.O_WRONLY)
    os.dup2(dn, 2)  # pykotor is very chatty on stderr
    try:
        return Rules()
    finally:
        os.dup2(fd, 2)
        os.close(fd)
        os.close(dn)


def _num(s, d=None):
    try:
        return int(s)
    except (ValueError, TypeError):
        return d


def selectable_feats(r):
    """feat rows with a non-empty label and feat.2da <cls>_list in (0,1) for at least one of FEAT_LIST_COLS."""
    out = []
    for i in range(r.feat.get_height()):
        lab = r.cell(r.feat, i, "label")
        if not lab or lab == "****":
            continue
        if any(r.cell(r.feat, i, c + "_list") in ("0", "1") for c in FEAT_LIST_COLS):
            out.append(i)
    return out


def selectable_powers(r):
    """spells.2da rows with usertype==1 (Force power), non-empty label, and some class column in 0..98 (-1 = unlearnable, 99 = never)."""
    out = []
    for i in range(r.spells.get_height()):
        lab = r.cell(r.spells, i, "label")
        if not lab or lab == "****" or r.cell(r.spells, i, "usertype") != "1":
            continue
        if any(0 <= _num(r.cell(r.spells, i, c), -1) <= 98 for c in SPELL_CLASS_COLS):
            out.append(i)
    return out


def feat_tags(label):
    for _rid, rx, tags in FEAT_RULES:
        if re.search(rx, label, re.I):
            return list(tags)
    return []


def power_tags(r, i):
    lab = r.cell(r.spells, i, "label")
    t = ["force"] + ROLE
    t.append({"G": "light", "E": "dark"}.get(r.cell(r.spells, i, "goodevil"), "neutral"))
    for _rid, rx, add in POWER_ADD_RULES:
        if re.search(rx, lab, re.I):
            t += add
    return t


def load_overrides():
    with open(OVR, "rb") as f:
        d = tomllib.load(f)
    return d.get("feat", []), d.get("power", [])


def load_waivers():
    with open(OVR, "rb") as f:
        w = tomllib.load(f).get("preset_waiver", [])
    for x in w:
        if not x.get("reason"):
            raise SystemExit("preset_waiver %s lacks a reason" % x.get("preset"))
    return {(x["preset"], x["kind"]): x["reason"] for x in w}


def apply_overrides(tab, ovs, kind):
    n = 0
    for o in ovs:
        i = o["id"]
        if i not in tab:
            raise SystemExit("override %s %d not in selectable scope" % (kind, i))
        if not o.get("reason"):
            raise SystemExit("override %s %d lacks a reason" % (kind, i))
        t = list(o["set"]) if "set" in o else list(tab[i])
        t += o.get("add", [])
        t = [x for x in t if x not in o.get("remove", [])]
        tab[i] = canon(t)
        n += 1
    return n


def generate(r):
    feats = {i: feat_tags(r.cell(r.feat, i, "label")) for i in selectable_feats(r)}
    powers = {i: power_tags(r, i) for i in selectable_powers(r)}
    fo, po = load_overrides()
    n = apply_overrides(feats, fo, "feat") + apply_overrides(powers, po, "power")
    feats = {i: canon(t) for i, t in feats.items()}
    powers = {i: canon(t) for i, t in powers.items()}
    return feats, powers, n


def preset_builds():
    for f in sorted(glob.glob(PRESETS)):
        d = tomllib.load(open(f, "rb"))
        w = d["meta"].get("wizard", {})
        F, P = set(), set()
        for lv in d.get("level", []):
            F.update(lv.get("feats", []))
            P.update(lv.get("powers", []))
        yield os.path.basename(f), w.get("role", ""), w.get("style", ""), w.get("alignment", ""), F, P


def check(r):
    feats, powers, n = generate(r)
    txt = format_ini(feats, powers)
    bad = 0
    try:
        cur = open(INI, "rb").read().decode("ascii")
    except OSError:
        cur = None
    if cur != txt:
        print("STALE: runtime/r10_tags.ini differs from regenerated output (run without --check)")
        bad += 1
    for kind, tab in (("feat", feats), ("power", powers)):
        for i, t in sorted(tab.items()):
            if not t:
                print("UNTAGGED %s %d %s" % (kind, i, r.cell(r.feat if kind == "feat" else r.spells, i, "label")))
                bad += 1
    conflicts = waived = 0
    waivers = load_waivers()
    for name, role, style, al, F, P in preset_builds():
        for kind, ids, tab, tbl in (("feat", F, feats, r.feat), ("power", P, powers, r.spells)):
            for i in sorted(ids):
                if i not in tab:
                    print("OUT-OF-SCOPE %s %d %s taken by %s" % (kind, i, r.cell(tbl, i, "label"), name))
                    conflicts += 1
                elif not fits(tab[i], role, style, al):
                    if (name, kind) in waivers:
                        waived += 1
                        continue
                    print("CONFLICT %s %d %s [%s] vs %s (%s/%s/%s)" % (kind, i, r.cell(tbl, i, "label"), ",".join(tab[i]), name, role, style, al))
                    conflicts += 1
    print("--check %s: feats %d/%d tagged, powers %d/%d tagged, conflicts %d, overrides %d, waived %d" % (
        "PASS" if not bad and not conflicts else "FAIL",
        sum(1 for t in feats.values() if t), len(feats), sum(1 for t in powers.values() if t), len(powers), conflicts, n, waived))
    return 0 if not bad and not conflicts else 1


def selftest():
    t = format_ini({5: ["combat", "melee", "general"], 11: ["tank"], 2: ["ranged"]}, {9: ["dark", "caster", "force"], 3: ["light", "support"]})
    assert t == (HEADER + "\n[feats]\n2=ranged\n5=melee,general,combat\n11=tank\n[powers]\n3=support,light\n9=caster,dark,force\n"), t
    assert parse_ini(t)["feats"][5] == ["melee", "general", "combat"]
    assert t.isascii() and "\r" not in t
    assert fits(["general"], "tank", "none", "dark")
    assert fits(["melee", "dark"], "melee", "dual", "dark") and not fits(["melee", "dark"], "melee", "dual", "light")
    assert fits(["caster", "light"], "caster", "none", "neutral") and fits(["caster", "neutral"], "caster", "none", "dark")
    assert fits(["pistols"], "ranged", "pistols", "none") and not fits(["pistols"], "ranged", "rifle", "none")
    assert not fits(["force", "combat"], "melee", "single", "light")
    assert not fits([], "melee", "single", "light")
    try:
        canon(["bogus"])
        raise SystemExit("canon accepted bogus tag")
    except ValueError:
        pass
    print("selftest PASS")


def main(argv):
    if "--selftest" in argv:
        return selftest() or 0
    r = load_rules()
    if "--check" in argv:
        return check(r)
    feats, powers, n = generate(r)
    with open(INI, "w", newline="\n") as f:
        f.write(format_ini(feats, powers))
    print("wrote %s: %d feats, %d powers, %d overrides" % (INI, len(feats), len(powers), n))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
